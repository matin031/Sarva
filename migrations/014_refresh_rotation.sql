-- چرخشِ refresh token با تشخیصِ استفادهٔ مجدد.
--
-- ⚠️ مشکلی که حل می‌کند: تا امروز refresh token هرگز چرخانده نمی‌شد. همان
-- رشته‌ای که هنگام ورود ساخته می‌شد، سی روز تمام معتبر می‌ماند. یعنی اگر یک
-- بار از دستگاه کاربر بیرون می‌رفت (بکاپِ مرورگر، افزونهٔ آلوده، دسترسی
-- فیزیکی)، مهاجم سی روز دسترسی داشت و هیچ ردی نمی‌گذاشت: نه کاربر می‌فهمید،
-- نه ما. لیستِ «دستگاه‌های فعال» هم چیز تازه‌ای نشان نمی‌داد، چون سشن همان
-- سشنِ خودِ کاربر بود.
--
-- با چرخش، هر تازه‌سازی توکنِ قبلی را می‌سوزاند. اگر توکنِ سوخته دوباره
-- استفاده شود یعنی دو نفر یک زنجیره را در دست دارند — و چون نمی‌دانیم کدام
-- یک کاربرِ واقعی است، کلِ خانواده باطل می‌شود و هر دو باید دوباره وارد
-- شوند. این «شکستِ محسوس» عمدی است: بهتر از دسترسیِ خاموشِ سی‌روزه.
--
-- دو ستون لازم است:
--
--   family_id  زنجیرهٔ سشن‌هایی که همه از یک ورود آمده‌اند. باطل کردن باید
--              خانوادگی باشد وگرنه مهاجم فقط یک حلقه را از دست می‌دهد.
--
--   rotated_to سشنِ جانشین. همین ستون است که «باطل شده چون چرخید» را از
--              «باطل شده چون کاربر خارج شد» جدا می‌کند — بدون آن، هر خروجِ
--              معمولی مثل حملهٔ استفادهٔ مجدد به نظر می‌رسید و کاربر را از
--              همهٔ دستگاه‌هایش بیرون می‌انداخت.

alter table sessions add column family_id uuid;

-- سشن‌های موجود هرکدام خانوادهٔ خودشان‌اند؛ هیچ‌کدام هنوز نچرخیده‌اند.
update sessions set family_id = id where family_id is null;

alter table sessions alter column family_id set not null;
alter table sessions alter column family_id set default gen_random_uuid();

alter table sessions
  add column rotated_to uuid references sessions(id) on delete set null;

-- باطل کردنِ خانوادگی تنها کوئریِ داغِ این ستون است و همیشه روی سشن‌های
-- زنده اجرا می‌شود، پس ایندکس جزئی است.
create index sessions_family_idx on sessions (family_id) where revoked_at is null;
