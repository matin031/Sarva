-- =============================================================================
-- ۰۱۵ — نوعِ اعلانِ «دسترسیِ دبیری لغو شد»
-- =============================================================================
--
-- ⚠️ یک ALTER، و دلیلش سلیقه‌ای نیست.
--
-- مدیر حالا می‌تواند دسترسیِ دبیریِ کسی را لغو کند، و کاربر باید خبردار
-- شود — وگرنه تنها راهِ فهمیدنش این است که روزی سراغِ پنلِ دبیر برود و
-- ببیند دیگر بازش نمی‌کند.
--
-- `notify()` هر `kind`ی را که در این CHECK نباشد رد می‌کند (و از زمانِ
-- اصلاحِ `INSERT IGNORE`، با صدای بلند). پس بدونِ این migration، اعلان
-- اصلاً نوشته نمی‌شود.
--
-- ── چرا مقدارِ موجود دوباره استفاده نشد ──────────────────────────────────
-- ⚠️ `plus_revoked` وسوسه‌انگیز بود و غلط است.
--
-- در این رویداد اشتراکِ پلاس هم لغو می‌شود، ولی آن *عارضه* است و نه خودِ
-- خبر. کاربری که «اشتراک پلاس شما لغو شد» می‌بیند، فکر می‌کند مسئله
-- مالی است و سراغِ پشتیبانیِ خرید می‌رود — در حالی که چیزی که واقعاً عوض
-- شده، نقشِ دبیری اوست.
--
-- همان استدلالی که در ۰۱۰ برای `teacher_needs_revision` نوشته شد: آنجا هم
-- استفادهٔ دوباره از `teacher_rejected` ساده‌تر بود و پیامِ غلط می‌داد.
--
-- ⚠️ و فهرست پیش از نوشتن **کامل خوانده شد**؛ هر چهارده مقدارِ موجود
-- اینجا تکرار می‌شوند. جا انداختنِ حتی یکی، ثبتِ آن نوع را از فردا
-- می‌شکست.
ALTER TABLE `plus_notifications` DROP CONSTRAINT `plus_notifications_kind_check`;
ALTER TABLE `plus_notifications`
  ADD CONSTRAINT `plus_notifications_kind_check`
  CHECK (`kind` IN ('plus_activated', 'plus_renewed', 'plus_expiring', 'plus_expired',
                    'plus_revoked', 'ticket_reply', 'payment_action_needed',
                    'teacher_approved', 'teacher_rejected', 'teacher_needs_revision',
                    'teacher_viewed_student', 'teacher_feedback',
                    'class_joined', 'class_removed',
                    'teacher_revoked'));
