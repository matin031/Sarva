type Mark = { h: number; words: number[]; label: string };
type ExtraMark = { h: number; word: number; label: string };

const tokens = (line: string) => line.trim().split(/\s+/);

/**
 * نقش هر توکن را به‌ترتیب واژه‌های همان سطر می‌گیرد. این تابع عمداً در زمان
 * بارگذاری، تعداد نقش‌ها و واژه‌ها را کنترل می‌کند تا indexها جابه‌جا نشوند.
 */
function syntax(lines: string[], roles: string[][], extra: ExtraMark[] = []): Mark[] {
  if (lines.length !== roles.length) throw new Error("تعداد سطرها و آرایه‌های نقش برابر نیست.");
  const result: Mark[] = [];
  lines.forEach((line, h) => {
    const lineTokens = tokens(line);
    if (lineTokens.length !== roles[h].length) {
      throw new Error(`ناهماهنگی توکن و نقش در سطر ${h}: ${line}`);
    }
    roles[h].forEach((label, word) => result.push({ h, words: [word], label }));
  });
  for (const item of extra) {
    if (!tokens(lines[item.h])?.[item.word]) throw new Error("index نقش تکمیلی نامعتبر است.");
    result.push({ h: item.h, words: [item.word], label: item.label });
  }
  return result;
}

function device(lines: string[], h: number, phrase: string, label: string, occurrence = 0): Mark {
  const haystack = tokens(lines[h]);
  const needle = tokens(phrase);
  let seen = 0;
  for (let i = 0; i <= haystack.length - needle.length; i += 1) {
    if (needle.every((word, j) => haystack[i + j] === word)) {
      if (seen === occurrence) return { h, words: needle.map((_, j) => i + j), label };
      seen += 1;
    }
  }
  throw new Error(`عبارت آرایه پیدا نشد: ${phrase}`);
}

