import { queryOne } from "@/lib/db";
import { logger } from "@/lib/observability";

/**
 * «آیا می‌شود روزِ تهران را حساب کرد؟»
 *
 * =============================================================================
 * ⚠️ مسئله‌ای که این ماژول برایش هست
 * =============================================================================
 *
 * هر گزارشِ **روزمحور** در سروا به این می‌رسد:
 *
 *     CONVERT_TZ(answered_at, '+00:00', 'Asia/Tehran')
 *
 * مقصد *باید* نامِ منطقه باشد و نه یک offsetِ ثابت — ایران تا ۲۰۲۲ ساعتِ
 * تابستانی داشت، پس `+03:30` برای داده‌های قدیمی یک ساعت جابه‌جا می‌شود و
 * پاسخ‌های نزدیکِ نیمه‌شب به روزِ اشتباه می‌افتند.
 *
 * ولی نامِ منطقه فقط وقتی کار می‌کند که جدول‌های `mysql.time_zone` بارگذاری
 * شده باشند. اگر نباشند — که روی هاستِ اشتراکی حالتِ رایجی است —
 * `CONVERT_TZ` مقدارِ **NULL** برمی‌گرداند. نه خطایی، نه هشداری.
 *
 * و پیامدش دقیقاً همان چیزی است که نباید اتفاق بیفتد: نمودارِ روزانه خالی
 * می‌شود و دبیر می‌بیند «این دانش‌آموز هیچ فعالیتی نداشته» — در حالی که
 * داشته. یک گزارشِ **غلط** که شبیهِ یک گزارشِ **درست** است.
 *
 * ── راه‌حل ────────────────────────────────────────────────────────────────
 * یک بار در هر فرایند سنجیده می‌شود. اگر نبود:
 *
 *   • تحلیلِ **غیرروزانه** دست‌نخورده کار می‌کند (دقتِ وزن، نقشِ دستوری،
 *     شمارش‌ها، آخرین فعالیت) — چون هیچ‌کدام به `CONVERT_TZ` نیاز ندارند.
 *   • بخشِ روزمحور یک وضعیتِ **صریحِ «در دسترس نیست»** می‌گیرد و نه یک
 *     آرایهٔ خالی. رابط کاربری همان را نشان می‌دهد، نه یک نمودارِ صفر.
 *   • و یک بار در لاگ ثبت می‌شود تا روی سرور معلوم باشد چرا.
 */

/** نتیجهٔ سنجش، برای کلِ عمرِ فرایند. */
let cached: boolean | null = null;
/** سنجشِ در جریان — تا ده درخواستِ همزمان ده کوئری نزنند. */
let inFlight: Promise<boolean> | null = null;

/**
 * ⚠️ چرا کش در سطحِ ماژول و نه در هر فراخوانی:
 *
 * پاسخ فقط با یک تغییرِ *پیکربندیِ سرور* عوض می‌شود (بارگذاری جدول‌های
 * منطقه)، و آن کار خودش ری‌استارت می‌خواهد. زدنِ یک کوئری به‌ازای هر
 * نمودار، هزینه‌ای است برای جوابی که تا ری‌استارتِ بعدی عوض نمی‌شود.
 */
export async function tehranDayAvailable(): Promise<boolean> {
  if (cached !== null) return cached;
  if (inFlight) return inFlight;

  inFlight = (async () => {
    try {
      const row = await queryOne<{ converted: string | null }>(
        // ⚠️ مبدأ صریحاً `'+00:00'` و نه `'UTC'`: اولی همیشه کار می‌کند،
        // دومی خودش به همان جدول‌ها نیاز دارد — یعنی سنجش با چیزی انجام
        // می‌شد که قرار است سنجیده شود.
        "select convert_tz('2026-01-01 12:00:00', '+00:00', 'Asia/Tehran') as converted",
      );
      const available = row?.converted != null;

      if (!available) {
        logger.error("جدول‌های منطقهٔ زمانی بارگذاری نشده‌اند — گزارشِ روزانه غیرفعال شد", {
          event: "analytics.timezone_unavailable",
          hint: "mysql_tzinfo_to_sql /usr/share/zoneinfo | mysql -u root mysql",
        });
      }

      cached = available;
      return available;
    } catch (err) {
      /* شکستِ خودِ کوئری یعنی نمی‌دانیم — و «نمی‌دانیم» باید مثلِ «نیست»
         رفتار کند. نتیجه کش **نمی‌شود**: یک قطعیِ گذرای دیتابیس نباید
         گزارشِ روزانه را تا ری‌استارتِ بعدی خاموش نگه دارد. */
      logger.error("سنجشِ جدول‌های منطقهٔ زمانی شکست خورد", {
        event: "analytics.timezone_probe_failed",
        err,
      });
      return false;
    } finally {
      inFlight = null;
    }
  })();

  return inFlight;
}

/** فقط برای تست و اسکریپت‌ها. کدِ اپ به این دست نمی‌زند. */
export function resetTehranDayCache(): void {
  cached = null;
  inFlight = null;
}

/**
 * عبارتِ «روزِ تهرانِ این ستون».
 *
 * ⚠️ نامِ ستون درون‌ریزی می‌شود و پارامتر نیست — در MySQL نامِ ستون
 * نمی‌تواند `?` باشد. پس فراخوان‌ها باید فقط رشته‌های ثابتِ خودشان را
 * بدهند و هرگز ورودیِ کاربر را.
 */
export function tehranDay(column: string): string {
  return `date_format(convert_tz(${column}, '+00:00', 'Asia/Tehran'), '%Y-%m-%d')`;
}

