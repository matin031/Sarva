/**
 * یادآوریِ پایانِ اشتراک  —  `npm run notify:expiring`
 *
 * ⚠️ این اسکریپت **پیامکِ واقعی می‌فرستد و پول خرج می‌کند.** یک ابزارِ
 * بررسی نیست؛ همان کاری را می‌کند که کرون هر روز می‌کند.
 *
 * ── جای اجرا ───────────────────────────────────────────────────────────────
 *
 * روزی یک بار، ترجیحاً صبح (پیامکِ نیمه‌شب هم بی‌ادبانه است و هم خوانده
 * نمی‌شود). روی هاست با کرونِ سیستمی:
 *
 *     0 9 * * *  cd /path/to/app && npm run notify:expiring >> logs/notify.log 2>&1
 *
 * اگر هاست کرون ندارد، `POST /api/v1/cron/notifications` همین کار را
 * می‌کند و با یک سرویسِ کرونِ اینترنتی صدا زده می‌شود.
 *
 * ── اجرای دوباره بی‌خطر است ────────────────────────────────────────────────
 *
 * ⚠️ و این را باید *باور* کرد، چون تنها چیزی است که اجازه می‌دهد بعد از یک
 * تیکِ جاافتاده دستی اجرایش کنید. ضمانتش `dedupe_key` در
 * `outbound_notifications` است: کلیدِ هر پیام تاریخِ پایانِ اشتراک را در خود
 * دارد و ایندکسِ یکتا، دومی را رد می‌کند. ده بار اجرا، همان یک پیامک.
 *
 * ⚠️ خروجی هیچ شماره و ایمیلی ندارد — فقط شمارش. این خروجی معمولاً در یک
 * فایلِ لاگ می‌نشیند و گاهی جایی paste می‌شود.
 */

import { runExpirySweep } from "@/lib/notify/expiry";

async function main(): Promise<void> {
  const result = await runExpirySweep();

  if (!result.ran) {
    console.log("سروا پلاس خاموش است؛ هیچ یادآوری‌ای فرستاده نشد.");
    return;
  }

  console.log("یادآوریِ پایانِ اشتراک اجرا شد:");
  console.log(`  نزدیک پایان : ${result.expiring}`);
  console.log(`  تمام‌شده     : ${result.expired}`);
  console.log(`  تکراری      : ${result.skipped}`);
}

main()
  .catch((err) => {
    /* ⚠️ `runExpirySweep` خودش throw نمی‌کند، پس رسیدن به اینجا یعنی چیزی
       پیش از آن شکسته — معمولاً اتصالِ دیتابیس. کدِ خروجیِ غیرصفر لازم است
       تا کرون آن را «شکست» ببیند و در لاگِ سیستم بنشیند. */
    console.error("اجرا با خطا متوقف شد:", err);
    process.exitCode = 1;
  })
  .finally(async () => {
    const { getPool } = await import("@/lib/db");
    await getPool().end();
  });
