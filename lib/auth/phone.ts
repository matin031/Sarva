/**
 * شمارهٔ موبایل — یک شکلِ متعارف، یک نقطه.
 *
 * ⚠️ عمداً بدون `server-only`: فرمِ ورود هم باید بتواند پیش از فرستادن، ورودی
 * را بسنجد. هیچ‌چیز محرمانه‌ای اینجا نیست.
 *
 * ── چرا نرمال‌سازی، و چرا اینجا ────────────────────────────────────────────
 * یک نفر می‌تواند شماره‌اش را به چهار شکل بنویسد:
 *
 *     09123456789        +989123456789
 *     9123456789         0098 912 345 6789
 *
 * اگر هرکدام همان‌طور که تایپ شده ذخیره شود، «این شماره قبلاً ثبت شده؟» پاسخِ
 * قطعی ندارد: یک نفر با یک خط، چهار حساب می‌سازد و کدِ بازیابیِ رمزش به
 * حسابی می‌رود که انتظارش را ندارد.
 *
 * پس **همه‌جا** یک شکل ذخیره می‌شود: `989123456789` — بدون صفر، بدون +، بدون
 * فاصله. مهاجرتِ ۰۰۶ یک CHECK با همین الگو دارد تا اگر روزی کدی این تابع را
 * دور زد، دیتابیس جلویش را بگیرد.
 *
 * ⚠️ ارقامِ فارسی و عربی هم پذیرفته می‌شوند. دانش‌آموزی که با کیبورد فارسی
 * تایپ می‌کند «۰۹۱۲…» می‌نویسد، و ردِ کردنش با پیام «شماره معتبر نیست» یعنی
 * کاربری که شمارهٔ درست را وارد کرده و نمی‌فهمد چرا قبول نمی‌شود.
 */

/** ارقامِ فارسی (۰-۹) و عربی-هندی (٠-٩) به ارقامِ لاتین. */
function toLatinDigits(raw: string): string {
  return raw.replace(/[۰-۹٠-٩]/g, (d) => {
    const code = d.charCodeAt(0);
    // ۰ = U+06F0 و ٠ = U+0660. هر کدام که باشد، فاصله‌اش از مبدأ همان رقم است.
    const base = code >= 0x06f0 ? 0x06f0 : 0x0660;
    return String(code - base);
  });
}

/**
 * ورودیِ کاربر → شکلِ متعارف (`989123456789`)، یا `null` اگر شمارهٔ موبایلِ
 * ایرانی نباشد.
 *
 * ⚠️ `null` یعنی «قبول نیست» و هرگز نباید به یک رشتهٔ خالی یا به خودِ ورودی
 * تبدیل شود. هر تابعی که این را صدا می‌زند باید حالتِ null را صریح مدیریت
 * کند — به همین دلیل نوعِ خروجی nullable است و نه `string`.
 */
export function normalizePhone(raw: unknown): string | null {
  if (typeof raw !== "string") return null;

  // جداکننده‌های رایج: فاصله، خط تیره، پرانتز، و فاصلهٔ مجازی که از کپی کردن
  // از پیامک یا اکسل می‌آید.
  const cleaned = toLatinDigits(raw)
    .replace(/[\s\-()‌‏‎]/g, "")
    .trim();

  if (!cleaned) return null;

  // چهار شکلِ ممکن، همه به `9XXXXXXXXX` می‌رسند.
  let national: string | null = null;

  if (/^\+989\d{9}$/.test(cleaned)) national = cleaned.slice(3);
  else if (/^00989\d{9}$/.test(cleaned)) national = cleaned.slice(4);
  else if (/^989\d{9}$/.test(cleaned)) national = cleaned.slice(2);
  else if (/^09\d{9}$/.test(cleaned)) national = cleaned.slice(1);
  else if (/^9\d{9}$/.test(cleaned)) national = cleaned;

  if (national === null) return null;

  // ⚠️ فقط پیش‌شماره‌های موبایل. `0913…` موبایل است و `021…` تلفنِ ثابت؛
  // دومی پیامک نمی‌گیرد و پذیرفتنش یعنی کاربری که هرگز کد دریافت نمی‌کند و
  // دلیلش را هم نمی‌فهمد. همهٔ اپراتورهای ایران با `9` شروع می‌شوند و رقمِ
  // دومشان ۰ تا ۹ است، پس همین یک الگو کافی است.
  if (!/^9\d{9}$/.test(national)) return null;

  return `98${national}`;
}

/** آیا این ورودی یک شمارهٔ موبایلِ ایرانیِ معتبر است؟ */
export function isValidPhone(raw: unknown): boolean {
  return normalizePhone(raw) !== null;
}

/**
 * شکلِ متعارف → آنچه به کاربر نشان داده می‌شود (`0912 345 6789`).
 *
 * ⚠️ هیچ‌وقت شکلِ ذخیره‌شده مستقیم نمایش داده نمی‌شود: `989123456789` برای
 * کاربرِ ایرانی شمارهٔ آشنایی نیست و یک لحظه مکث می‌خواهد تا بفهمد شمارهٔ
 * خودش است.
 */
export function formatPhone(canonical: string | null): string | null {
  if (!canonical || !/^989\d{9}$/.test(canonical)) return null;
  const n = canonical.slice(2); // 9XXXXXXXXX
  return `0${n.slice(0, 3)} ${n.slice(3, 6)} ${n.slice(6)}`;
}

/**
 * نسخهٔ پوشیده برای پیام‌ها و گزارش‌ها: `0912 *** 6789`.
 *
 * ⚠️ در صفحهٔ «کد را فرستادیم» باید آن‌قدر از شماره دیده شود که کاربر مطمئن
 * شود درست وارد کرده، و آن‌قدر کم که اگر کسی صفحه را دید، شماره را برندارد.
 */
export function maskPhone(canonical: string | null): string | null {
  if (!canonical || !/^989\d{9}$/.test(canonical)) return null;
  const n = canonical.slice(2);
  return `0${n.slice(0, 3)} *** ${n.slice(6)}`;
}
