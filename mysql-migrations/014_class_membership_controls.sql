-- ۰۱۴ — تفکیکِ «خروجِ خودخواسته» از «اخراج»، و «بستنِ عضویت» از «بایگانی»
-- =============================================================================
--
-- دو ابهام که هر دو در عمل به باگ رسیده‌اند.
--
-- ── ۱) `removed` دو معنای متضاد داشت ────────────────────────────────────
--
-- `class_members.status` فقط `active` و `removed` داشت، و `removed` هم برای
-- دانش‌آموزی که خودش رفته به کار می‌رفت و هم برای کسی که دبیر بیرونش گذاشته.
--
-- نتیجه‌اش این بود: `joinClassByCode` هر ردیفِ `removed` را دوباره زنده
-- می‌کرد، پس دانش‌آموزی که همین الان اخراج شده بود، **با همان کد بلافاصله
-- برمی‌گشت**. کامنتِ خودِ کد هم این را می‌دانست و ابزارِ چاره‌اش را «چرخاندنِ
-- کد» معرفی می‌کرد — یعنی برای بیرون نگه داشتنِ یک نفر، باید کلِ کلاس کدِ
-- تازه می‌گرفت.
--
-- ⚠️ و حالتِ سومی هم لازم است که هیچ‌کدام از این دو نیست: دبیری که نظرش عوض
-- شده و می‌خواهد همان نفر برگردد. بدونِ یک وضعیتِ جدا، «اجازهٔ بازگشت» هیچ
-- معنایی نداشت.
--
-- ⚠️⚠️ و مهم‌ترین قاعدهٔ این فایل: **هیچ backfill حدسی انجام نمی‌شود.**
-- `removed`های موجود `removed` می‌مانند. نمی‌دانیم کدامشان اخراج بوده‌اند و
-- حدس زدن یعنی دانش‌آموزی که خودش رفته، بی‌دلیل از کلاسش بیرون بماند.
-- سیاستِ تازه فقط از این به بعد اعمال می‌شود.
--
-- ── ۲) `is_active` دو مفهوم را یکی کرده بود ─────────────────────────────
--
-- رابط کاربری با آن «عضوگیری را ببند» را می‌فهماند («کسی نمی‌تواند عضو شود.
-- اعضای فعلی سرِ جایشان هستند») ولی نامش می‌گفت کلاس بسته است. دو کارِ
-- کاملاً متفاوت با یک کلید:
--
--   • عضوگیری بسته  → کلاس زنده است، فقط کدش دیگر کسی را وارد نمی‌کند.
--   • کلاس بایگانی  → ترمِ تمام‌شده. چیزی حذف نمی‌شود.
--
-- `join_enabled` با پیش‌فرضِ ۱ اضافه می‌شود، پس **رفتارِ امروز ذره‌ای عوض
-- نمی‌شود**: هر کلاسِ موجود همچنان عضو می‌پذیرد. از این به بعد آن دکمه به
-- این ستون وصل است و `is_active` برای بایگانی می‌ماند.
--
-- معنای بایگانی (و عمداً همان رفتارِ فعلی است، فقط مستند):
--   • عضوِ فعلی حذف نمی‌شود.
--   • دسترسیِ دبیر به عملکردِ اعضای فعال قطع نمی‌شود — تحلیلِ ترمِ گذشته
--     باید بعدش هم قابلِ خواندن باشد.
--   • عضوِ تازه پذیرفته نمی‌شود.
--   • بازخوردها و سابقه دست‌نخورده می‌مانند.
-- =============================================================================


-- =============================================================================
-- بخش ۱ — وضعیتِ سومِ عضویت
-- =============================================================================
--
-- `DROP CONSTRAINT` و نه `DROP CHECK` — تنها شکلی که روی MariaDB و MySQL هر
-- دو کار می‌کند. (استدلالِ کاملش در ۰۰۹.)
--
--   active  — عضوِ فعال.
--   removed — خودش رفته. می‌تواند با کدِ معتبر برگردد.
--   blocked — دبیر بیرونش گذاشته. تا وقتی دبیر اجازه ندهد برنمی‌گردد.
--
-- ⚠️ `removed` عمداً حذف نشد و معنایش هم عوض نشد. حذفش یعنی هر ردیفِ موجود
-- نامعتبر شود و migration روی دادهٔ واقعی بشکند.
ALTER TABLE `class_members` DROP CONSTRAINT `class_members_status_check`;
ALTER TABLE `class_members`
  ADD CONSTRAINT `class_members_status_check`
  CHECK (`status` IN ('active', 'removed', 'blocked'));


-- =============================================================================
-- بخش ۲ — «عضوگیری باز است؟»، جدا از «کلاس بایگانی شده؟»
-- =============================================================================
--
-- ⚠️ `NOT NULL DEFAULT 1` — و این پیش‌فرض بخشی از طراحی است و نه راحتی:
-- ردیف‌های موجود همگی ۱ می‌گیرند، پس هیچ کلاسی با اجرای این migration
-- عضوگیری‌اش بسته نمی‌شود. یک استقرارِ نیمه‌شب نباید فردا صبح دبیرها را با
-- کلاس‌هایی روبه‌رو کند که هیچ‌کس نمی‌تواند عضوشان شود.
ALTER TABLE `teacher_classes`
  ADD COLUMN `join_enabled` TINYINT(1) NOT NULL DEFAULT 1 AFTER `is_active`;
