/**
 * هندسهٔ مسیرِ ستاره — خالص، بدون DOM و بدون GSAP.
 *
 * ⚠️ چرا جدا از کامپوننت: این تنها جایی است که «حسِ حرکت» در آن تصمیم گرفته
 * می‌شود — جهت چرخش، فاصله از کارت، و شکلِ سفرِ بینِ دو بخش. با جدا بودن، هم
 * می‌شود بدونِ مرورگر امتحانش کرد و هم عوض کردنِ حس، چند عدد است و نه گشتن
 * در میانِ کدِ انیمیشن.
 *
 * ── چرا چرخش به چپ ────────────────────────────────────────────────────────
 * کلِ سایت راست‌به‌چپ است و چشمِ خواننده از راست شروع می‌کند. ستاره‌ای که از
 * بالا به سمتِ راست بچرخد، برخلافِ جهتِ خواندن حرکت می‌کند و حسِ «برگشت»
 * می‌دهد نه «پیش‌روی». پس مدار از بالای کارت به سمتِ *چپ* باز می‌شود.
 *
 * تمامِ این جهت در یک عدد خلاصه شده: `s` — علامتِ «جلو» روی محورِ x. در RTL
 * منفی است. هیچ‌جای دیگری راست و چپ هاردکد نشده.
 *
 * ── چرا مدار «بسته» است ───────────────────────────────────────────────────
 * ⚠️ هر مدار یک حلقهٔ **بسته** است: از بالای وسطِ کارت شروع می‌شود، یک دور
 * کامل می‌زند و دقیقاً به همان نقطه برمی‌گردد. آن نقطه «لنگر» (anchor) آن
 * بخش است، و سفرِ بعدی از همان‌جا آغاز می‌شود.
 *
 * پایانِ هر تکه = آغازِ تکهٔ بعدی. این تنها چیزی است که تضمین می‌کند مسیر در
 * کلِ صفحه پیوسته باشد و ستاره هیچ‌جا نپرد.
 */

export type Rect = { left: number; top: number; width: number; height: number };
export type Point = { x: number; y: number };

export type OrbitOptions = {
  /** فاصلهٔ مدار از لبهٔ کارت، به پیکسل. */
  pad: number;
  /** شعاعِ گوشه‌های مدار. */
  radius: number;
  /** راست‌به‌چپ: مدار از بالا به سمتِ چپ باز می‌شود. */
  rtl: boolean;
};

/**
 * کمترین فاصلهٔ مدار تا لبهٔ صفحه.
 *
 * ⚠️ باید از *نصفِ عرضِ خودِ ستاره* بیشتر باشد و نه فقط یک عددِ دلخواه.
 * ستاره ۴۴ پیکسل است، پس با فاصلهٔ ۱۶ پیکسل، در چپ‌ترین نقطهٔ مدار روی
 * گوشی چند پیکسل از پرش بیرونِ کادر می‌افتاد.
 */
const MIN_EDGE_GAP = 30;

/** یک عدد با دقتِ کافی برای SVG و بدونِ دنبالهٔ اعشارِ بی‌فایده. */
const n = (v: number) => Math.round(v * 100) / 100;

/** لنگرِ یک کارت: بالای وسطِ مدارش. هم آغازِ حلقه است و هم پایانش. */
export function orbitAnchor(card: Rect, pad: number): Point {
  return { x: card.left + card.width / 2, y: card.top - pad };
}

/**
 * حلقهٔ بستهٔ دورِ یک کارت — یک دورِ کامل، از لنگر تا خودِ لنگر.
 *
 * شکلش مستطیلِ گردشده است و نه دایره، چون باید *دورِ کارت* بچرخد و نه دورِ
 * یک نقطه؛ کارتِ پهن با یک دایره یا خیلی دور می‌افتد یا از دو طرف بیرون
 * می‌زند.
 */
export function orbitLoop(card: Rect, o: OrbitOptions): string {
  const { pad, radius: rr, rtl } = o;

  const x0 = card.left - pad;
  const y0 = card.top - pad;
  const x1 = card.left + card.width + pad;
  const y1 = card.top + card.height + pad;
  const cx = (x0 + x1) / 2;

  /** علامتِ «جلو» روی محورِ x. در راست‌به‌چپ، جلو یعنی چپ. */
  const s = rtl ? -1 : 1;
  /** لبه‌ای که ستاره اول به آن می‌رسد، و لبهٔ مقابلش. */
  const near = rtl ? x0 : x1;
  const far = rtl ? x1 : x0;

  return [
    `M ${n(cx)} ${n(y0)}`,
    `L ${n(near - s * rr)} ${n(y0)}`,
    `Q ${n(near)} ${n(y0)} ${n(near)} ${n(y0 + rr)}`,
    `L ${n(near)} ${n(y1 - rr)}`,
    `Q ${n(near)} ${n(y1)} ${n(near - s * rr)} ${n(y1)}`,
    `L ${n(far + s * rr)} ${n(y1)}`,
    `Q ${n(far)} ${n(y1)} ${n(far)} ${n(y1 - rr)}`,
    `L ${n(far)} ${n(y0 + rr)}`,
    `Q ${n(far)} ${n(y0)} ${n(far + s * rr)} ${n(y0)}`,
    `L ${n(cx)} ${n(y0)}`,
  ].join(" ");
}

/**
 * حلقهٔ بیضی — برای گوشی، و برای چیزی که خودش گرد است (چرخِ «چطور کار می‌کند»).
 *
 * ⚠️ روی گوشی شکلِ دیگری لازم است و نه همان مسیرِ کوچک‌شده: کارت تقریباً
 * تمامِ عرضِ صفحه را می‌گیرد، پس مدارِ مستطیلی یا از صفحه بیرون می‌زند یا
 * آن‌قدر به متن می‌چسبد که رویش می‌افتد.
 */
export function orbitLoopCompact(
  card: Rect,
  o: Pick<OrbitOptions, "pad" | "rtl"> & { viewportWidth: number },
): string {
  const { pad, rtl, viewportWidth: vw } = o;
  const cx = card.left + card.width / 2;
  const cy = card.top + card.height / 2;
  // ⚠️ معیارِ محدودیت، فاصله تا *نزدیک‌ترین* لبه است و نه نصفِ عرضِ صفحه.
  // نسخهٔ اول `vw / 2` را می‌گرفت، که تلویحاً فرض می‌کرد کارت وسط است.
  // کارت‌ها جابه‌جاییِ افقی دارند، پس آن فرض غلط بود و مدارِ کارتِ جابه‌جاشده
  // باز هم از یک طرف بیرون می‌زد.
  const roomToEdge = Math.min(cx, vw - cx) - MIN_EDGE_GAP;
  const rx = Math.max(24, Math.min(card.width / 2 + pad, roomToEdge));
  const ry = card.height / 2 + pad;
  // sweep=0 یعنی از بالا به سمتِ چپ — همان جهتِ راست‌به‌چپ.
  const sweep = rtl ? 0 : 1;

  return [
    `M ${n(cx)} ${n(cy - ry)}`,
    `A ${n(rx)} ${n(ry)} 0 0 ${sweep} ${n(cx)} ${n(cy + ry)}`,
    `A ${n(rx)} ${n(ry)} 0 0 ${sweep} ${n(cx)} ${n(cy - ry)}`,
  ].join(" ");
}

/**
 * سفرِ ستاره از لنگرِ یک بخش به لنگرِ بخشِ بعدی.
 *
 * ⚠️ چرا منحنی و نه خطِ راست: خطِ راست بینِ دو نقطه، در طولِ اسکرول شبیهِ
 * «جهیدن» است و نه «افتادن». منحنیِ درجه‌سه با دو نقطهٔ کنترل که یکی رو به
 * جلو و دیگری رو به عقب خم شده، همان قوسِ آرامی را می‌دهد که چشم آن را
 * سقوطِ طبیعیِ یک جسم می‌خواند.
 */
export function travelPath(
  from: Point,
  to: Point,
  o: { rtl: boolean; viewportWidth: number },
): string {
  const s = o.rtl ? -1 : 1;
  const dx = to.x - from.x;
  const dy = to.y - from.y;

  // خمِ جانبی: ستاره کمی به سمتِ «جلو» می‌زند و بعد برمی‌گردد.
  //
  // ⚠️ سقفش به *عرضِ صفحه* بسته است و نه یک عددِ ثابت. با سقفِ ثابتِ ۱۸۰
  // پیکسل، روی گوشیِ ۳۹۰ پیکسلی ستاره در میانهٔ سفر از کادر بیرون می‌رفت و
  // کاربر به‌جای یک قوس، ناپدید شدن و برگشتنش را می‌دید.
  const cap = Math.min(170, o.viewportWidth * 0.19);
  const swing = Math.min(cap, Math.abs(dy) * 0.4 + 55) * s;

  return [
    `M ${n(from.x)} ${n(from.y)}`,
    `C ${n(from.x + swing)} ${n(from.y + dy * 0.34)}`,
    `${n(to.x + swing - dx * 0.22)} ${n(to.y - dy * 0.34)}`,
    `${n(to.x)} ${n(to.y)}`,
  ].join(" ");
}
