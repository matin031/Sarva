const VAR_CACHE = new Map<string, Record<string, number>>();

export function meterVariants(
  pat: string,
  name?: string,
): Record<string, number> {
  const key = pat + "|" + (name ?? "");
  const cached = VAR_CACHE.get(key);
  if (cached) return cached;

  const out: Record<string, number> = name && name in FAM_PAT ? { ...FAM_PAT[name] } : { [pat]: 0.0 };

  if (name === "وزن رباعی") {
    // ★ ۲۴ گونهٔ وزنِ رباعی: مفاعیلُ (U--U) ↔ مفاعِلُن (U-U-)، پایانه فعل (U-) یا فع (-)
    for (const a of ["U--U", "U-U-"]) {
      for (const b of ["U--U", "U-U-"]) {
        for (const t of ["U-", "-"]) {
          const p = "--U" + a + b + t;
          const c = 0.15 * ((a !== "U--U" ? 1 : 0) + (b !== "U--U" ? 1 : 0));
          if (!(p in out) || c < out[p]) out[p] = c;
        }
      }
    }
  }
  if (pat.startsWith("UU")) {
    // فاعلاتن جای فعلاتن
    const alt = "-" + pat.slice(1);
    if (!(alt in out)) out[alt] = 0.5;
  }
  for (let i = 0; i < pat.length - 1; i++) {
    // ابدال
    if (pat.slice(i, i + 2) === "UU") {
      const alt = pat.slice(0, i) + "-" + pat.slice(i + 2);
      if (!(alt in out)) out[alt] = 1.1;
    }
  }
  for (let i = 0; i < pat.length - 3; i++) {
    // قلب
    if (pat.slice(i, i + 4) === "-UU-") {
      const alt = pat.slice(0, i) + "U-U-" + pat.slice(i + 4);
      if (!(alt in out)) out[alt] = 1.2;
    } else if (pat.slice(i, i + 4) === "U-U-") {
      const alt = pat.slice(0, i) + "-UU-" + pat.slice(i + 4);
      if (!(alt in out)) out[alt] = 1.2;
    }
  }
  VAR_CACHE.set(key, out);
  return out;
}

export function meterCost(
  scans: Map<string, number>,
  pat: string,
  name?: string,
): number {
  let best = 999.0;
  const variants = meterVariants(pat, name);
  for (const [v, vp] of Object.entries(variants)) {
    for (const [x, sp] of scans) {
      if (x.length !== v.length) continue;
      const c = matchCost(x, v) + LAMBDA * sp + vp;
      if (c < best) best = c;
    }
  }
  return best;
}

export function bestScan(
  scans: Map<string, number>,
  pat: string,
  name?: string,
): string | null {
  if (scans.size === 0) return null;
  let best: string | null = null;
  let bc = 1e9;
  const variants = meterVariants(pat, name);
  for (const [v, vp] of Object.entries(variants)) {
    for (const [x, sp] of scans) {
      if (x.length !== v.length) continue;
      const c = matchCost(x, v) + LAMBDA * sp + vp;
      if (c < bc) {
        bc = c;
        best = x;
      }
    }
  }
  if (best) return best;
  let closest: string | null = null;
  let bestDiff = Infinity;
  for (const x of scans.keys()) {
    const diff = Math.abs(x.length - pat.length);
    if (diff < bestDiff) {
      bestDiff = diff;
      closest = x;
    }
  }
  return closest;
}
