/**
 * ستارهٔ هشت‌پرِ خاتم — قابِ هر واژه.
 *
 * ⚠️ خط‌های مستقیم، نه منحنی.
 *
 * نسخهٔ قبلی هر پره را با یک کمانِ درجه‌دو می‌کشید و نتیجه‌اش یک *گُل* بود
 * نه یک ستاره: پره‌های تپل و گرد که کنارِ یک مصراعِ شعر بیشتر شبیه
 * برچسبِ کودکانه دیده می‌شدند. نقش‌مایهٔ خاتم لبهٔ صاف دارد و همان چیزی
 * است که «مینیمال» را می‌سازد.
 *
 * نرمیِ لازم از `stroke-linejoin: round` می‌آید و نه از خمِ خودِ مسیر —
 * یعنی نوکِ پره‌ها کمی گرد می‌شوند بی‌آنکه شکل از ستاره بودن بیفتد.
 */

/** شعاعِ نوکِ پره. جعبه ۱۰۰×۱۰۰ است، پس ۴۶ یعنی کمی فاصله تا لبه. */
const OUTER = 46;

/**
 * نسبتِ شعاعِ درونی به بیرونی.
 *
 * ⚠️ این تنها عددی است که «چقدر تیز» را تعیین می‌کند.
 *
 * ۰٫۶۸ آزموده شد و هنوز شلوغ بود: هشت نوکِ بلند کنارِ هم، روی هشت واژه،
 * صفحه را پر از خار می‌کرد. ۰٫۸ پره‌ها را کوتاه می‌کند و شکل به یک
 * هشت‌ضلعیِ نرم با برجستگیِ ملایم می‌رسد — همان چیزی که «مینیمال» است:
 * نقش‌مایه هست، ولی داد نمی‌زند. پایین‌تر از این به ستارهٔ کارتونی می‌رود.
 */
const INNER_RATIO = 0.8;
const POINTS = 8;

function buildStar(): string {
  const inner = OUTER * INNER_RATIO;
  const parts: string[] = [];
  for (let i = 0; i < POINTS * 2; i++) {
    // از رأسِ بالا شروع می‌شود تا ستاره «ایستاده» دیده شود.
    const angle = (i * Math.PI) / POINTS - Math.PI / 2;
    const r = i % 2 === 0 ? OUTER : inner;
    const x = 50 + r * Math.cos(angle);
    const y = 50 + r * Math.sin(angle);
    parts.push(`${i === 0 ? "M" : "L"}${x.toFixed(2)} ${y.toFixed(2)}`);
  }
  return `${parts.join(" ")} Z`;
}

export const STAR_PATH = buildStar();
