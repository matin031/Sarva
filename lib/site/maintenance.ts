import "server-only";
import { getSetting } from "@/lib/settings";
import { logger } from "@/lib/observability";

/**
 * =============================================================================
 * حالتِ «در حال بروزرسانی»
 * =============================================================================
 *
 * یک کلید در ‎/admin/settings‎ که سایت را برای بازدیدکننده می‌بندد و برای
 * مالک باز نگه می‌دارد.
 *
 * ── چرا از تنظیمات و نه از متغیرِ محیطی ────────────────────────────────────
 *
 * لحظه‌ای که این کلید لازم می‌شود، همان لحظه‌ای است که چیزی خراب شده — و آن
 * لحظه وقتِ ویرایشِ `.env`، ساختنِ ایمیج و ری‌استارتِ کانتینر نیست. یک کلید
 * در پنل، از گوشی هم زده می‌شود. (`SITE_MAINTENANCE` همچنان کار می‌کند، به
 * عنوانِ مقدارِ پیش‌فرض — همان ترتیبی که کلِ `lib/settings` دارد.)
 *
 * ── چیزی که سایت‌های واقعی در این حالت می‌کنند، و اینجا هم می‌شود ───────────
 *
 *   ۱) **کدِ ۵۰۳ و نه ۲۰۰.** این مهم‌ترین بخش است و راحت‌ترین بخش برای
 *      فراموش کردن. صفحهٔ بروزرسانی با کدِ ۲۰۰ یعنی گوگل آن را *محتوای
 *      واقعیِ* آن آدرس می‌فهمد و در نتایج می‌نشاند؛ چند روز بروزرسانی
 *      می‌تواند ماه‌ها رتبه را ببرد. ۵۰۳ یعنی «موقتاً در دسترس نیست،
 *      دوباره سر بزن» و هیچ صفحه‌ای را از فهرست بیرون نمی‌اندازد.
 *
 *   ۲) **`Retry-After`.** به خزنده می‌گوید کِی برگردد.
 *      (`RETRY_AFTER_SECONDS` پایین.)
 *
 *   ۳) **راهِ عبور برای خودِ تیم.** بدونش، تنها راهِ امتحانِ سایت این است که
 *      اول بازش کنی — یعنی دقیقاً همان کاری که نباید. اینجا دو راه هست:
 *      مدیرِ واردشده خودبه‌خود رد می‌شود، و هر کسی با ‎?bypass=<کلید>‎ یک
 *      کوکی می‌گیرد و تا ۱۲ ساعت سایت را عادی می‌بیند.
 *
 * ⚠️ **این یک لایهٔ امنیتی نیست.** هیچ دسترسیِ تازه‌ای نمی‌بندد و هیچ گاردِ
 * موجودی را جایگزین نمی‌کند؛ فقط جلوِ *دیده شدن* را می‌گیرد. هر چیزی که
 * واقعاً باید محدود باشد، گاردِ خودش را در لایهٔ داده دارد.
 */

/** مسیرِ صفحه‌ای که بازدیدکننده به آن می‌رود. */
export const MAINTENANCE_PATH = "/maintenance";

/** نامِ کوکیِ عبور. */
export const MAINTENANCE_BYPASS_COOKIE = "sarva_bypass";

/** نامِ پارامترِ آدرس که کوکی را می‌نشاند. */
export const MAINTENANCE_BYPASS_PARAM = "bypass";

/**
 * عمرِ کوکیِ عبور.
 *
 * ⚠️ محدود و نه دائمی. یک بروزرسانیِ چندساعته تمام می‌شود ولی کوکی می‌ماند؛
 * دوازده ساعت یعنی مرورگرِ همکاری که ماه بعد لینک را باز می‌کند، همان
 * چیزی را ببیند که بقیه می‌بینند.
 */
export const MAINTENANCE_BYPASS_MAX_AGE = 12 * 60 * 60;

/**
 * چند ثانیه بعد دوباره سر بزن.
 *
 * ⚠️ عددِ کوچک و نه بزرگ. `Retry-After` بلند یعنی گوگل هم دیرتر برمی‌گردد و
 * صفحهٔ بروزرسانی بیشتر در کشِ میانی‌ها می‌ماند. ده دقیقه برای هر دو کافی
 * است و اگر بروزرسانی طول کشید، خزنده چند بار دیگر می‌آید — که همان چیزی
 * است که می‌خواهیم.
 */
export const RETRY_AFTER_SECONDS = 600;

export type MaintenanceState = {
  on: boolean;
  /** متنی که مالک نوشته، یا `null` برای متنِ پیش‌فرضِ صفحه. */
  message: string | null;
};

function isOn(value: string | null): boolean {
  if (!value) return false;
  const v = value.trim().toLowerCase();
  return v === "on" || v === "true" || v === "1" || v === "yes";
}

/**
 * وضعیتِ فعلی.
 *
 * ⚠️ اگر خواندنِ تنظیمات شکست بخورد، پاسخ **خاموش** است و نه روشن.
 *
 * این انتخاب یک بار برعکس نوشته شد و باید برمی‌گشت: با پیش‌فرضِ «روشن»، یک
 * قطعیِ کوتاهِ دیتابیس کلِ سایت را پشتِ صفحهٔ بروزرسانی می‌برد — یعنی یک
 * خرابیِ کوچک به یک خاموشیِ کامل تبدیل می‌شد. با پیش‌فرضِ «خاموش»، همان
 * قطعی فقط خودش را نشان می‌دهد و صفحه‌هایی که به دیتابیس نیاز ندارند
 * سرِ پا می‌مانند.
 */
export async function maintenanceState(): Promise<MaintenanceState> {
  try {
    const [flag, message] = await Promise.all([
      getSetting("site.maintenance"),
      getSetting("site.maintenance_message"),
    ]);
    return { on: isOn(flag), message: message?.trim() || null };
  } catch (err) {
    logger.error("خواندن وضعیت بروزرسانی شکست خورد؛ سایت باز ماند", {
      event: "site.maintenance.read_failed",
      err,
    });
    return { on: false, message: null };
  }
}

/**
 * آیا این رشته همان کلیدِ عبور است؟
 *
 * ⚠️ مقایسه در زمانِ ثابت نیست و لازم هم نیست: این کلید «رازِ امنیتی» به آن
 * معنا نیست — بدترین کاری که با آن می‌شود کرد، دیدنِ سایتی است که فردا
 * برای همه باز می‌شود. (رازهایی که واقعاً حمله‌پذیرند — توکنِ سشن و
 * `CRON_SECRET` — مقایسهٔ زمان‌ثابت دارند.)
 *
 * ⚠️ کلیدِ ثبت‌نشده یعنی این راه **بسته** است و نه «هر کسی رد می‌شود». یک
 * تنظیمِ خالی نباید به اجازهٔ عبور ترجمه شود.
 */
export async function bypassKeyMatches(provided: string | undefined): Promise<boolean> {
  if (!provided) return false;
  const expected = (await getSetting("site.maintenance_bypass_key"))?.trim();
  if (!expected) return false;
  return provided === expected;
}
