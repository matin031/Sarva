import { absoluteUrl } from "@/lib/seo/site";
import { encodeQr, qrToSvg } from "@/lib/qr/encode";

/**
 * لینک و QRِ دعوتِ کلاس.
 *
 * ⚠️ عمداً بدونِ `"server-only"`: هیچ چیزِ این فایل به دیتابیس یا رازی دست
 * نمی‌زند و کامپوننتِ کلاینت هم باید بتواند لینک را از کد بسازد (مثلاً
 * بعد از چرخاندنِ کد، بدونِ یک رفت‌وبرگشتِ دیگر).
 *
 * =============================================================================
 * ⚠️ چرا مسیرِ `/panel/classes?join=…` و نه یک صفحهٔ عمومیِ `/join/[code]`
 * =============================================================================
 *
 * یک صفحهٔ عمومی یعنی هر کسی با یک کد — از جمله کسی که کد را حدس زده —
 * بتواند **بدونِ حساب** نام کلاس، مدرسه و دبیر را ببیند. مسیرِ داخلِ پنل
 * از همان اول پشتِ ورود است: کاربرِ ناشناس به صفحهٔ ورود می‌رود و فقط پس
 * از احراز هویت چیزی می‌بیند.
 *
 * و یک صرفه‌جوییِ واقعی: مسیرِ تازه‌ای ساخته نمی‌شود، همان صفحه‌ای که
 * دانش‌آموز بعدش هم به آن برمی‌گردد کارش را می‌کند.
 */

/** پارامترِ آدرس که کدِ دعوت در آن می‌نشیند. */
export const JOIN_PARAM = "join";

/** مسیرِ داخلیِ دعوت — بدونِ دامنه. */
export function invitePath(joinCode: string): string {
  return `/panel/classes?${JOIN_PARAM}=${encodeURIComponent(joinCode)}`;
}

/**
 * لینکِ کاملِ دعوت.
 *
 * ⚠️ دامنه از `absoluteUrl` می‌آید و نه از هدرِ `Host`. اگر از هدر خوانده
 * می‌شد، هر کسی با یک درخواستِ دستکاری‌شده می‌توانست کاری کند که دبیر یک
 * لینکِ دعوت با دامنهٔ **دیگری** کپی کند و به کلاسش بدهد.
 * (استدلالِ کاملش بالای `lib/seo/site.ts`.)
 */
export function inviteUrl(joinCode: string): string {
  return absoluteUrl(invitePath(joinCode));
}

/**
 * QRِ لینکِ دعوت، به‌صورت SVG.
 *
 * ⚠️ هیچ سرویسِ بیرونی‌ای در کار نیست — نه در زمانِ ساخت و نه در زمانِ
 * نمایش. لینکِ دعوت کدِ عضویتِ کلاس را دارد؛ فرستادنش به سرورِ یک شرکتِ
 * دیگر برای «تولیدِ تصویر» دقیقاً همان چیزی است که این قابلیت باید از آن
 * محافظت کند. (چراییِ کامل بالای `lib/qr/encode.ts`.)
 *
 * ⚠️ و QR به **کد** بند است و نه به کلاس: با چرخاندنِ کد، QRِ قبلی
 * خودبه‌خود بی‌اثر می‌شود، چون لینکی که در آن رمزگذاری شده دیگر کلاسی را
 * پیدا نمی‌کند.
 */
export function inviteQrSvg(joinCode: string, size = 220): string {
  return qrToSvg(encodeQr(inviteUrl(joinCode)), { size });
}
