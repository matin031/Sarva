/**
 * شکلِ داده‌هایِ پیامک — عمداً بدونِ هیچ import ای.
 *
 * ⚠️ چرا جدا از `./index`: آن فایل `server-only` است و به `lib/db` وصل، پس
 * هر ماژولی که فقط به *نوع*ها نیاز دارد — از جمله آداپترِ SMS.ir و تست‌هایش —
 * با import کردنش کلِ زنجیرهٔ دیتابیس را هم می‌کشید. تست‌ها با
 * `node --test` اجرا می‌شوند و بدونِ شرطِ `react-server`؛ در آن حالت
 * `server-only` عمداً throw می‌کند.
 */

/** پیامکِ متنِ آزاد (خطِ تبلیغاتی/اطلاع‌رسانی). */
export type SmsMessage = {
  to: string;
  body: string;
};

/**
 * کدِ یک‌بارمصرف.
 *
 * ⚠️ چرا `code` و نه یک متنِ آماده: خطِ خدماتی متنِ دلخواه نمی‌پذیرد. متن باید
 * از قالبِ تأییدشده در پنلِ سرویس بیاید و فقط متغیرش پر شود. شناسهٔ قالب هم
 * اینجا نیست چون تنظیمِ سایت است و نه تصمیمِ فراخوان — `lib/sms` خودش
 * می‌خواندش.
 */
export type SmsOtpMessage = {
  to: string;
  code: string;
};

/** شناسهٔ پیام در سمتِ سرویس — برای پیگیری. `null` یعنی سرویس نداد. */
export type SmsSendResult = { providerMessageId: string | null };

export interface SmsAdapter {
  readonly name: string;
  send(message: SmsMessage): Promise<SmsSendResult>;
  /**
   * ارسال با یک قالبِ دلخواه — همان مسیرِ `sendOtp` ولی برای رویدادهای
   * دیگر (خوش‌آمد، فعال‌سازیِ اشتراک، یادآوریِ تمدید).
   *
   * ⚠️ جدا از `sendOtp` مانده و با آن یکی نشده، با اینکه هر دو یک endpoint
   * را صدا می‌زنند: `sendOtp` کدِ ورود را از هر پیامِ خطایی **پاک** می‌کند
   * و آن رفتار نباید با یک پارامترِ اختیاری قابلِ خاموش‌شدن باشد.
   */
  sendTemplate(message: SmsTemplateMessage): Promise<SmsSendResult>;
  /**
   * ارسالِ کد با قالبِ تأییدشده.
   *
   * ⚠️ اختیاری نیست. در نسخهٔ قبلی بود و هر فراخوان باید یادش می‌ماند که
   * نبودنش را چک کند — وگرنه کدِ ورود بی‌صدا از مسیرِ متنِ آزاد می‌رفت.
   */
  sendOtp(message: SmsOtpMessage): Promise<SmsSendResult>;
}

/**
 * پیامکِ **قالبی** — متنی که پنلِ سرویس از پیش تأیید کرده و ما فقط
 * متغیرهایش را پر می‌کنیم.
 *
 * ⚠️ چرا این و نه `SmsMessage` برای اطلاع‌رسانی‌ها:
 *
 * خطِ خدماتی (همان خطی که کدِ ورود از آن می‌رود) متنِ آزاد نمی‌پذیرد. پیامکِ
 * «اشتراکت فعال شد» یک پیامِ خدماتی است و باید از همان خط برود — اگر از خطِ
 * تبلیغاتی برود، هم دیرتر می‌رسد، هم برای کاربری که تبلیغات را بسته اصلاً
 * نمی‌رسد، و هم از نظرِ قوانینِ اپراتور در جای اشتباهی نشسته.
 *
 * پس هر رویدادِ اطلاع‌رسانی شناسهٔ قالبِ خودش را دارد (تنظیمات → پیامک) و
 * تا وقتی آن شناسه ثبت نشده، آن پیامک **فرستاده نمی‌شود** و نه اینکه
 * بی‌سروصدا از مسیرِ متنِ آزاد برود.
 */
export type SmsTemplateMessage = {
  to: string;
  templateId: number;
  /**
   * نامِ متغیرها باید **دقیقاً** با قالبِ تأییدشده یکی باشد.
   *
   * ⚠️ نامِ غلط خطا نمی‌دهد: SMS.ir پیامکی می‌فرستد که جای آن متغیر در آن
   * خالی است. یعنی تنها راهِ فهمیدنش، دیدنِ پیامکِ واقعی است.
   */
  parameters: { name: string; value: string }[];
};
