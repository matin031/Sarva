import "server-only";
import { NextResponse } from "next/server";

/* ═══════════════════════════════════════════════════════════════════════════
   یک ۴۰۹ که رابط کاربری بتواند بفهمدش.
   ═══════════════════════════════════════════════════════════════════════════

   ⚠️ چرا اینجا و نه در `lib/api/http.ts`:

   شکلِ پاسخِ کلِ API یک قرارداد است — `{ ok, data } | { ok, errors }` — و
   هر route و هر کامپوننتِ این پروژه رویش حساب می‌کند. اضافه کردنِ یک
   فیلدِ اجباری به آن قرارداد برای نیازِ *یک* بازی، هزینه‌اش را به همه‌جا
   پخش می‌کند.

   پس این تابع همان شکل را نگه می‌دارد و فقط یک فیلدِ **اختیاری** کنارش
   می‌گذارد. هر مصرف‌کنندهٔ دیگری که این پاسخ را بخواند، دقیقاً همان
   `{ ok: false, errors: [...] }`ِ همیشگی را می‌بیند و `code` را نادیده
   می‌گیرد؛ فقط `lib/kimia/source.ts` سراغش می‌رود.

   ⚠️ و چرا اصلاً کد لازم است: بدونِ آن، تنها راهِ تشخیصِ «تلاش‌هایت تمام
   شد» از «پاسخ را قبلاً دیدی» تطبیقِ متنِ فارسیِ خطاست — یعنی یک رابط
   کاربری که با ویرایشِ یک جملهٔ نمایشی می‌شکند.

   ⚠️ متن‌ها عمداً هیچ‌چیز دربارهٔ *پاسخ* نمی‌گویند. کسی که با اسکریپت
   تلاشِ چهارم می‌فرستد نباید از خودِ پیامِ خطا چیزی دربارهٔ وزن بفهمد.
   ═══════════════════════════════════════════════════════════════════════════ */

const NO_STORE = {
  "cache-control": "no-store, no-cache, must-revalidate, private",
  pragma: "no-cache",
} as const;

/** کدهای ماشین‌خوانِ «این دور دیگر تلاش نمی‌پذیرد». */
export type KimiaClosedCode = "attempts-exhausted" | "already-revealed" | "no-attempt-yet";

const MESSAGE: Record<KimiaClosedCode, string> = {
  "attempts-exhausted": "تلاش‌های این بیت تمام شده است.",
  "already-revealed": "پاسخِ این بیت قبلاً نشان داده شده است.",
  "no-attempt-yet": "اول یک بار ترکیب را آزمایش کن.",
};

/**
 * ۴۰۹ با کدِ ماشین‌خوان.
 *
 * بدنه همان `ApiResult`ِ ناموفق است، به‌اضافهٔ `code`.
 */
export function closedFail(code: KimiaClosedCode) {
  return NextResponse.json(
    { ok: false as const, errors: [MESSAGE[code]], code },
    { status: 409, headers: NO_STORE },
  );
}
