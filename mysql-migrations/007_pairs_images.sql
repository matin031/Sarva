-- =============================================================================
--
-- یک ستون به `memory_pairs` اضافه می‌شود: نشانیِ تصویرِ آن جفت — همان
-- نگاره‌ای که پدیدآورنده را کنارِ کتابش نشان می‌دهد.
--
-- ⚠️ چرا *یک* تصویر برای هر جفت و نه دو تصویرِ جدا (یکی برای اثر و یکی برای
-- پدیدآورنده):
--
-- چیزی که دانش‌آموز باید به‌خاطر بسپارد خودِ **پیوند** است، نه دو شیءِ
-- مستقل. نگاره‌ها هم دقیقاً همین‌اند: شاعر و کتابش در یک قاب، با برچسبِ نام
-- روی جلد. دو ستونِ جدا یعنی دو تصویری که باید کنار هم معنا بدهند ولی هیچ
-- چیز در اسکیما تضمین نمی‌کند بدهند.
--
-- ⚠️ و چرا یک رشته و نه یک جدولِ فایل: همان قاعده‌ای که lib/storage.ts رویش
-- ایستاده — «چیزی که در دیتابیس می‌ماند فقط یک نشانی است و هیچ‌کجای اسکیما
-- نمی‌داند آن نشانی به کجا اشاره می‌کند». امروز /uploads/pair-images/… است،
-- فردا می‌تواند هر چیز دیگری باشد، بی‌آنکه این ستون عوض شود.
--
-- خالی بودن مجاز است و معنایش «هنوز نگاره‌ای ندارد» است: صفحهٔ مرور در بازی
-- برای چنین جفتی یک کتابِ تزئینی می‌کشد، پس یک دستهٔ بی‌تصویر هم بازی را
-- نمی‌شکند.

ALTER TABLE `memory_pairs`
  ADD COLUMN `image` VARCHAR(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin
  NOT NULL DEFAULT '' AFTER `author`;
