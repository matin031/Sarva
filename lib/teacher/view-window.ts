/**
 * پنجرهٔ خاموشیِ اعلانِ «دبیر عملکردت را دید» — منطقِ خالص.
 *
 * ⚠️ چرا فایلِ جدا و نه داخلِ `lib/teacher/views.ts`:
 *
 * همان الگوی `doc-paths.ts` و `analytics-rules.ts`. آن ماژول
 * `"server-only"` است و هیچ تستی نمی‌تواند واردش کند — و این قاعده دقیقاً
 * همان چیزی است که اگر بشکند، دانش‌آموز ده اعلانِ تکراری می‌گیرد،
 * اعلان‌ها را خاموش می‌کند، و اعلانِ *واقعیِ* بعدی را هم نمی‌بیند.
 */

/**
 * ⚠️ شش ساعت، نه چند دقیقه و نه یک روز:
 *
 *   • چند دقیقه جلوی تازه‌سازیِ پیاپی را می‌گیرد ولی نه جلوی «صبح نگاه
 *     کردم، ظهر دوباره» — که از نظرِ دانش‌آموز یک بررسیِ ادامه‌دار است و
 *     دو اعلان می‌گیرد.
 *   • یک روزِ کامل یعنی دبیری که عصر پس از یک آزمون واقعاً دوباره بررسی
 *     می‌کند، آن بار هیچ خبری نمی‌دهد.
 */
export const NOTIFY_WINDOW_HOURS = 6;

/**
 * آیا از آخرین بازدید به‌اندازهٔ کافی گذشته؟
 *
 * ⚠️ `previousIso` باید بازدیدِ **قبلی** باشد و نه همینی که تازه ثبت شده —
 * وگرنه پنجره همیشه صفر است و هیچ اعلانی هرگز ساخته نمی‌شود.
 */
export function shouldNotify(previousIso: string | null, now: Date): boolean {
  if (previousIso === null) return true;

  const previous = Date.parse(previousIso);

  /* ⚠️ تاریخِ بدشکل → اعلان ساخته می‌شود.
     در تردید، به نفعِ *شفافیت برای دانش‌آموز* تصمیم گرفته می‌شود: اعلانِ
     اضافه آزاردهنده است، ولی اعلانی که نیامده یعنی کسی بی‌خبر عملکردِ او
     را دیده. */
  if (!Number.isFinite(previous)) return true;

  return now.getTime() - previous >= NOTIFY_WINDOW_HOURS * 60 * 60 * 1000;
}

/** سطلِ ساعتیِ UTC — فقط برای کلیدِ یکتاسازیِ اعلان. */
export function hourBucket(at: Date): number {
  return Math.floor(at.getTime() / (60 * 60 * 1000));
}
