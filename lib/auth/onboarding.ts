import type { AuthUser } from "./types";

/**
 * «آیا این حساب هنوز نیمه‌ساخته است؟» — یک قاعده، یک فایل.
 *
 * ⚠️ عمداً بدون `"server-only"`: هم `proxy.ts` و مسیرهای API از آن استفاده
 * می‌کنند و هم صفحهٔ تکمیل که کاربر را از روی `/api/v1/auth/me` می‌خواند.
 * چیزی محرمانه‌ای اینجا نیست — فقط یک شرط روی دو ستون.
 *
 * ── چرا اصلاً لازم شد ─────────────────────────────────────────────────────
 * سه راهِ ورود به سروا وجود دارد و دوتایشان حسابی می‌سازند که **هیچ نامی
 * ندارد**:
 *
 *   • ورود با گوگل — `full_name` را از گوگل می‌گیرد، ولی آن نام ممکن است
 *     لاتین باشد («Matin Jafari») و `first_name`/`last_name` هرگز پر
 *     نمی‌شوند.
 *   • ورود با کدِ پیامکی — حساب فقط یک شماره دارد و بس.
 *
 * نتیجه‌اش در پنل «سلام دانش‌آموز» بود، و در سروا کلاب یک سروده بدونِ
 * نویسنده. پس از امروز این حساب‌ها پیش از هر کارِ دیگری باید نامشان را
 * بنویسند.
 *
 * ⚠️ معیار `first_name`/`last_name` است و نه `full_name`.
 *
 * `full_name` مشتق است (تریگرِ مهاجرت ۰۰۹) و برای کاربرِ گوگل از نامِ گوگل
 * پر می‌شود — یعنی اگر معیار آن بود، دقیقاً همان کاربری که این گیت برایش
 * ساخته شده از آن رد می‌شد.
 */
export function needsOnboarding(
  user: Pick<AuthUser, "firstName" | "lastName"> | null | undefined,
): boolean {
  if (!user) return false;
  return !user.firstName?.trim() || !user.lastName?.trim();
}

