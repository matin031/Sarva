export function matchCost(scan: string, pat: string): number {
  if (scan.length !== pat.length) return 999;
  let c = 0.0;
  for (let i = 0; i < scan.length; i++) {
    if (i === scan.length - 1) continue;
    const a = scan[i];
    const b = pat[i];
    if (a === b || b === "x") continue;
    c += a === "U" && b === "-" ? 0.5 : 1.0;
  }
  return c;
}

