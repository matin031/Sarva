"use client";

/* ═══════════════════════════════════════════════════════════════════════════
   رویدادهای صوتی — امروز خاموش، فردا بی‌دردسر.
   ═══════════════════════════════════════════════════════════════════════════

   هنوز هیچ فایلِ صوتی‌ای برای این بازی وجود ندارد، و ساختنِ یک لایهٔ صوتیِ
   کامل برای صداهایی که نداریم یعنی کدِ مرده.

   ولی *جای* شلیکِ صدا را نمی‌شود بعداً پیدا کرد: اگر امروز این فراخوانی‌ها
   نباشند، افزودنِ صدا یعنی گشتن در همهٔ کامپوننت‌ها دنبالِ «کجا کتاب کوبیده
   می‌شود؟». پس رویدادها همین حالا در جای درستشان شلیک می‌شوند و فعلاً به
   جایی نمی‌روند.

   ⚠️ مهم‌تر از همه: هیچ‌جای منطقِ بازی به بازگشتِ این تابع وابسته نیست.
   `emit` هیچ‌وقت چیزی برنمی‌گرداند و هیچ‌وقت throw نمی‌کند، پس نبودِ صدا
   نمی‌تواند دور را متوقف کند.

   وصل‌کردن در آینده:

       setSoundHandler((event) => myPlayer.play(event.type));
   ═══════════════════════════════════════════════════════════════════════════ */

export type GameSound =
  /** بازیکن کتابی را انتخاب کرد. */
  | "select"
  /** شخصیت شروع به دویدن کرد. */
  | "runStart"
  /** شخصیت رسید و ایستاد. */
  | "arrive"
  /** کتاب از طاقچه کنده شد. */
  | "bookLift"
  /** کتاب روی سر کوبیده شد. */
  | "slam"
  /** ستاره‌های گیجی ظاهر شدند. */
  | "dizzy"
  /** پاسخِ درست. */
  | "success"
  /** دورِ تازه. */
  | "roundStart";

export interface SoundEvent {
  type: GameSound;
  /** بلندیِ نسبی، ۰ تا ۱. مثلاً شدتِ برخورد. */
  gain?: number;
}

type Handler = (event: SoundEvent) => void;

let handler: Handler | null = null;

/** شنوندهٔ صدا را می‌نشاند (یا با `null` برمی‌دارد). */
export function setSoundHandler(next: Handler | null): void {
  handler = next;
}

/** یک رویدادِ صوتی. بی‌صدا شکست می‌خورد و هرگز throw نمی‌کند. */
export function emitSound(type: GameSound, gain?: number): void {
  if (!handler) return;
  try {
    handler({ type, gain });
  } catch {
    /* صدا هرگز نباید بازی را بشکند. */
  }
}
