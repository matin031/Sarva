export type SessionLength = (typeof KIMIA_CONFIG.sessionLengths)[number];

/**
 * ⚠️ نگهبانِ طولِ نشست — خالص، تا هم رابط کاربری و هم تست یک قاعده را
 * ببینند. هر چیزی جز ۵، ۱۰ و ۱۵ رد می‌شود؛ مقدارِ نامعتبر به پیش‌فرض
 * برمی‌گردد و نه به یک عددِ دلبخواه، تا «۰ بیت» یا «۱۰۰۰ بیت» هیچ‌وقت
 * ساخته نشود.
 */
export function isSessionLength(value: unknown): value is SessionLength {
  return (
    typeof value === "number" &&
    (KIMIA_CONFIG.sessionLengths as readonly number[]).includes(value)
  );
}

export function coerceSessionLength(value: unknown): SessionLength {
  return isSessionLength(value) ? value : KIMIA_CONFIG.defaultSessionLength;
}
