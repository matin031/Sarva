import { KIMIA_FOOT_CATALOG, footPattern, normalizeFoot, type FootKey } from "./catalog";

/* ═══════════════════════════════════════════════════════════════════════════
   هویتِ دیداریِ ارکان — یک نگاشتِ مرکزی، و هیچ رنگی جای دیگری.
   ═══════════════════════════════════════════════════════════════════════════

   کلِ بازی روی یک زنجیرهٔ حافظه بنا شده:

       رکن  →  رنگ  →  نشانه  →  جایگاه روی رَک  →  صدا

   اگر رنگِ «مفاعیلن» در دو فایل دو جور نوشته شود، آن زنجیره همان‌جا پاره
   می‌شود. پس هیچ رنگِ رکنی داخلِ کامپوننت یا CSS نوشته نمی‌شود؛ همه از
   اینجا می‌آید و CSS آن را به‌صورتِ متغیرِ درون‌خطی می‌گیرد.

   ── پالت چطور انتخاب شد ─────────────────────────────────────────────────
   ⚠️ دستی چیده نشد و «خوشگل به نظر می‌رسید» ملاک نبود. شانزده رنگ روی
   زمینهٔ شبِ سروا باید هم‌زمان چهار شرط را برآورند، و چهارتایی که با چشم
   جور نمی‌شوند:

     ۱) فاصلهٔ ادراکیِ کافی، دوبه‌دو، در دیدِ عادی
     ۲) همان فاصله در سه‌گونهٔ رایجِ کوررنگی (پروتان، دوتِران، تریتان)
     ۳) کنتراستِ کافی با زمینهٔ تیره *و* دیده‌شدن روی زمینهٔ روشن
     ۴) فاصله از فیروزهٔ سروا، چون دکمهٔ «آزمایش ترکیب» آن رنگ است و نباید
        با یک ماده اشتباه شود

   پس با یک جست‌وجوی محلی روی OKLCH بهینه شد و `tests/kimia/visuals.test.ts`
   همان چهار شرط را دوباره می‌سنجد. عوض کردنِ یک هگز بدونِ گذراندنِ آن تست
   ممکن نیست — که دقیقاً هدف است.

   کمینهٔ اندازه‌گیری‌شدهٔ فاصلهٔ دوبه‌دو (فاصلهٔ اقلیدسی در OKLab):
       دیدِ عادی ۰٫۰۹۹ · پروتان ۰٫۰۵۶ · دوتِران ۰٫۰۳۸ · تریتان ۰٫۰۵۷

   ⚠️ دوتِران ۰٫۰۳۸ عمداً پذیرفته شد و پنهان نمی‌شود: شانزده رنگ روی یک
   زمینه، سقفِ چیزی است که نگاشتِ رنگی می‌تواند بدهد. برای همین **رنگ
   هیچ‌وقت تنها نشانهٔ هویت نیست**: هر ماده هم‌زمان رنگ، نشانهٔ هجایی و
   برچسبِ فارسی دارد، در ویال و در جایگاهِ پرشدهٔ مخزن. رنگ کمکِ حافظه است،
   نه راهِ تشخیص.
   ═══════════════════════════════════════════════════════════════════════════ */

export type FootVisual = {
  /** رنگِ پایهٔ جوهر. سایه‌روشنِ مایع از همین ساخته می‌شود (`mix.ts`). */
  readonly color: string;
  /**
   * الگوی هجایی — `-` بلند، `U` کوتاه.
   *
   * ⚠️ نشانهٔ هر ماده همین است و نه یک شکلِ دلبخواه، و این تصمیم آموزشی
   * است: یک مثلث یا لوزیِ تصادفی فقط یک «آیکونِ متفاوت» است، ولی
   * `U - - -` *تعریفِ خودِ مفاعیلن* است. دانش‌آموز هر بار که به رَک نگاه
   * می‌کند، جدولِ ارکان را هم می‌بیند.
   *
   * ⚠️ و لو نمی‌دهد: الگوی هر ماده روی *همهٔ* ویال‌ها هست، نه فقط
   * درست‌ها. کاری که می‌کند این است که بازی را از حدس زدن به تقطیع کردن
   * می‌برد — یعنی دقیقاً همان مهارتی که قرار است تمرین شود.
   *
   * یکتاییِ نشانه از همین‌جا تضمین می‌شود: هیچ دو رکنِ این کاتالوگ الگوی
   * هجاییِ یکسان ندارند (تستِ `visuals.test.ts` می‌سنجدش).
   */
  readonly pattern: string;
};

/**
 * ⚠️ کلیدها همان کلیدهای متعارفِ `ARKAN` اند و نه برچسبِ آزاد. تستِ
 * کاملیِ کاتالوگ هر رکنِ جامانده یا اضافه را رد می‌کند، پس این شیء
 * هیچ‌وقت نمی‌تواند بی‌صدا از `catalog.ts` عقب بماند.
 */
const FOOT_COLORS: Readonly<Record<FootKey, string>> = {
  // یک‌هجایی و دوهجایی — کوتاه‌ها، در طیفِ گرمِ روشن
  فع: "#e1cb83",
  فعل: "#d47927",
  // سه‌هجایی
  مفعول: "#f29c82",
  فاعلن: "#c75750",
  فعولن: "#feabd3",
  فعلن: "#bf669a",
  // چهارهجایی
  مستفعلن: "#d392db",
  فاعلاتن: "#9364c0",
  فاعلات: "#a1b3fb",
  مفتعلن: "#958bed",
  مفاعیلن: "#58d7f1",
  مفاعیل: "#4182d7",
  مفاعلن: "#90d9b0",
  فعلاتن: "#69b054",
  فعلات: "#b5bd42",
  // پنج‌هجایی
  متفاعلن: "#9a9258",
};

/** رنگِ پشتیبان برای رکنی که نگاشت ندارد. */
const FALLBACK_COLOR = "#7c8796";

/**
 * نگاشتِ نهایی: رنگِ دست‌چین + الگوی مشتق از `ARKAN`.
 *
 * ⚠️ رفتارِ رکنِ ناشناخته عمداً دو حالت دارد:
 *   • در production رنگِ خنثی می‌گیرد و صفحه **نمی‌شکند** — یک نگاشتِ
 *     ناقص نباید وسطِ درس خواندنِ کسی یک صفحهٔ سفید بسازد.
 *   • در تست/توسعه `tests/kimia/visuals.test.ts` همان حالت را *رد* می‌کند.
 * یعنی خطا دیده می‌شود، ولی کاربر هزینه‌اش را نمی‌دهد.
 */
export const FOOT_VISUALS: Readonly<Record<FootKey, FootVisual>> = (() => {
  const out: Record<FootKey, FootVisual> = {};
  for (const [foot, color] of Object.entries(FOOT_COLORS)) {
    const key = normalizeFoot(foot);
    out[key] = { color, pattern: footPattern(key) ?? "" };
  }
  return out;
})();

export function footVisual(foot: FootKey): FootVisual {
  return (
    FOOT_VISUALS[normalizeFoot(foot)] ?? {
      color: FALLBACK_COLOR,
      pattern: footPattern(foot) ?? "",
    }
  );
}

export function footColor(foot: FootKey): string {
  return footVisual(foot).color;
}

/** رنگِ همهٔ ارکانِ یک دنباله، به همان ترتیب. ورودیِ ترکیب‌کنندهٔ رنگ. */
export function sequenceColors(feet: readonly FootKey[]): string[] {
  return feet.map(footColor);
}

/** ارکانی که نگاشتِ دیداری ندارند — فقط برای تست و ابزارِ توسعه. */
export function missingVisuals(): FootKey[] {
  return KIMIA_FOOT_CATALOG.filter((foot) => !(foot in FOOT_VISUALS));
}
