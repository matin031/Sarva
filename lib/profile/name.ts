import { z } from "zod";

/**
 * قانونِ «نامِ فارسی» — جدا از بقیهٔ فرمِ پروفایل، و این جدایی عمدی است.
 *
 * =============================================================================
 * ⚠️ چرا این فایل وجود دارد
 * =============================================================================
 *
 * همین دو فیلد را حالا چهار جا لازم دارند: فرمِ پروفایل، صفحهٔ تکمیلِ حساب،
 * فرمِ ثبت‌نام، و `lib/auth/schemas.ts`. سه‌تای اولشان کلاینت‌اند.
 *
 * تا وقتی این دو داخلِ `lib/profile/schemas.ts` بودند، هر کدام از آن
 * صفحه‌ها کلِ آن فایل را هم می‌آوردند — و آن فایل `isValidLocation` را از
 * `@/lib/geo` می‌گیرد، که یک JSON چهل‌وهفت‌کیلوبایتی از استان‌ها و شهرهای
 * ایران است. یعنی صفحهٔ *ورود* برای اینکه بگوید «نام را به فارسی بنویس»،
 * فهرستِ همهٔ شهرهای کشور را به مرورگر می‌فرستاد.
 *
 * همان کاری که `lib/auth/duration.ts` و `lib/db/errors.ts` برای همین جنس
 * مشکل کردند: قانون به فایلِ خودش می‌رود و فایلِ قبلی دوباره export اش
 * می‌کند، پس هیچ کدِ مصرف‌کننده‌ای تغییر نمی‌کند.
 */

/**
 * ⚠️ نیم‌فاصله (`‌`) در فهرستِ مجاز است و نبودش یک باگِ واقعی می‌ساخت:
 * «حسین‌زاده» با نیم‌فاصله نوشته می‌شود و بدونِ آن نویسه، پیامِ «نام را به
 * فارسی بنویس» به کسی نشان داده می‌شد که دقیقاً همان کار را کرده بود.
 */
const PERSIAN_NAME = /^[؀-ۿ‌\s]+$/;

/**
 * ⚠️ سقف ۴۰ و نه ۱۲.
 *
 * نسخهٔ قدیمی یک فیلدِ واحد برای *کلِ* نام بود و ۱۲ نویسه برایش بس بود.
 * حالا دو فیلدِ جداست و نام خانوادگی به آن سقف نمی‌خورد: «قره‌باغی نیاسر»
 * هفده نویسه است و یک نامِ کاملاً واقعی.
 */
export const firstNameField = z
  .string()
  .trim()
  .min(2, "نام باید دستِ‌کم ۲ حرف باشد")
  .max(40, "نام حداکثر ۴۰ حرف است")
  .regex(PERSIAN_NAME, "نام را به فارسی بنویس");

export const lastNameField = z
  .string()
  .trim()
  .min(2, "نام خانوادگی باید دستِ‌کم ۲ حرف باشد")
  .max(40, "نام خانوادگی حداکثر ۴۰ حرف است")
  .regex(PERSIAN_NAME, "نام خانوادگی را به فارسی بنویس");
