import { randomInt } from "node:crypto";

/**
 * کدِ عضویتِ کلاس.
 *
 * ⚠️ عمداً بدون `"server-only"`: `normalizeJoinCode` را فرمِ دانش‌آموز هم
 * لازم دارد تا پیش از ارسال، کدِ تایپ‌شده را یکدست کند. تولیدِ کد
 * (`generateJoinCode`) فقط سمتِ سرور صدا زده می‌شود، ولی چیزی در آن نیست که
 * دانستنش کمکی به کسی بکند — امنیتش از *فضای* کد می‌آید و نه از پنهان بودنِ
 * الگوریتم.
 *
 * ── الفبا ──────────────────────────────────────────────────────────────────
 * ⚠️ `I`، `O`، `0` و `1` در الفبا نیستند.
 *
 * این کد قرار است روی تخته نوشته شود، از روی آن تایپ شود، یا تلفنی خوانده
 * شود. با هر چهارِ آن‌ها، «آیا این صفر است یا اُ؟» یک سؤالِ واقعی است — و
 * جوابِ اشتباهش یعنی دانش‌آموزی که فکر می‌کند دبیرش کدِ غلط داده.
 *
 * ── طول ────────────────────────────────────────────────────────────────────
 * ۳۲ نویسه و ۶ رقم → حدود یک میلیارد ترکیب. با چند هزار کلاسِ فعال، شانسِ
 * حدس زدنِ یک کدِ معتبر عملاً صفر است — و سقفِ نرخ در `joinClass` همان شانس
 * را هم می‌گیرد.
 */

/** ⚠️ بدونِ I، O، 0 و 1. با `teacher_classes_join_code_check` در migration
 *  ۰۰۹ می‌خواند؛ عوض کردنِ یکی بدونِ دیگری یعنی کدی که تولید می‌شود و
 *  دیتابیس ردش می‌کند. */
const ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

const CODE_LENGTH = 6;

/**
 * یک کدِ تازه.
 *
 * ⚠️ `randomInt` از `node:crypto` و نه `Math.random`. کدِ عضویت تنها چیزی
 * است که بینِ یک غریبه و فهرستِ دانش‌آموزانِ یک کلاس ایستاده؛ یک مولدِ
 * قابلِ پیش‌بینی یعنی کسی که چند کد دیده، بتواند بقیه را حساب کند.
 */
export function generateJoinCode(): string {
  let code = "";
  for (let i = 0; i < CODE_LENGTH; i++) code += ALPHABET[randomInt(0, ALPHABET.length)];
  return code;
}

/**
 * کدی که کاربر تایپ کرده → شکلِ متعارف.
 *
 * حروفِ کوچک، فاصله، خط تیره و نیم‌فاصله همه پاک می‌شوند. کسی که «a7k-2p9»
 * می‌نویسد باید همان کلاس را پیدا کند.
 *
 * ⚠️ ارقامِ فارسی هم تبدیل می‌شوند: دانش‌آموزی که کیبوردش فارسی است «۲۳۴»
 * تایپ می‌کند و بدونِ این، کدِ کاملاً درستش رد می‌شد.
 */
export function normalizeJoinCode(raw: string): string {
  return raw
    .replace(/[۰-۹٠-٩]/g, (d) => {
      const code = d.charCodeAt(0);
      const base = code >= 0x06f0 ? 0x06f0 : 0x0660;
      return String(code - base);
    })
    .replace(/[\s\-‌‏‎]/g, "")
    .toUpperCase();
}
