import { absoluteUrl } from "./site";

/**
 * دادهٔ ساختاریافته (JSON-LD).
 *
 * ── چه چیزی اینجا هست و چه چیزی عمداً نیست ────────────────────────────────
 *
 * هست: `BreadcrumbList` — مسیرِ واقعیِ هر صفحه. سال‌هاست پشتیبانی می‌شود و
 * چیزی ادعا نمی‌کند جز آنچه خودِ ناوبریِ سایت نشان می‌دهد.
 *
 * ⚠️ نیست: امتیاز، نظر کاربر، `AggregateRating`، `Review`، `FAQPage`، مدرک،
 * قیمت. هیچ‌کدامِ این داده‌ها در سروا وجود ندارند و ساختنشان برای گرفتنِ
 * نتیجهٔ غنی‌تر، دقیقاً همان چیزی است که موتور جست‌وجو جریمه‌اش می‌کند — و
 * مهم‌تر، دروغ گفتن به کسی است که دنبالِ کلاسِ درس می‌گردد.
 *
 * ⚠️ و نیست: نوع‌های آموزشیِ `Course` / `LearningResource`. دلیلش نه بی‌ربط
 * بودنشان، بلکه این است که پشتیبانیِ *فعلیِ* گوگل از نتیجهٔ غنیِ آن‌ها را در
 * این محیط نتوانستم بررسی کنم (دسترسی به شبکه بسته است). افزودنِ نوعی که
 * پشتیبانی‌اش را ندیده‌ام یعنی ادعای بی‌پشتوانه. اگر مالک تأیید کرد، افزودنش
 * چند خط است.
 *
 * هیچ‌کدامِ این‌ها تضمینِ نتیجهٔ غنی یا رتبه نیست. schema فقط محتوا را
 * قابل‌فهم‌تر می‌کند؛ تصمیمِ نمایش با موتور جست‌وجوست.
 */

/**
 * سریال‌سازیِ امن برای نشستن داخلِ `<script>`.
 *
 * ⚠️ چرا لازم است: بعضی از این داده‌ها متنِ کاربر است — عنوانِ سروده و تخلصِ
 * شاعر در سروا کلاب. اگر کسی در عنوانش `</script>` بنویسد، `JSON.stringify`
 * خام آن را همان‌طور بیرون می‌دهد، مرورگر تگ را همان‌جا می‌بندد و بقیهٔ
 * رشته به‌عنوان HTML اجرا می‌شود.
 *
 * جایگزینیِ `<` با یونیکدِ فرارش، هم JSON را معتبر نگه می‌دارد و هم امکانِ
 * بستنِ تگ را می‌گیرد. U+2028 و U+2029 هم برای همین‌اند: در JSON مجازند ولی
 * در جاوااسکریپت پایانِ خط حساب می‌شوند.
 *
 * ⚠️ و همین دو کاراکتر، اولین بار که *خام* در همین فایل نوشته شدند، خودشان
 * ثابتش کردند: کامپایلر «unterminated regular expression literal» داد، چون
 * وسطِ الگو خط را شکسته بودند. حالا فقط با کدِ فرار نوشته می‌شوند.
 */
export function safeJsonLd(data: unknown): string {
  return JSON.stringify(data)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

export type Crumb = { name: string; path: string };

/**
 * `BreadcrumbList` از مسیرِ واقعیِ صفحه.
 *
 * ⚠️ آخرین حلقه هم `item` می‌گیرد. بعضی راهنماها می‌گویند آخری را بدونِ آدرس
 * بگذارید؛ ولی وقتی هر حلقه آدرسِ خودش را دارد، فهرست هم برای موتور جست‌وجو
 * بی‌ابهام‌تر است و هم با ناوبریِ دیده‌شدهٔ صفحه یکی می‌ماند.
 */
export function breadcrumbList(crumbs: readonly Crumb[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: crumbs.map((crumb, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: crumb.name,
      item: absoluteUrl(crumb.path),
    })),
  };
}
