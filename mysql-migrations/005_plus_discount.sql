-- =============================================================================
-- ۰۰۵ — قیمتِ پیش از تخفیف
-- =============================================================================
--
-- یک ستون به نسخهٔ پلن اضافه می‌شود: `compare_at_rials` — «قیمت قبل از
-- تخفیف»، همان عددی که خط‌خورده کنارِ قیمتِ فعلی نشان داده می‌شود.
--
-- ⚠️ چرا روی *نسخه* و نه روی پلن، و چرا یک ستونِ جدا به‌جای یک درصدِ تخفیف:
--
--   • روی نسخه، چون خودِ قیمت هم روی نسخه است. اگر تخفیف روی پلن می‌نشست،
--     عوض کردنش فاکتورِ خریدهای قبلی را هم عوض می‌کرد — دقیقاً همان چیزی که
--     نسخه‌بندی برای جلوگیری از آن ساخته شد.
--
--   • مبلغِ مطلق و نه درصد، چون درصد باید از چیزی حساب شود و آن «چیز» باید
--     ذخیره می‌شد. با مبلغ، هر دو عدد صریح‌اند و درصد در نمایش حساب می‌شود.
--
-- ⚠️ و مهم‌تر از هر دو: این ستون **قیمتِ واقعیِ قبلی** است، نه یک عددِ بزرگ‌تر
-- برای ساختنِ تخفیفِ جعلی. `plus_plans.ts` قبلاً این را نوشته بود و اینجا هم
-- همان قاعده است: «۵۰٪ تخفیف!» از قیمتی که هیچ‌وقت وجود نداشته، در این
-- پروژه ساخته نمی‌شود. تنها چیزی که دیتابیس می‌تواند تضمین کند این است که
-- عدد از قیمتِ فعلی بزرگ‌تر باشد؛ *واقعی* بودنش با مدیر است.

ALTER TABLE `plus_plan_versions`
  ADD COLUMN `compare_at_rials` BIGINT NULL AFTER `amount_rials`;

-- تخفیفِ صفر یا منفی معنایی ندارد و فقط رابط کاربری را گیج می‌کند.
ALTER TABLE `plus_plan_versions`
  ADD CONSTRAINT `plus_plan_versions_compare_at_check`
  CHECK (`compare_at_rials` IS NULL OR `compare_at_rials` > `amount_rials`);


-- =============================================================================
-- تریگرِ تغییرناپذیری — بازنویسی
-- =============================================================================
--
-- ⚠️ این تریگر در ۰۰۴ ساخته شد و باید *دوباره* ساخته شود، نه اینکه رهایش
-- کنیم. `compare_at_rials` بخشی از همان snapshotِ قیمتی است: اگر در فهرستِ
-- نگهبانی نباشد، مدیر می‌تواند تخفیفِ یک نسخهٔ فروخته‌شده را بعداً عوض کند و
-- فاکتورِ گذشته چیزِ دیگری نشان بدهد — همان دری که ۰۰۴ بسته بود، این بار از
-- کنار.
--
-- MySQL و MariaDB هیچ‌کدام `CREATE OR REPLACE TRIGGER`ِ قابلِ اتکا در هر دو
-- ندارند، پس اول DROP.

DROP TRIGGER IF EXISTS `plus_plan_versions_immutable_bu`;

DELIMITER $$
CREATE TRIGGER `plus_plan_versions_immutable_bu` BEFORE UPDATE ON `plus_plan_versions`
FOR EACH ROW
BEGIN
  -- ⚠️ `<=>` و نه `<>` برای ستونِ nullable.
  -- در SQL، `NULL <> NULL` نتیجه‌اش NULL است و نه TRUE — یعنی با `<>` ساده،
  -- تغییرِ NULL به NULL دیده نمی‌شد و بدتر، مقایسه‌های شاملِ NULL کلِ شرط را
  -- به NULL می‌بردند. `<=>` مقایسهٔ امن در برابر NULL است و `NOT (a <=> b)`
  -- دقیقاً یعنی «فرق کرده‌اند».
  IF NEW.`plan_id`       <> OLD.`plan_id`
  OR NEW.`version`       <> OLD.`version`
  OR NEW.`title`         <> OLD.`title`
  OR NEW.`duration_days` <> OLD.`duration_days`
  OR NEW.`amount_rials`  <> OLD.`amount_rials`
  OR NOT (NEW.`compare_at_rials` <=> OLD.`compare_at_rials`)
  OR NEW.`currency`      <> OLD.`currency` THEN
    SIGNAL SQLSTATE '45000'
      SET MESSAGE_TEXT = 'نسخهٔ پلن پس از ساخته‌شدن تغییر نمی‌کند؛ نسخهٔ تازه بسازید.';
  END IF;
END$$
DELIMITER ;
