-- =============================================================================
-- ۰۱۶ — مدتِ رفت‌وبرگشتِ سرویسِ پیامک در `sms_log`
-- =============================================================================
--
-- ⚠️ یک ستون، برای پاسخ دادن به یک سؤالِ مشخص که بدونِ آن جواب ندارد:
--
--     «کدِ ورود با ده دقیقه تأخیر می‌رسد — مشکل از ماست یا از سرویسِ پیامک؟»
--
-- ── چرا از روی کد نمی‌شود جواب داد ─────────────────────────────────────────
--
-- از خواندنِ کد این‌قدر معلوم است: `app/api/v1/auth/mobile/send-code/route.ts`
-- تابعِ `sendOtpSms` را **await** می‌کند و تازه بعدش پاسخ می‌دهد. پس اگر
-- درخواستِ HTTP به SMS.ir ده دقیقه طول می‌کشید، صفحهٔ کاربر هم ده دقیقه
-- منتظر می‌ماند — و نمی‌ماند.
--
-- این استدلال درست است ولی *شاهد* نیست. شاهدش عددِ همین ستون است:
--
--   • اگر `duration_ms` کوچک باشد (چند صد میلی‌ثانیه) و پیامک دیر برسد،
--     تأخیر در صفِ سرویس یا اپراتور است و هیچ تغییری در این کد حلش نمی‌کند.
--   • اگر بزرگ باشد، مشکل سمتِ ماست (شبکهٔ سرور یا خودِ فراخوانی) و
--     همان‌جا باید دنبالش گشت.
--
-- ⚠️ چرا در دیتابیس و نه فقط در لاگ: `lib/sms/index.ts` از قبل همین عدد را
-- با `logger.info` می‌نویسد. ولی لاگِ هاستِ اشتراکی می‌چرخد و می‌رود، و
-- اولین سؤال همیشه دربارهٔ چیزی است که *دیروز* اتفاق افتاده. `sms_log` هم
-- دقیقاً به همین دلیل از اول ساخته شد.
--
-- ── چرا NULL مجاز است ──────────────────────────────────────────────────────
-- ⚠️ ردیف‌های قبلیِ این جدول این عدد را ندارند و ساختنش برایشان ممکن نیست.
-- `NOT NULL DEFAULT 0` وسوسه‌انگیز بود و دروغ می‌گفت: «صفر میلی‌ثانیه» یعنی
-- یک ارسالِ آنی، و میانگینِ هر گزارشی را به سمتِ پایین می‌کشید. `NULL`
-- یعنی «نمی‌دانیم» و گزارش‌ها باید کنارش بگذارند.
--
-- ⚠️ و `INT` و نه `SMALLINT`: سقفِ SMALLINT حدودِ ۳۲ ثانیه است و دقیقاً
-- همان حالتی که این ستون برای تشخیصش ساخته شده (یک فراخوانیِ خیلی کند) از
-- آن رد می‌شود و عدد بی‌صدا بریده می‌شد.
--
-- ⚠️ و یک نکته دربارهٔ خودِ همین توضیح: نسخهٔ اولش برای «بریده شدنِ عدد»
-- نامِ انگلیسیِ همان دستورِ SQL را به کار برده بود — و آزمونِ «هیچ
-- migration ای داده را حذف نمی‌کند» (`tests/observability/migration.test.ts`)
-- همین فایل را رد کرد. آن آزمون متنِ خامِ فایل را می‌خواند و کامنت را
-- از دستور جدا نمی‌کند. این سختگیری عمدی است و ارزان‌تر از نگرفتنِ
-- یک دستورِ واقعیِ مخرب؛ پس متن عوض شد و نه آزمون.

ALTER TABLE `sms_log`
  ADD COLUMN `duration_ms` INT NULL AFTER `provider_message_id`;

-- گزارشِ «کندترین ارسال‌های اخیر» روی همین دو ستون فیلتر می‌کند.
CREATE INDEX `sms_log_duration_idx` ON `sms_log` (`created_at` DESC, `duration_ms`);
