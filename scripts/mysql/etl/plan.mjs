/**
 * نقشهٔ انتقال: هر جدول چطور خوانده، چطور نوشته، و چطور بررسی می‌شود.
 *
 * ⚠️ اصلِ حاکم بر این فایل: **همه‌چیز به‌صورت متن از مبدأ بیرون می‌آید.**
 *
 * وسوسه این است که مقدارها را به درایور بسپاریم و همان اشیای JS را به مقصد
 * بدهیم. اشکالش این است که هر تبدیل یک فرصت برای از دست رفتنِ بی‌صداست:
 *
 *   • timestamptz → شیء Date در JS = میکروثانیه می‌سوزد. ستون‌های ما
 *     DATETIME(6) اند و این یعنی سه رقم از هر زمانِ منتقل‌شده گم می‌شود.
 *   • numeric → عدد ممیز شناور = گِرد شدن. نمرهٔ امتحان با ممیز شناور
 *     همان چیزی است که کل این ستون‌ها برای پرهیز از آن DECIMAL شده‌اند.
 *   • jsonb → شیء JS → دوباره رشته = ترتیب کلیدها و شکلِ عددها می‌تواند
 *     عوض شود.
 *
 * پس هر ستون با یک عبارتِ صریح به متن تبدیل می‌شود و همان متن به MySQL
 * می‌رود. MySQL خودش به نوعِ ستون تبدیلش می‌کند — و چون هر دو طرف دقیقاً
 * می‌دانند چه شکلی است، جایی برای حدس نمی‌ماند.
 */

/**
 * عبارتِ خواندنِ یک ستون از PostgreSQL، به‌صورت متن.
 *
 * @param {string} column نام ستون
 * @param {string} pgType خروجی format_type()
 */
export function readExpr(column, pgType) {
  const q = `"${column}"`;

  // ⚠️ at time zone 'UTC' صریح است و نه تکیه بر تنظیمِ نشست: اگر روزی کسی
  // TimeZone را در اتصال عوض کند، همهٔ زمان‌ها بی‌صدا جابه‌جا می‌شوند.
  //
  // فرمت با US (میکروثانیه) و نه MS: ستون مقصد DATETIME(6) است.
  if (pgType.startsWith("timestamp")) {
    return `to_char(${q} at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS.US')`;
  }
  if (pgType === "date") return `to_char(${q}, 'YYYY-MM-DD')`;

  // ⚠️ TINYINT(1) در مقصد؛ 0/1 صریح، تا 't'/'f' پستگرس به مقصد نرسد.
  if (pgType === "boolean") return `case when ${q} then '1' else '0' end`;

  // ⚠️ text(inet) و نه host(inet): host() پیشوندِ شبکه را می‌اندازد.
  //    '10.0.0.0/8' با host() می‌شود '10.0.0.0' — یعنی معنایش عوض می‌شود.
  if (pgType === "inet") return `${q}::text`;

  // آرایهٔ متن → آرایهٔ JSON.
  //
  // ⚠️ to_jsonb و نه to_json — اختلافشان فقط در فاصله‌گذاری است و همان
  // یک فاصله verify را می‌شکاند:
  //
  //     to_json (نوع json)   →  ["الف","ب"]
  //     to_jsonb (نوع jsonb) →  ["الف", "ب"]
  //     MySQL  cast(… as char) →  ["الف", "ب"]
  //
  // یعنی داده یکی است ولی متنش نه، و checksum تفاوت را «خرابی» می‌خواند.
  // جای درستِ حل این مسئله همین‌جاست: هر دو طرف یک شکل بدهند.
  //
  // (array_to_string با کاما اصلاً گزینه نبود: برچسبی که خودش کاما دارد
  //  را به دو برچسب تبدیل می‌کرد.)
  if (pgType.endsWith("[]")) return `to_jsonb(${q})::text`;

  // jsonb::text نمایشِ canonical می‌دهد (کلیدها مرتب، تکراری‌ها حذف) —
  // همان کاری که MySQL هم با JSON می‌کند.
  if (pgType === "jsonb" || pgType === "json") return `${q}::text`;

  // numeric به متن، تا هرگز از ممیز شناور رد نشود.
  return `${q}::text`;
}

