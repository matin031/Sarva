/**
 * فهرستِ رویدادهایی که سروا دربارهٔ آن‌ها پیامِ بیرونی می‌فرستد.
 *
 * ⚠️ عمداً بدونِ هیچ import ای — نه `server-only`، نه `lib/db`، نه
 * `lib/settings`. دو مصرف‌کننده دارد که هیچ‌کدام سرور نیستند: تستِ
 * `node --test` و کارتِ تنظیماتِ حساب در پنل (که کامپوننتِ کلاینت است و با
 * یک import از `lib/settings` کلِ `mysql2` را به بستهٔ مرورگر می‌کشد —
 * همان تجربه‌ای که `lib/settings/groups.ts` از آن ساخته شد).
 *
 * =============================================================================
 * ⚠️ چرا هر رویداد «شناسهٔ قالب» می‌خواهد و نه یک متنِ ساده
 * =============================================================================
 *
 * خطِ خدماتیِ ایران متنِ آزاد نمی‌پذیرد. متن باید از قالبی بیاید که پنلِ
 * سرویس تأیید کرده و ما فقط متغیرهایش را پر کنیم. یعنی نوشتنِ متنِ فارسیِ
 * زیبا در کد، به‌تنهایی هیچ پیامکی نمی‌فرستد.
 *
 * پس هر رویداد دو چیز دارد:
 *
 *   • `smsVariables` — نامِ دقیقِ متغیرهایی که قالبِ تأییدشده باید داشته
 *     باشد. مدیر موقعِ ساختِ قالب در پنلِ SMS.ir همین نام‌ها را می‌نویسد.
 *   • یک کلیدِ تنظیمات (`sms.template_<event>`) که شناسهٔ آن قالب در آن
 *     ذخیره می‌شود.
 *
 * ⚠️ و تا وقتی آن شناسه ثبت نشده، پیامکِ آن رویداد **نمی‌رود**. بی‌صدا هم
 * نمی‌رود: یک ردیفِ `skipped` با دلیلِ `no_template` ثبت می‌شود. جایگزینش
 * — «از متنِ آزاد بفرست» — یعنی پیامِ خدماتی از خطِ تبلیغاتی برود: دیرتر
 * می‌رسد، برای کسی که تبلیغات را بسته اصلاً نمی‌رسد، و جای اشتباهی نشسته.
 * (متنِ آزاد فقط وقتی به کار می‌رود که مدیر «شمارهٔ خط» را ثبت کرده باشد و
 * قالب را نه — یعنی صریحاً همان را خواسته باشد.)
 */

/** رویدادهایی که پیامِ بیرونی دارند. */
export const NOTIFY_EVENTS = [
  "welcome",
  "plus_activated",
  "plus_renewed",
  "plus_expiring",
  "plus_expired",
] as const;

export type NotifyEvent = (typeof NOTIFY_EVENTS)[number];

export type NotifyChannel = "sms" | "email";

export type NotifyEventSpec = {
  /** برچسبِ فارسی — در تنظیمات و در گزارشِ ارسال‌ها دیده می‌شود. */
  label: string;
  /** یک جمله: این پیام کِی می‌رود. */
  when: string;
  /**
   * نامِ متغیرهای قالبِ پیامک، به همان ترتیبی که در قالب می‌آیند.
   *
   * ⚠️ حروفِ بزرگ و کوچک مهم است و باید مو‌به‌مو با پنلِ سرویس یکی باشد.
   * نامِ غلط خطا نمی‌دهد؛ پیامکی می‌فرستد که جای متغیر در آن خالی است.
   */
  smsVariables: readonly string[];
};

