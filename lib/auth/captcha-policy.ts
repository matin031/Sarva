/** سیاستِ کپچا — جدا از `lib/auth/turnstile.ts` چون آن فایل `server-only` را
 *  import می‌کند و بیرون از باندل Next بار نمی‌شود (و این یکی باید در
 *  `node --test` هم قابل import باشد). */

export type CaptchaMode = "off" | "optional" | "required";

/**
 * =============================================================================
 * ⚠️ چرا «حالت» جای «روشن/خاموش» را گرفت — و چرا پیش‌فرض دیگر `deny` نیست
 * =============================================================================
 *
 * نسخهٔ قبلی یک تصمیمِ دوحالته داشت: کلید هست → کپچا اجباری؛ کلید نیست و
 * production است → **همه چیز رد شود**. استدلالش درست بود («غیبتِ محافظ نباید
 * شبیه سلامت به نظر برسد») ولی برای سروا نتیجه‌اش دو حالتِ خراب بود و هیچ
 * حالتِ سالمی:
 *
 *   ۱. **کلید تنظیم نشده** (وضعیتِ امروزِ سروا): در production هر درخواستِ
 *      ورود، ثبت‌نام، ارسال کد و بازیابی رمز با «تأیید امنیتی پیکربندی نشده
 *      است» رد می‌شد. یعنی سایت در لحظهٔ بالا آمدن، برای *همه* قفل بود.
 *
 *   ۲. **کلید تنظیم شده**: ویجت از `challenges.cloudflare.com` بار می‌شود.
 *      کاربرِ ایرانی‌ای که به آن دامنه دسترسی ندارد هیچ توکنی تولید نمی‌کند،
 *      و سرور بدونِ توکن ردش می‌کند. یعنی همان کاربرِ واقعی‌ای که سایت برای
 *      اوست، بیرونِ در می‌ماند — و هیچ کارِ دیگری هم از دستش برنمی‌آید.
 *
 * با احتمالِ ملی شدنِ اینترنت، حالتِ ۲ یک فرضِ بدبینانه نیست؛ حالتِ محتمل است.
 *
 * پس کپچا از «دروازه» به «شاهد» تنزل کرد:
 *
 *   • `off`      — هیچ توکنی خواسته نمی‌شود. **پیش‌فرض، وقتی کلیدی نیست.**
 *   • `optional` — توکنِ *موجود* تأیید می‌شود و جعلی/منقضی رد؛ توکنِ *نبوده*
 *                  مانعِ کار نمی‌شود. پیش‌فرض وقتی کلید هست.
 *   • `required` — رفتارِ سخت‌گیرانهٔ قبلی. فقط با نوشتنِ صریح.
 *
 * ⚠️ و این یعنی محافظتِ واقعیِ سروا دیگر به کپچا وابسته نیست.
 *
 * آنچه واقعاً جلوی سوءاستفاده را می‌گیرد در جای خودش است و هیچ‌کدام به
 * سرویسِ خارجی وصل نیست: سقفِ نرخ به ازای ایمیل/شماره/IP در **دیتابیس**
 * (`lib/api/rate-limit-db.ts` — ری‌استارت را تاب می‌آورد)، سقفِ تلاشِ حدسِ
 * کد و رمز، argon2id با زمانِ پاسخِ یکسان برای کاربرِ موجود و ناموجود، و
 * سقفِ سراسریِ خرجِ پیامک (`lib/sms/budget.ts`) که سقفِ *پول* را می‌بندد.
 *
 * ⚠️ `optional` صادقانه نیمه‌کاره است و ادعای بیشتری هم ندارد: کسی که
 * عمداً توکن نمی‌فرستد از آن رد می‌شود. ارزشش این است که ترافیکِ واقعیِ
 * مرورگر را تأیید می‌کند بدونِ اینکه کسی را بیرون بگذارد — و روزی که یک
 * کپچای در دسترس از ایران داشته باشید، فقط یک متغیرِ محیطی تا `required`
 * فاصله دارید.
 */
/* ⚠️ نوعِ ورودی عمداً `Record<string, string|undefined>` است و نه یک شیء با
   سه کلیدِ نام‌برده. `process.env` در Next یک `ProcessEnv` با کلیدهای
   augment-شده است و به یک شیءِ سه‌کلیدی **assignable نیست** (خطای «no
   properties in common»)، پس امضای دقیق‌تر یعنی این تابع نتواند مقدارِ
   واقعیِ محیط را بگیرد. کلیدهایی که خوانده می‌شوند:
   `CAPTCHA_MODE`، `TURNSTILE_SECRET_KEY`، `TURNSTILE_OPTIONAL`. */
export function captchaMode(
  env: Record<string, string | undefined> = process.env,
): CaptchaMode {
  const raw = env.CAPTCHA_MODE?.trim().toLowerCase();
  if (raw === "off" || raw === "optional" || raw === "required") return raw;

  /* ⚠️ سازگاری با تنظیمِ قدیمی. `TURNSTILE_OPTIONAL=true` تنها راهی بود که
     کپچا را در production خاموش می‌کرد؛ هر جایی که امروز آن را دارد باید
     همان معنی را بگیرد و نه «اختیاری»، وگرنه یک deploy رفتار را عوض می‌کند
     بدونِ اینکه کسی چیزی تغییر داده باشد. */
  if (env.TURNSTILE_OPTIONAL === "true") return "off";

  /* بدونِ کلید هیچ کپچایی در کار نیست — نه اینکه «همه رد شوند». ویجت هم در
     همین حالت اصلاً رندر نمی‌شود، پس سرور و مرورگر یک چیز می‌فهمند. */
  return env.TURNSTILE_SECRET_KEY ? "optional" : "off";
}

/**
 * تصمیمِ پیش از هر درخواستِ بیرونی: با این حالت و این ورودی، چه باید کرد؟
 *
 * ⚠️ این تابع اینجاست و نه داخلِ `lib/auth/turnstile.ts`، چون آن فایل
 * `server-only` را import می‌کند و `node --test` اصلاً نمی‌تواند بارش کند
 * (آزموده شد: «This module cannot be imported from a Client Component»).
 * همان کاری که `lib/auth/duration.ts` و `lib/db/errors.ts` برای همین مشکل
 * کردند — منطقِ تصمیم به فایلِ بی‌وابستگی می‌رود تا بشود پینش کرد.
 *
 * سه خروجی:
 *   • `allow`  — بدونِ هیچ بررسی‌ای رد شو
 *   • `verify` — توکن هست، از Cloudflare بپرس
 *   • `deny`   — رد کن
 */
export type CaptchaDecision = "allow" | "verify" | "deny";

export function captchaPreflight(
  mode: CaptchaMode,
  input: { hasKey: boolean; hasToken: boolean },
): CaptchaDecision {
  if (mode === "off") return "allow";

  /* کلید نیست ولی حالت چیزِ دیگری می‌گوید — یک پیکربندیِ ناتمام. در
     `required` رد می‌شود (کسی که صریح نوشته «اجباری» باید بفهمد کار
     نمی‌کند)، در `optional` مانعِ کاربر نمی‌شود. */
  if (!input.hasKey) return mode === "required" ? "deny" : "allow";

  if (input.hasToken) return "verify";

  /* ⚠️ قلبِ تصمیم: «توکن نیامد» دو معنیِ کاملاً متفاوت دارد و از سمتِ سرور
     قابلِ تفکیک نیستند — یا مرورگر نتوانسته به Cloudflare برسد (کاربرِ
     واقعیِ ایرانی)، یا کسی عمداً فرم را دور زده. در `required` به دومی وزن
     می‌دهیم و در `optional` به اولی. */
  return mode === "required" ? "deny" : "allow";
}

/**
 * وقتی خودِ *سرور* نتوانست به Cloudflare برسد.
 *
 * ⚠️ نسخهٔ قبلی همیشه رد می‌کرد، با این استدلال که «وگرنه مهاجم فقط کافی
 * است دسترسیِ سرور را مختل کند تا کپچا ناپدید شود». استدلال درست است ولی
 * وزنِ دو طرف برای سروا یکی نیست: قطعیِ دسترسی به دامنه‌های خارجی در ایران
 * یک اتفاقِ روزمره است و نه یک حمله، و رد کردن یعنی کلِ ورود و ثبت‌نامِ سایت
 * به در دسترس بودنِ یک دامنهٔ خارجی گره بخورد.
 */
export function captchaOnUnreachable(mode: CaptchaMode): "allow" | "deny" {
  return mode === "required" ? "deny" : "allow";
}
