#!/bin/sh
# مهاجرت دیتابیس قبل از بالا آمدن سرور.
#
# اینجا اجرا می‌شود و نه در یک سرویس جداگانهٔ compose، تا وعدهٔ «روی سرور جدید
# فقط docker compose up» واقعاً درست باشد: کانتینر اپ خودش اسکیما را به روز
# می‌کند و بعد start می‌شود.
#
# set -e یعنی اگر مهاجرت شکست خورد، سرور اصلاً بالا نمی‌آید. این عمدی است —
# سروری که با اسکیمای ناقص بالا بیاید، خطاهایی می‌دهد که ردیابی‌شان بسیار
# سخت‌تر از یک کانتینرِ بالا نیامده است.
set -e

echo "[entrypoint] اجرای migration ها…"
node scripts/migrate.mjs

# ⚠️ بررسی جدول‌های منطقهٔ زمانی.
#
# پنل مدیریت برای گروه‌بندیِ روزانه از CONVERT_TZ(…, '+00:00', 'Asia/Tehran')
# استفاده می‌کند. آن تابع اگر نام منطقه را نشناسد **خطا نمی‌دهد؛ NULL
# برمی‌گرداند** — پس همهٔ نمودارها و گزارش‌های روزانه بی‌صدا خالی می‌شوند و
# هیچ‌چیز در لاگ نمی‌آید.
#
# نام‌ها فقط وقتی شناخته‌اند که جدول‌های mysql.time_zone پر شده باشند. ایمیج
# رسمی این کار را در مقداردهیِ اولیه انجام می‌دهد مگر MYSQL_INITDB_SKIP_TZINFO
# ست باشد — ولی روی دیتابیسی که از جای دیگری آمده (بازیابی از بکاپ، سرویس
# مدیریت‌شده) ممکن است پر نشده باشد.
#
# ⚠️ اینجا با شکست متوقف *نمی‌شویم*. یک بخشِ گزارش‌گیری نباید جلوی بالا
# آمدنِ کلِ سایت را بگیرد. ولی پیام باید آن‌قدر بلند باشد که دیده شود.
node scripts/check-timezone.mjs || true

# فقط وقتی ADMIN_EMAIL/ADMIN_PASSWORD ست باشند کاری می‌کند، و idempotent است.
echo "[entrypoint] بررسی حساب مدیر…"
node scripts/seed-admin.mjs

echo "[entrypoint] راه‌اندازی سرور…"
exec "$@"
