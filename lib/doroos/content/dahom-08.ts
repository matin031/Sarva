type Mark = { h: number; words: number[]; label: string };

const tokens = (s: string) => s.trim().split(/\s+/);
const clean = (s: string) =>
  s.replace(/[«»،؛؟!:.()\[\]…“”"\']/g, "").trim();

function mark(
  lines: string[],
  h: number,
  phrase: string,
  label: string,
  occurrence = 0,
): Mark {
  const hay = tokens(lines[h]).map(clean);
  const need = tokens(phrase).map(clean);
  let seen = 0;

  for (let i = 0; i <= hay.length - need.length; i += 1) {
    if (need.every((w, j) => hay[i + j] === w)) {
      if (seen === occurrence) {
        return { h, words: need.map((_, j) => i + j), label };
      }
      seen += 1;
    }
  }

  throw new Error(`عبارت پیدا نشد: ${phrase}`);
}

