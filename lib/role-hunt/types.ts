import type { GradeKey } from "@/lib/doroos/types";

/**
 * مدلِ دادهٔ «شکار نقش‌ها».
 *
 * ⚠️ این بازی **بانکِ سؤالِ خودش را ندارد** و قرار هم نیست داشته باشد. هر دور
 * از یک پرسشِ منتشرشدهٔ «مدارِ دستور» ساخته می‌شود — همان جدولِ
 * `grammar_circuit_questions` و همان payload که آنجا اعتبارسنجی می‌شود.
 *
 * دلیلش یک قاعدهٔ محتوایی است و نه تنبلی: نقشِ دستوریِ یک واژه در یک مصراع،
 * *داده‌ای است که یک انسان تأیید کرده*. ساختنِ بانکِ دومی از همان مصراع‌ها
 * یعنی دو حقیقتِ موازی که روزی با هم اختلاف پیدا می‌کنند، و آن روز هیچ‌کس
 * نمی‌داند کدام درست است. تبدیل در `round.ts` است و خالص — پس همان تبدیل، هم
 * در مسیرِ ساختِ دور اجرا می‌شود و هم در مسیرِ ثبتِ پاسخ.
 */

/** یک واژه در مصراع — دقیقاً یک *رخداد*، نه یک رشته. */
export interface RoleHuntToken {
  /** شناسهٔ توکن در payloadِ پرسش (`t1`، `t7`، …). مبنای همهٔ مقایسه‌ها. */
  id: string;
  text: string;
  /** جداکنندهٔ بعد از توکن، همان‌طور که در داده نوشته شده. */
  separatorAfter: string;
  /**
   * این رخداد در «مدارِ دستور» نقشِ تأییدشده دارد؟
   *
   * ⚠️ دیگر تعیین نمی‌کند چه چیزی به مدار می‌رود — کلِ مصراع می‌چرخد. فقط
   * می‌گوید این واژه دربارهٔ نقشش داده دارد یا فقط حواس‌پرت‌کن است.
   */
  hasConfirmedRole: boolean;
}

/** یک مصراع — تکه‌ای از متن که روی یک خط خوانده می‌شود. */
export type RoleHuntLine = RoleHuntToken[];

/** یک پرسش از یک مصراع: «کدام واژه این نقش را دارد؟» */
export interface RoleHuntAsk {
  /** کلیدِ متعارفِ نقش (`subject`، `predicate`، …). */
  roleKey: string;
  /** برچسبِ فارسی، از کاتالوگِ نقش‌ها. هرگز مبنای مقایسه نیست. */
  roleLabel: string;
  /**
   * تنها رخدادِ درست.
   *
   * ⚠️ «تنها» یک شرطِ ورود است و نه یک فرض: نقشی که دو واژه‌اش آن را
   * داشته باشند اصلاً پرسیده نمی‌شود. توضیحش در `round.ts`.
   */
  correctTokenId: string;
}

export interface RoleHuntRound {
  /** شناسهٔ ردیفِ `grammar_circuit_questions`. */
  questionId: string;
  sourceId: string | null;
  grade: GradeKey | null;
  lesson: number | null;

  /**
   * متنِ پرسش، شکسته به مصراع‌ها.
   *
   * ⚠️ یک عنصر یعنی مصراع، دو عنصر یعنی بیت. رابط کاربری هر دو را می‌شناسد و
   * هیچ‌کدام حالتِ خاص نیست: در داده، بیت همان مصراعی است که یکی از
   * توکن‌هایش جداکنندهٔ « / » دارد.
   */
  lines: RoleHuntLine[];

  /** واژه‌هایی که دورِ مصراع می‌چرخند — به ترتیبِ ظاهرشدن در متن. */
  orbit: RoleHuntToken[];

  /**
   * پرسش‌های همین مصراع، به ترتیب.
   *
   * ⚠️ یک مصراع چند نقشِ تأییدشده دارد و هر کدام یک پرسش است: اول «قید»،
   * بعد «نهاد»، بعد «مسند»… بازیکن بیت را *یک بار* می‌خواند و بعد پشتِ هم
   * به همهٔ نقش‌ها جواب می‌دهد. این همان کاری است که سرِ جلسهٔ امتحان از او
   * می‌خواهند و با «یک نقش برای هر بیت» اصلاً تمرین نمی‌شد.
   *
   * ترتیب قطعی است (بر اساسِ کلیدِ نقش) چون سرور باید بتواند از روی
   * *اندیس* بفهمد کدام نقش پرسیده شده — بدونِ اینکه مرورگر بتواند دروغ
   * بگوید.
   */
  asks: RoleHuntAsk[];
}

/** نتیجهٔ سنجشِ یک پاسخ — همان چیزی که سرور در جدول می‌نویسد. */
export interface RoleHuntResolvedAnswer {
  round: RoleHuntRound;
  /** پرسشی که پاسخ داده شد. */
  ask: RoleHuntAsk;
  chosenToken: RoleHuntToken;
  correctToken: RoleHuntToken;
  isCorrect: boolean;
  /** متنِ کاملِ پرسش، برای snapshot در ردیفِ پاسخ. */
  verse: string;
}
