-- =============================================================================
-- ۰۱۱ — رویدادهای فعالیتِ کاربر
-- =============================================================================
--
-- ── چرا اصلاً لازم است ─────────────────────────────────────────────────────
-- تا امروز سروا فقط *پاسخ* را ثبت می‌کند: `user_answers`، `vocab_answers`،
-- `jasoos_answers`، `aruz_bridge_answers`، `grammar_circuit_answers`،
-- `quiz_attempts`، `exam_attempts`. هر کدام دقیق و قابل اعتمادند، ولی همه‌شان
-- یک چیز مشترک دارند: **فقط وقتی ردیف می‌سازند که پاسخی داده شده باشد.**
--
-- یعنی این سه سؤالِ دبیر امروز هیچ جوابی ندارند:
--
--   • «کِی آخرین بار وارد سروا شد؟»          → هیچ جدولی نمی‌گوید (جز sessions)
--   • «سراغِ بازی رفت ولی چیزی ثبت نشد، یا اصلاً نرفت؟»
--   • «درسی را باز کرد؟»
--
-- و سه بازی — تندخوانِ عروض، نینجا، جفت‌ها — اصلاً هیچ جدولِ پاسخی ندارند
-- (بررسی شد: `aruz_rapid_questions`، `ninja_words`، `memory_pairs` فقط
-- محتوایِ نوشتهٔ مدیرند). برای آن‌ها «بازی کرد» امروز به هیچ شکلی قابل
-- دانستن نیست.
--
-- ── و مهم‌تر: چه چیزی **نیست** ──────────────────────────────────────────────
-- ⚠️ این جدول **جایگزینِ ذخیرهٔ پاسخ نیست و نباید بشود.**
--
-- درست/غلط، وزن، نقشِ دستوری، نمره و تسلط همگی منبعِ خودشان را دارند و
-- تحلیلِ دبیر باید از همان‌ها بخواند. اگر همان اعداد اینجا هم نوشته شوند، دو
-- منبعِ حقیقت می‌سازیم که روزی با هم اختلاف پیدا می‌کنند و آن روز هیچ‌کس
-- نمی‌داند کدام درست است.
--
-- ⚠️ و هیچ نمره‌ای از کلاینت پذیرفته نمی‌شود. مرورگر می‌تواند بگوید «بازی را
-- تمام کردم» — این یک ادعای بی‌ضرر است. ولی «۹۰٪ درست زدم» ادعایی است که
-- سرور نمی‌تواند راستی‌آزمایی کند، و نشان دادنش به دبیر به‌عنوانِ نتیجهٔ
-- آموزشی یعنی ساختنِ عددی که پشتش چیزی نیست. فهرستِ کلیدهای مجازِ `metadata`
-- در `lib/activity/schema.ts` عمداً هیچ کلیدِ نمره‌ای ندارد.
--
-- ⚠️ و هیچ کلیک، اسکرول، حرکتِ ماوس یا heartbeatی ثبت نمی‌شود. ده رویدادِ
-- اسمی، همین. «زمانِ صرف‌شده در سایت» هم عمداً ساخته نشده: مدلِ دقیقی برایش
-- نداریم و عددِ نادقیق بدتر از نبودنِ عدد است.
-- =============================================================================


CREATE TABLE `user_activity_events` (
  `id` CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,

  `user_id` CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,

  -- ⚠️ فهرستِ بسته، در CHECK و نه فقط در تایپ‌اسکریپت.
  --
  -- تایپ‌اسکریپت در زمانِ اجرا وجود ندارد. تنها چیزی که جلوی نوشتنِ یک
  -- رویدادِ دلخواه را در هر مسیرِ آینده‌ای می‌گیرد، همین بند است.
  --
  -- هر مقدارِ تازه باید یک migration بگیرد — که عمدی است: افزودنِ نوعِ
  -- رویداد باید یک تصمیم باشد، نه یک رشتهٔ تازه در یک فایلِ کامپوننت.
  `event_type` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,

  -- «این رویداد دربارهٔ چه چیزی است» — بازی، آزمون، کوییز، درس.
  -- nullable چون `login` دربارهٔ هیچ‌چیزِ خاصی نیست.
  `entity_type` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_general_ci NULL,

  -- ⚠️ VARCHAR و نه CHAR(36): بعضی شناسه‌ها UUIDاند (شناسهٔ تلاشِ آزمون) و
  -- بعضی اسمِ کوتاهِ مسیرند (`aruz-bridge`). یک ستون برای هر دو، با الگوی
  -- محدودکننده پایین.
  `entity_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_general_ci NULL,

  -- ⚠️ شیءِ JSON، با فهرستِ کلیدهای مجاز به‌ازای هر نوعِ رویداد در
  -- `lib/activity/schema.ts` — نه هر JSONی.
  --
  -- سقفِ حجم هم آنجاست و نه اینجا: عبارتِ سنجشِ طولِ یک ستونِ JSON بین
  -- MariaDB و MySQL یکسان رفتار نمی‌کند و گذاشتنِ یک CHECK که روی یکی از دو
  -- موتور نیازموده باشد، یعنی احتمالِ شکستِ migration روی هاست. آنچه اینجا
  -- می‌ماند همان بندی است که ۰۰۱ هم استفاده کرده و روی هر دو کار می‌کند:
  -- «شیء باشد، نه آرایه و نه عدد».
  `metadata` JSON NULL,

  -- ⚠️⚠️ `occurred_at` را **برنامه** می‌نویسد و نه `CURRENT_TIMESTAMP`.
  --
  -- این یک تصمیمِ آگاهانه است و دلیلش در `docs/time-contract.md` کامل آمده.
  -- خلاصه‌اش: `lib/db` به درایور می‌گوید هر DATETIME را UTC بخواند
  -- (`timezone: "Z"`) ولی `time_zone`ِ نشست را تنظیم نمی‌کند. روی سروری که
  -- `time_zone = SYSTEM` دارد و ساعتش UTC نیست، `now(6)` وقتِ *محلی*
  -- می‌نویسد و کد آن را UTC می‌خواند — همان باگی که اشتراکِ دبیری را ۳٫۵
  -- ساعت غیرفعال نگه داشته بود.
  --
  -- تا وقتی وضعیتِ production با `npm run db:check-time` اندازه‌گیری نشده،
  -- تنها راهِ داشتنِ یک ستونِ **بی‌ابهام** این است که مقدارش از Node بیاید:
  -- درایور یک `Date` را همیشه UTC می‌فرستد، مستقل از تنظیمِ سرور.
  --
  -- هر تحلیلِ زمانی فقط به این ستون تکیه می‌کند.
  `occurred_at` DATETIME(6) NOT NULL,

  -- ⚠️ و این یکی عمداً ساعتِ *دیتابیس* را می‌نویسد.
  --
  -- تکرارِ بی‌فایده به‌نظر می‌رسد ولی نیست: اختلافِ این دو ستون روی
  -- production، اندازه‌گیریِ همیشگی و رایگانِ همان چیزی است که هنوز
  -- نمی‌دانیم —
  --
  --   SELECT MAX(TIMESTAMPDIFF(SECOND, occurred_at, created_at))
  --     FROM user_activity_events;
  --
  -- اگر صفر بود، ساعتِ نشست UTC است. اگر ۱۲۶۰۰ بود، سرور روی تهران است.
  -- هیچ تحلیلی از این ستون نمی‌خواند.
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),

  PRIMARY KEY (`id`),

  -- «آخرین فعالیت» و «تاریخچهٔ این دانش‌آموز» — کوئریِ اصلیِ صفحهٔ دبیر.
  -- همین ایندکس کوئریِ دسته‌ایِ داشبوردِ کلاس را هم پوشش می‌دهد
  -- (`where user_id in (…) group by user_id`)، پس داشبورد به‌ازای هر
  -- دانش‌آموز یک کوئری نمی‌زند.
  KEY `user_activity_events_user_idx` (`user_id`, `occurred_at` DESC),

  -- «چند بار بازی را تمام کرد» — شمارش به تفکیکِ نوع، بدونِ اسکنِ ردیف‌ها.
  KEY `user_activity_events_type_idx` (`user_id`, `event_type`, `occurred_at` DESC),

  CONSTRAINT `user_activity_events_user_fk`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE,

  CONSTRAINT `user_activity_events_type_check`
    CHECK (`event_type` IN (
      'login',
      'game_started',
      'game_completed',
      'quiz_started',
      'quiz_completed',
      'exam_started',
      'exam_completed',
      'lesson_viewed',
      'aruz_practice_completed',
      'grammar_practice_completed'
    )),

  CONSTRAINT `user_activity_events_entity_type_check`
    CHECK (`entity_type` IS NULL OR `entity_type` IN ('game', 'quiz', 'exam', 'lesson')),

  -- ⚠️ الگوی محدودکننده روی شناسه: بدونِ آن، این ستون یک فیلدِ متنیِ آزاد
  -- است که کلاینت پُرش می‌کند و هر چیزی می‌تواند در آن بنشیند — از یک
  -- نشانیِ کامل تا دادهٔ شخصی. حروف و رقم و خط تیره، همین.
  CONSTRAINT `user_activity_events_entity_id_check`
    CHECK (`entity_id` IS NULL OR `entity_id` REGEXP '^[A-Za-z0-9_-]{1,64}$'),

  -- شیء، نه آرایه و نه عدد. (همان بندی که ۰۰۱ برای `payload` دارد.)
  CONSTRAINT `user_activity_events_metadata_check`
    CHECK (`metadata` IS NULL OR JSON_TYPE(`metadata`) = 'OBJECT')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin ROW_FORMAT=DYNAMIC;


