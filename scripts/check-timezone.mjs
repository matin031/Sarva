#!/usr/bin/env node
/**
 * آیا MySQL نام «Asia/Tehran» را می‌شناسد؟
 *
 * ⚠️ چرا این یک بررسیِ جداگانه است و نه یک خط داخل migration:
 *
 * CONVERT_TZ با نامِ ناشناخته **خطا نمی‌دهد؛ NULL برمی‌گرداند**. یعنی هر
 * کوئریِ گروه‌بندیِ روزانه در پنل مدیریت، به‌جای شکستن، بی‌صدا صفر ردیف
 * می‌دهد. نه استثنایی، نه لاگی، نه هیچ نشانه‌ای — فقط نمودارهای خالی که
 * به‌نظر می‌رسد «کاربری نبوده».
 *
 * این تنها کلاسِ خطایی است که در کلِ این مهاجرت هیچ آزمونِ خودکاری در
 * زمانِ اجرا نمی‌گیردش، چون از دید SQL همه‌چیز درست است.
 *
 * جدول‌های mysql.time_zone را نمی‌شود از داخلِ اپ پر کرد (به دسترسیِ
 * فایل‌سیستمِ سرور و امتیاز نوشتن در اسکیمای mysql نیاز دارد)، پس اینجا فقط
 * گزارش می‌شود و دستورِ درستش چاپ.
 */

import { connect } from "./mysql/script-db.mjs";

const conn = await connect();
try {
  // ۲۱ ژوئن: اگر روزی ساعت تابستانی برگردد، این تاریخ تفاوتش را نشان می‌دهد.
  // ⚠️ cast به CHAR: بدون آن، typeCast مقدار را به ISO با پسوند Z تبدیل
  // می‌کند و پیام می‌شود «…Z تهران» — یعنی دقیقاً همان چیزی که این بررسی
  // قرار است روشن کند را گنگ می‌کند.
  const [[row]] = await conn.query(
    "select cast(convert_tz('2024-06-21 20:30:00', '+00:00', 'Asia/Tehran') as char) as tehran",
  );

  if (row.tehran === null) {
    console.error(
      "\n" +
        "  ⚠️  MySQL نام «Asia/Tehran» را نمی‌شناسد.\n" +
        "\n" +
        "      جدول‌های mysql.time_zone پر نشده‌اند. CONVERT_TZ به‌جای خطا NULL\n" +
        "      برمی‌گرداند، پس همهٔ گزارش‌های روزانهٔ پنل مدیریت بی‌صدا خالی\n" +
        "      می‌شوند — بدون هیچ خطایی در لاگ.\n" +
        "\n" +
        "      سایت بالا می‌آید و بقیهٔ بخش‌ها سالم‌اند. برای رفعش، روی هاستِ\n" +
        "      دیتابیس:\n" +
        "\n" +
        "        mysql_tzinfo_to_sql /usr/share/zoneinfo | mysql -u root -p mysql\n" +
        "\n" +
        "      و بعد یک بار restart دیتابیس. نیازی به مهاجرت دوباره نیست.\n",
    );
    process.exitCode = 1;
  } else {
    console.log(`[entrypoint] منطقهٔ زمانی سالم است (۲۰:۳۰ UTC → ${row.tehran} تهران).`);
  }
} finally {
  await conn.end();
}
