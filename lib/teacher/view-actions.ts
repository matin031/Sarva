"use server";

import { requireTeacher } from "@/lib/auth/current-user";
import { uuidArg } from "@/lib/api/action-input";
import { getStudentForTeacher } from "./analytics";
import { recordStudentView } from "./views";

/**
 * ثبتِ «دبیر عملکردِ این دانش‌آموز را دید» — از **مرورگر** و نه از رندرِ
 * سرور.
 *
 * =============================================================================
 * ⚠️ چرا این اکشن اصلاً وجود دارد
 * =============================================================================
 *
 * تا امروز `recordStudentView` در بدنهٔ خودِ Server Component صدا زده
 * می‌شد. یعنی **هر رندرِ سمتِ سرور** یک ردیفِ بازدید می‌ساخت — و
 * `<Link>` در Next.js به‌صورت پیش‌فرض prefetch می‌کند.
 *
 * نتیجه‌اش این بود: دبیری که موسِ خود را روی دکمهٔ «عملکرد» در فهرستِ
 * کلاس می‌برد، بدونِ هیچ کلیکی یک بازدید ثبت می‌کرد. با یک بار اسکرول
 * روی فهرستِ سی‌نفره، سی ردیف — و دانش‌آموزانی که دبیرشان هرگز صفحهٔ
 * آن‌ها را باز نکرده بود، در فهرستِ «چه کسانی عملکردِ من را دیده‌اند»
 * می‌دیدندش.
 *
 * پنجرهٔ شش‌ساعتهٔ اعلان جلوی *اعلان* را می‌گرفت، ولی ردیف‌ها می‌ماندند و
 * همان‌ها چیزی هستند که به دانش‌آموز نشان داده می‌شود.
 *
 * ⚠️ تنها سیگنالِ قابلِ اعتمادِ «یک آدم واقعاً این صفحه را باز کرد»، اجرای
 * کدِ کلاینت است. prefetch، خزندهٔ موتورِ جست‌وجو و رندرِ دوبارهٔ سرور
 * هیچ‌کدام `useEffect` را اجرا نمی‌کنند.
 *
 * =============================================================================
 * ⚠️ و چون از کلاینت می‌آید، هیچ چیزی از آن باور نمی‌شود
 * =============================================================================
 *
 * شناسه‌ها از مرورگر می‌رسند، پس دسترسی **از نو** سنجیده می‌شود — دقیقاً
 * همان گاردی که خودِ صفحه دارد. بدونِ آن، هر دبیری می‌توانست با یک
 * فراخوانِ دستی برای هر دانش‌آموزِ سایت اعلان بسازد.
 */
export async function teacherRegisterStudentView(
  classId: string,
  studentId: string,
): Promise<void> {
  const teacher = await requireTeacher();
  const cls = uuidArg(classId, "شناسهٔ کلاس نامعتبر است.");
  const student = uuidArg(studentId, "شناسهٔ دانش‌آموز نامعتبر است.");

  /* ⚠️ همان گاردِ صفحه، از نو. `classId` هم فرستاده می‌شود تا بازدید به
     کلاسی نسبت داده نشود که دانش‌آموز عضوش نیست. */
  const access = await getStudentForTeacher(teacher.id, student, cls);
  if (!access) return;

  await recordStudentView({
    teacherId: teacher.id,
    teacherName: teacher.fullName ?? null,
    studentId: student,
    classId: cls,
    className: access.classes.find((c) => c.id === cls)?.name ?? "کلاس",
  });
}
