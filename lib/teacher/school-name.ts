/**
 * یکدست کردنِ نامِ مدرسه — منطقِ خالص، بدونِ دیتابیس.
 *
 * ⚠️ چرا فایلِ جدا و نه کنارِ `lib/teacher/schools.ts`:
 *
 * آن ماژول `"server-only"` است (به `@/lib/db` وصل است) و هر چیزی که از آن
 * import شود، همان قید را با خودش می‌آورد. یعنی این تابعِ کاملاً خالص نه
 * قابلِ تست با `node --test` بود و نه قابلِ استفاده در فرمِ مرورگر.
 *
 * همان کاری که `lib/plus/coverage.ts` کرد و به همان دلیل: منطقِ محصولی که
 * دیتابیس لازم ندارد، نباید پشتِ دیتابیس قفل شود.
 *
 * ── مسئله ──────────────────────────────────────────────────────────────────
 * جدولِ `schools` مثل بقیهٔ جدول‌های این پروژه `utf8mb4_bin` است، یعنی
 * مقایسه بایت‌به‌بایت. در فارسی این یعنی همهٔ این‌ها ردیف‌های *متفاوت*ی
 * می‌شوند:
 *
 *     «دبیرستان هدی»   «دبیرستان هدي»   ← یِ فارسی در برابر یِ عربی
 *     «دبیرستان  هدف»                    ← دو فاصله
 *     «دبیرستانِ هدف»                     ← با کسره
 *
 * و نتیجه‌اش یک شهر با پنج ردیفِ «دبیرستان هدف» است که دبیرانِ همان مدرسه
 * هرکدام به یکی‌شان وصل شده‌اند — یعنی هدفِ اصلیِ جدول (که دو دبیر به یک
 * چیز اشاره کنند) از بین می‌رود.
 *
 * ⚠️ نامِ *نمایشی* دست نمی‌خورد: کاربر همان چیزی را می‌بیند که نوشته. این
 * تابع فقط کلیدِ مقایسه می‌سازد که در ستونِ `name_key` می‌نشیند.
 */
export function normalizeSchoolName(raw: string): string {
  return (
    raw
      .trim()
      // یِ عربی و الفِ مقصوره → یِ فارسی
      .replace(/[يى]/g, "ی")
      // کافِ عربی → کافِ فارسی
      .replace(/ك/g, "ک")
      // هٔ چسبیده → ه
      .replace(/ۀ/g, "ه")
      // اعراب، تشدید، سکون، همزه و مدِ روی حرف — در نامِ مدرسه معنایی
      // ندارند و فقط تفاوتِ بایتی می‌سازند.
      //
      // ⚠️ بازه تا U+065F می‌رود و نه تا U+0652، و این را یک تستِ شکست‌خورده
      // پیدا کرد: «مدرسهٔ» با «ه» + U+0654 (همزهٔ بالا) نوشته می‌شود و نه با
      // U+06C0. با بازهٔ کوتاه‌تر، «مدرسهٔ هدی» و «مدرسه هدی» دو ردیفِ جدا
      // می‌ساختند — دقیقاً همان چیزی که این تابع برای جلوگیری‌اش هست.
      .replace(/[ً-ٰٟ]/g, "")
      // نیم‌فاصله و نویسه‌های جهت‌دهی → فاصلهٔ معمولی
      .replace(/[‌‎‏]/g, " ")
      // فاصله‌های تکراری
      .replace(/\s+/g, " ")
      .trim()
      .toLowerCase()
  );
}
