type RawLevel = Omit<Level, "tokens">;

/* ⚠️ همان قراردادِ درسنامه (`split(/\s+/)`) تا شناسه‌های «مصراع-جایگاه» با
   آنجا یکی بماند. */
export function tokenize(lines: readonly string[]): Token[] {
  return lines.flatMap((line, l) =>
    line
      .split(/\s+/)
      .filter(Boolean)
      .map((raw, i) => {
        const [, pre, text, post] = /^([«"(]*)(.*?)([»"),،؛:.!؟?]*)$/u.exec(raw) ?? [raw, "", raw, ""];
        return {
          id: `${l}-${i}` as TokenId,
          text: text || raw,
          ...(pre ? { pre } : {}),
          ...(post ? { post } : {}),
          line: l as 0 | 1,
        };
      }),
  );
}

/** ترتیبِ رنگ‌های پالت؛ مفهوم‌های هر بیت اول و بعد بقیه تا پنج رنگ. */
const PALETTE_ORDER: ConceptId[] = [
  "mushabbah",
  "mushabbahBih",
  "adat",
  "vajhShabah",
  "esteare",
  "majaz",
  "kenaye",
  "tashkhis",
  "jenas",
  "saj",
];

/* وجه‌شبه فقط وقتی روی پالت می‌آید که بیت بخواهدش. رنگِ پرکننده نیست، وگرنه
   پالتِ همهٔ بیت‌هایی که پیش از آن ساخته شده‌اند عوض می‌شد. */
const FILLERS = PALETTE_ORDER.filter((c) => c !== "vajhShabah");

export function paletteFor(steps: readonly Step[]): ConceptId[] {
  const needed = new Set(steps.map((s) => s.concept));
  const size = Math.max(5, needed.size);
  const out = PALETTE_ORDER.filter((c) => needed.has(c));
  for (const c of FILLERS) if (out.length < size && !out.includes(c)) out.push(c);
  return PALETTE_ORDER.filter((c) => out.includes(c));
}

