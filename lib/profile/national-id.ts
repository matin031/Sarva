/**
 * کد ملی ایران — نرمال‌سازی و بررسیِ رقمِ کنترلی.
 *
 * ⚠️ عمداً بدون `"server-only"`: فرمِ درخواستِ دبیر باید *پیش از* ارسال
 * بفهمد کد ملی غلط است. کاربری که فایلِ حکمش را آپلود کرده و بعد بابتِ یک
 * رقمِ جابه‌جا خطا می‌گیرد، باید کلِ فرم را دوباره پر کند.
 *
 * ── چرا فقط «ده رقم» کافی نیست ─────────────────────────────────────────────
 * یک regexِ `^\d{10}$` هر عددِ ده‌رقمی را می‌پذیرد، از جمله `1234567890` و
 * `0000000000`. کد ملیِ ایران رقمِ دهمش یک رقمِ کنترلی است که از نُه رقمِ
 * اول حساب می‌شود، پس غلط بودنِ یک رقم — یا جابه‌جا تایپ شدنِ دو رقم — همان
 * لحظه قابل تشخیص است.
 *
 * این کار *هویت* را تأیید نمی‌کند و قرار هم نیست بکند؛ فقط جلوی غلطِ تایپی
 * را می‌گیرد. تأییدِ واقعی کارِ مدیری است که حکمِ کارگزینی را می‌بیند.
 */

/** ارقامِ فارسی (۰-۹) و عربی-هندی (٠-٩) به لاتین — همان کاری که
 *  `lib/auth/phone.ts` برای شماره می‌کند، و به همان دلیل: دانش‌آموز و دبیری
 *  که با کیبورد فارسی تایپ می‌کنند «۰۰۱۲…» می‌نویسند. */
function toLatinDigits(raw: string): string {
  return raw.replace(/[۰-۹٠-٩]/g, (d) => {
    const code = d.charCodeAt(0);
    const base = code >= 0x06f0 ? 0x06f0 : 0x0660;
    return String(code - base);
  });
}

/**
 * ورودیِ کاربر → ده رقمِ لاتین، یا `null` اگر شکلش درست نباشد.
 *
 * ⚠️ صفرهای ابتدایی **حفظ می‌شوند** و هرگز نباید این مقدار از یک `Number`
 * رد شود. کد ملیِ `0012345678` واقعی است و تبدیلش به عدد، دو رقمش را
 * می‌خورد — یعنی دو نفرِ متفاوت یک کد ملی پیدا می‌کنند.
 */
export function normalizeNationalId(raw: unknown): string | null {
  if (typeof raw !== "string") return null;

  const cleaned = toLatinDigits(raw)
    // خط تیره و فاصله در نوشتنِ کد ملی رایج است («۰۰۱-۲۳۴۵۶۷-۸»).
    .replace(/[\s\-‌‏‎]/g, "")
    .trim();

  // کمتر از ده رقم با صفر پر می‌شود: بسیاری از شناسنامه‌ها کد را بدونِ
  // صفرهای ابتدایی چاپ کرده‌اند و کاربر هم همان‌طور تایپ می‌کند.
  const padded = /^\d{8,10}$/.test(cleaned) ? cleaned.padStart(10, "0") : cleaned;

  return /^\d{10}$/.test(padded) ? padded : null;
}

/**
 * رقمِ کنترلی درست است؟
 *
 * الگوریتم: مجموعِ وزن‌دارِ نُه رقمِ اول (وزن‌ها ۱۰ تا ۲)، باقی‌ماندهٔ ۱۱.
 *   • باقی‌مانده < ۲  → رقمِ کنترلی باید خودِ باقی‌مانده باشد.
 *   • باقی‌مانده ≥ ۲  → رقمِ کنترلی باید ۱۱ منهای باقی‌مانده باشد.
 *
 * ⚠️ کدهای «همه‌یک‌رقم» (`1111111111` و مانندش) از این الگوریتم رد می‌شوند
 * ولی هیچ‌کدام کد ملیِ واقعی نیستند، پس جداگانه رد می‌شوند. بدونِ این خط،
 * `1111111111` یک ورودیِ کاملاً معتبر بود — و دقیقاً همان چیزی است که کسی
 * که نمی‌خواهد کد ملیِ واقعی بدهد تایپ می‌کند.
 */
export function isValidNationalId(raw: unknown): boolean {
  const id = normalizeNationalId(raw);
  if (id === null) return false;

  if (/^(\d)\1{9}$/.test(id)) return false;

  let sum = 0;
  for (let i = 0; i < 9; i++) sum += Number(id[i]) * (10 - i);

  const remainder = sum % 11;
  const check = Number(id[9]);

  return remainder < 2 ? check === remainder : check === 11 - remainder;
}

/**
 * نسخهٔ پوشیده برای نمایش در فهرست‌ها: `00••••••78`.
 *
 * ⚠️ در جدولِ «مدیریت درخواست دبیران» کد ملیِ کاملِ ده‌ها نفر نباید هم‌زمان
 * روی صفحه باشد — یک اسکرین‌شات یا یک نفرِ پشتِ سرِ مدیر کافی است. کدِ کامل
 * فقط در نمای جزئیاتِ همان یک درخواست دیده می‌شود.
 */
export function maskNationalId(id: string | null): string | null {
  if (!id || !/^\d{10}$/.test(id)) return null;
  return `${id.slice(0, 2)}••••••${id.slice(8)}`;
}
