type MarkSpec = [h: 0 | 1, phrase: string, label: string, occurrence?: number];

function marks(hemistichs: [string, string], specs: MarkSpec[]) {
  return specs.map(([h, phrase, label, occurrence = 0]) => {
    const words = hemistichs[h].split(/\s+/);
    const wanted = phrase.split(/\s+/);
    const starts = words.flatMap((_, i) =>
      wanted.every((word, j) => words[i + j]?.replace(/[،؛؟]/g, "") === word.replace(/[،؛؟]/g, "")) ? [i] : [],
    );
    const start = starts[occurrence] ?? -1;
    if (start < 0) throw new Error(`عبارت «${phrase}» در مصراع پیدا نشد.`);
    return { h, words: wanted.map((_, i) => start + i), label };
  });
}

function beyt(
  n: number,
  hemistichs: [string, string],
  meaning: string,
  concept: string,
  clauses: number,
  linguistic: string[],
  literary: string[],
  deviceSpecs: MarkSpec[] = [],
  syntaxSpecs: MarkSpec[] = [],
) {
  return {
    n,
    hemistichs,
    meaning,
    concept,
    linguistic,
    literary,
    intellectual: meaning,
    clauses,
    devices: marks(hemistichs, deviceSpecs),
    syntax: marks(hemistichs, syntaxSpecs),
  };
}

