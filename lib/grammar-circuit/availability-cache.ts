import "server-only";

/**
 * شمارشِ درس‌های مدار دستور — یک بار حساب، بعد از کش.
 *
 * ⚠️ چرا لازم شد: مسیرِ availability در *هر* درخواست همهٔ پرسش‌های منتشرشده
 * را با `payload` کاملشان می‌خواند و اعتبارسنجی می‌کند — روی دادهٔ واقعی
 * ۵۵۵ پرسش و ۵۶۲ کیلوبایت — تا در پایان حدود سی عدد بدهد. پاسخِ نهایی
 * ۲٫۵ کیلوبایت است و هر درخواست حدود شصت میلی‌ثانیه CPU می‌گرفت.
 *
 * چرا شمارشِ ساده در SQL جایش را نمی‌گیرد: پرسشِ خراب باید از شمارش کنار
 * برود، و تشخیصِ خرابی همان اعتبارسنجیِ کد است. یک `count(*)` عددِ بزرگ‌تر
 * از واقعیت می‌داد و کاربر درسی را باز می‌کرد که پرسشِ سالم ندارد. پس
 * اعتبارسنجی سرِ جایش می‌ماند و فقط *نتیجه‌اش* کش می‌شود.
 *
 * ⚠️ این کش درون‌حافظه‌ای است و بینِ چند replica مشترک نیست. عمداً: افزودنِ
 * Redis برای یک عددِ سی‌تایی که هر دقیقه تازه می‌شود صرف نمی‌کند. بدترین
 * حالت با N نمونه، N بار محاسبه در هر دقیقه به‌جای یک بار — نه نادرستی.
 *
 * تازگی: شصت ثانیه، به‌علاوهٔ ابطالِ صریح وقتی مدیر چیزی را منتشر یا از
 * انتشار خارج می‌کند. یعنی تغییرِ مدیر بلافاصله دیده می‌شود و در بدترین
 * حالتِ چند-replica حداکثر یک دقیقه طول می‌کشد.
 */

const TTL_MS = 60_000;

type Entry<T> = { value: T; at: number };

let cached: Entry<unknown> | null = null;
let inFlight: Promise<unknown> | null = null;

/**
 * نتیجه را از کش می‌دهد، یا یک بار می‌سازد.
 *
 * درخواست‌های هم‌زمان یک محاسبه را به اشتراک می‌گذارند — وگرنه وقتی کش
 * منقضی می‌شود و ده نفر هم‌زمان صفحه را باز کنند، ده محاسبهٔ هم‌زمان
 * راه می‌افتد؛ دقیقاً همان لحظه‌ای که نباید.
 */
export async function cachedAvailability<T>(build: () => Promise<T>): Promise<T> {
  const now = Date.now();
  if (cached && now - cached.at < TTL_MS) return cached.value as T;

  if (inFlight) return inFlight as Promise<T>;

  const job = (async () => {
    const value = await build();
    cached = { value, at: Date.now() };
    return value;
  })();

  inFlight = job;
  try {
    return await job;
  } finally {
    inFlight = null;
  }
}

/** مدیر چیزی را منتشر یا پنهان کرد — شمارشِ کهنه دیگر معتبر نیست. */
export function invalidateAvailability(): void {
  cached = null;
}
