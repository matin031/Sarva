/**
 * سقفِ **سراسریِ** خرجِ پیامک.
 *
 * ⚠️ عمداً بدون `server-only`: اعداد باید در `node --test` هم خوانده شوند.
 * چیزی محرمانه‌ای اینجا نیست — فقط دو عدد از محیط.
 *
 * =============================================================================
 * ⚠️ چرا این لازم بود، وقتی سقف‌های دیگر از قبل وجود داشتند
 * =============================================================================
 *
 * سقف‌های موجود همه **نسبی**اند: سه کد در ساعت برای هر *شماره*، هشت تا برای
 * هر *IP*. هیچ‌کدام به این سؤال جواب نمی‌دهند: «بدترین حالت، امشب چقدر پول
 * از پنلِ پیامک می‌رود؟»
 *
 * جوابش با سقف‌های نسبی *بی‌نهایت* است. یک اسکریپت با هزار پروکسی و هزار
 * شمارهٔ معتبر، از هیچ‌کدام از آن سقف‌ها رد نمی‌شود و هزاران پیامک می‌فرستد —
 * هر کدام واقعاً ارسال می‌شود، چون از نظرِ هر سقفِ موجود کاملاً مجاز است.
 *
 * این فایل آن سؤال را قابلِ جواب می‌کند: در بدترین حالت، `perHour` پیامک در
 * ساعت و `perDay` در شبانه‌روز. نه بیشتر، فارغ از اینکه مهاجم چند IP و چند
 * شماره داشته باشد.
 *
 * ⚠️ و این تنها محافظی است که **مستقل از هوشمندی** کار می‌کند. کپچا، تشخیصِ
 * ربات و سقفِ نرخ همه سعی می‌کنند «خوب» را از «بد» تشخیص بدهند و هر کدام
 * روزی اشتباه می‌کنند. این یکی تشخیص نمی‌دهد؛ فقط شیر را می‌بندد.
 *
 * ── اعداد از کجا آمدند ─────────────────────────────────────────────────────
 * سروا یک سایتِ آموزشی است و نه یک شبکهٔ اجتماعی. یک کلاسِ سی‌نفره که با هم
 * ثبت‌نام می‌کنند، سی پیامک است. پیش‌فرضِ ۲۰۰ در ساعت جای چند کلاسِ هم‌زمان
 * را دارد و در عین حال سقفِ روزانه را زیرِ هزار نگه می‌دارد.
 *
 * ⚠️ اگر روزی کم آمد، عدد را بالا ببرید — ولی **آگاهانه**. کمبودِ سهمیه در
 * لاگ با `sms.budget.exhausted` دیده می‌شود و پیش از رسیدن به سقف هم
 * `sms.budget.low` هشدار می‌دهد، پس این تصمیم را با داده می‌گیرید نه با حدس.
 */

export type SmsBudget = {
  perHour: number;
  perDay: number;
};

const DEFAULT_PER_HOUR = 200;
const DEFAULT_PER_DAY = 1000;

/**
 * ⚠️ عددِ بد **صدا نمی‌کند** و به پیش‌فرض برمی‌گردد.
 *
 * همان تصمیمی که `parseDuration` برای `AUTH_REFRESH_TTL` گرفته: یک `.env`
 * بدشکل نباید سایت را از کار بیندازد. ولی اینجا یک نکتهٔ اضافه هست — صفر و
 * عددِ منفی هم رد می‌شوند. اگر `SMS_MAX_PER_HOUR=0` قابل قبول بود، یک
 * اشتباهِ تایپی کلِ ورودِ پیامکیِ سایت را بی‌صدا می‌بست، که دقیقاً همان
 * خرابی‌ای است که این ماژول باید جلویش را بگیرد. برای خاموش کردنِ پیامک،
 * درایورش را خاموش کنید نه سقفش را صفر.
 */
function positiveInt(raw: string | undefined, fallback: number): number {
  const n = Number(raw);
  if (!Number.isFinite(n) || !Number.isInteger(n) || n <= 0) return fallback;
  return n;
}

/* کلیدهای خوانده‌شده: `SMS_MAX_PER_HOUR` و `SMS_MAX_PER_DAY`. دلیلِ نوعِ
   بازِ ورودی همان است که بالای `captchaMode` نوشته شده. */
export function smsBudget(env: Record<string, string | undefined> = process.env): SmsBudget {
  const perHour = positiveInt(env.SMS_MAX_PER_HOUR, DEFAULT_PER_HOUR);
  const perDay = positiveInt(env.SMS_MAX_PER_DAY, DEFAULT_PER_DAY);

  /* ⚠️ سقفِ روزانه هرگز کمتر از ساعتی نمی‌شود.
     `SMS_MAX_PER_HOUR=500` با `SMS_MAX_PER_DAY` ِ پیش‌فرضِ ۱۰۰۰ یعنی سقفِ
     ساعتی از دو ساعت بعد بی‌معنی است. به‌جای اینکه این تناقض بی‌صدا بماند،
     سقفِ روزانه بالا کشیده می‌شود تا هر دو عدد همان چیزی باشند که نوشته
     شده‌اند. */
  return { perHour, perDay: Math.max(perDay, perHour) };
}

/** زیرِ این نسبت از سهمیه، هشدارِ «رو به اتمام» در لاگ می‌آید. */
export const SMS_BUDGET_LOW_RATIO = 0.2;
