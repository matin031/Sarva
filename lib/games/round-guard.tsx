"use client";

import { createContext, useContext, useEffect } from "react";

/**
 * «الان دوری در جریان است؟» — یک سیگنال، از خودِ بازی به پوسته.
 *
 * ⚠️ چرا لازم شد: `GameShell` نگهبانِ `beforeunload` را همیشه — از لحظهٔ
 * mount — نصب می‌کرد، در حالی که توضیحِ خودش می‌گفت «هنگامِ نوسازی یا بستنِ
 * تب *در میانهٔ یک دور* می‌پرسد». این دو یکی نبودند: کسی که تازه وارد صفحهٔ
 * انتخابِ درس شده بود و هنوز هیچ بازی‌ای شروع نکرده، با یک F5 ساده گفت‌وگوی
 * «صفحه را ترک می‌کنی؟» می‌گرفت. آزموده شد و همین بود:
 *
 *     صفحهٔ آماده‌سازیِ پلِ وزن، بدونِ شروعِ بازی
 *     نوسازیِ صفحه → گفت‌وگوها: beforeunload
 *
 * هشداری که وقتی چیزی برای از دست دادن نیست هم بلند می‌شود، آموزشِ بدی به
 * کاربر می‌دهد: یاد می‌گیرد بدونِ خواندن ردش کند — و آن‌وقت هشدارِ واقعی هم
 * بی‌اثر می‌شود.
 *
 * پوسته نمی‌تواند خودش حدس بزند؛ هر بازی حالتِ خودش را دارد. پس هر بازی
 * صریح می‌گوید، و پوسته فقط همان را باور می‌کند.
 */
type SetRoundActive = (active: boolean) => void;

const RoundGuardContext = createContext<SetRoundActive | null>(null);

export const RoundGuardProvider = RoundGuardContext.Provider;

/**
 * از داخلِ یک بازی صدا زده می‌شود: «دوری در جریان هست/نیست».
 *
 * `active` را از همان حالتی بده که خودِ بازی برای رندر استفاده می‌کند، نه یک
 * پرچمِ موازی — وگرنه همان ناهماهنگی که این ماژول برای رفعش نوشته شد، این بار
 * یک لایه پایین‌تر برمی‌گردد.
 *
 * ⚠️ در هر بازی فقط *یک* جا صدایش بزن. دو مصرف‌کننده روی یک مقدار کشمکش
 * می‌کنند و برنده به ترتیبِ اجرای effectها بستگی پیدا می‌کند.
 *
 * بیرون از `GameShell` بی‌اثر است (context خالی) و خطا نمی‌دهد: بازی‌ها در
 * تست و در Storybook هم بدونِ پوسته رندر می‌شوند.
 */
export function useRoundGuard(active: boolean): void {
  const setActive = useContext(RoundGuardContext);

  useEffect(() => {
    if (!setActive) return;
    setActive(active);
    /* با unmount شدنِ بازی نگهبان باید برداشته شود. تکیه بر «بازی خودش قبلِ
       رفتن false می‌فرستد» کافی نیست؛ خروجِ ناگهانی (تغییرِ مسیر، خطا) اصلاً
       فرصتِ آن را نمی‌دهد. */
    return () => setActive(false);
  }, [setActive, active]);
}
