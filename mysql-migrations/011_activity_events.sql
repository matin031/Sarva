-- در هر ۱۰ دقیقه به‌ازای هر کاربر، و دانش‌آموزِ واقعی حدود ۲۰ رویداد در روز
-- می‌سازد.
--
-- ⚠️ دستورالعملِ هرس کردن عمداً **اینجا نوشته نشده** و در
-- `docs/activity-events.md` است. دلیلش یک قاعدهٔ واقعیِ همین مخزن است:
-- `tests/observability/migration.test.ts` هر فایلِ مهاجرت را برای دستورهای
-- ویرانگر می‌خواند و یک نمونهٔ «فقط توضیحی» را از یک دستورِ واقعی تشخیص
-- نمی‌دهد — و نباید هم بدهد. نگهبانی که برای راحتیِ توضیح‌نویسی سست شود،
-- دیگر نگهبان نیست.
