/* ── قابِ دوربین ────────────────────────────────────────────────────────── */

export interface SceneFrame {
  cameraPosition: readonly [number, number, number];
  cameraTarget: readonly [number, number, number];
  fov: number;
  /** پهنای دنیای دیدنی در عمقِ کتاب‌ها — مبنای فاصلهٔ کتاب‌ها. */
  visibleWidth: number;
  spacing: number;
}

/**
 * قابِ صحنه برای یک نسبتِ تصویرِ مشخص.
 *
 * ⚠️ چرا فقط CSS کافی نبود: کوچک‌کردنِ بوم با CSS همان قاب را فشرده می‌کند،
 * پس روی گوشیِ عمودی کتاب‌های کناری از کادر بیرون می‌زدند و شخصیت از پایین
 * بریده می‌شد. راهِ درست عوض‌کردنِ *ترکیب‌بندیِ سه‌بعدی* است: دوربین عقب
 * می‌رود و میدانِ دید باز می‌شود تا همان محتوا در نسبتِ باریک‌تر جا شود.
 */
export function frameFor(aspect: number, bookCount: number): SceneFrame {
  /* نسبت‌های باریک‌تر از ۴:۳ کم‌کم به دوربینِ عقب‌تر نیاز دارند. عددها از
     همین یک قاعده می‌آیند و نه از جدولِ نقطه‌شکن‌های CSS — نسبتِ تصویر
     پیوسته است و رفتار هم باید پیوسته باشد. */
  const narrow = Math.min(1, Math.max(0, (1.45 - aspect) / 0.85));

  /* ضریب‌ها با محاسبهٔ قاب روی نسبت‌های ۲٫۲ تا ۰٫۵ بسته شده‌اند، با دو
     شرطِ هم‌زمان: همهٔ کتاب‌ها افقی جا شوند و بالای نشان از کادر بیرون
     نزند. سخت‌ترین حالت گوشیِ عمودی (۰٫۵) است و آنجا هر دو با اندکی حاشیه
     برقرارند. */
  const fov = 40 + narrow * 8;
  const distance = 6.05 + narrow * 0.9;
  const height = 2.0 + narrow * 0.35;
  /* در قابِ باریک نقطهٔ هدف *بالا* می‌رود و نه پایین: کادرِ بلند وگرنه
     نیمهٔ پایینش کفِ خالی می‌شد و کتاب‌ها به لبهٔ بالا می‌چسبیدند. */
  const targetY = 1.62 + narrow * 0.12;

  const target = [0, targetY, 0.45] as const;
  const position = [0, height, target[2] + distance] as const;

  /* پهنای دیدنی در عمقِ کتاب‌ها (z = BOOK_Z)، نه در عمقِ نقطهٔ هدف.
     کتاب‌ها دورترین چیزهایی‌اند که باید کامل دیده شوند، پس قابِ آن‌ها
     تنگ‌ترین قید است. */
  const depth = position[2] - BOOK_Z;
  const halfHeight = depth * Math.tan(((fov / 2) * Math.PI) / 180);
  const visibleWidth = halfHeight * aspect * 2;

  return {
    cameraPosition: position,
    cameraTarget: target,
    fov,
    visibleWidth,
    spacing: bookSpacing(bookCount, visibleWidth),
  };
}
