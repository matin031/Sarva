/* ── ابعادِ خامِ دارایی‌ها ───────────────────────────────────────────────────
   این دو عدد *اندازه‌گیری‌شده‌اند*، نه حدس:

     • ۴٫۸۰۳۶ — ارتفاعِ شخصیت در ژستِ بایند (فاصلهٔ کفِ پا تا
       `mixamorig:HeadTop_End` پس از اعمالِ مقیاسِ ۰٫۰۱ آرمیچر).
     • ۲۱ — ارتفاعِ خامِ مدلِ کتاب، که `book-geometry.json` هم گزارشش می‌کند.

   نگه‌داشتنشان به‌صورتِ ثابت یعنی مقیاس‌های زیر «ارتفاعِ دلخواه تقسیم بر
   ارتفاعِ واقعی» است و نه یک عددِ جادوییِ آزمون‌وخطایی. */
const CHARACTER_BIND_HEIGHT = 4.8036;
const BOOK_RAW_HEIGHT = 21;

/** قدِ شخصیت روی صحنه. یک نوجوان، نه یک بزرگسال. */
export const CHARACTER_HEIGHT = 1.55;
export const CHARACTER_SCALE = CHARACTER_HEIGHT / CHARACTER_BIND_HEIGHT;

/**
 * ارتفاعِ کتاب.
 *
 * ⚠️ عمداً بزرگ‌تر از یک کتابِ واقعی است. با مقیاسِ واقع‌گرایانه (حدودِ ۲۴
 * سانت) پنج کتاب کنارِ هم روی صفحهٔ گوشی به پنج لکهٔ کوچک تبدیل می‌شدند، در
 * حالی که کتاب‌ها *موضوعِ اصلیِ* این بازی‌اند و عنوانشان باید خوانده شود.
 * ۵۶ سانت یعنی هنوز کتاب دیده می‌شود ولی در قاب وزن دارد.
 */
export const BOOK_HEIGHT = 0.56;
export const BOOK_SCALE = BOOK_HEIGHT / BOOK_RAW_HEIGHT;
/** از ابعادِ خامِ ۱۴ × ۲۱ × ۳٫۵ می‌آید. */
export const BOOK_WIDTH = 14 * BOOK_SCALE;
export const BOOK_DEPTH = 3.5 * BOOK_SCALE;

/* ── دیوار و طاقچه ─────────────────────────────────────────────────────── */

/** رویهٔ دیوار روی z=۰ است و صحنه به سمتِ z مثبت جلو می‌آید. */
export const WALL_Z = 0;
export const WALL_WIDTH = 9.4;
/**
 * ⚠️ این عدد از قابِ دوربین می‌آید و نه از سلیقه.
 *
 * باریک‌ترین نسبتِ تصویری که پشتیبانی می‌شود (حدودِ ۰٫۵) بالاترین لبهٔ
 * دیدنی را روی y≈۴٫۹۴ می‌گذارد. دیوار باید از آن بلندتر باشد وگرنه در
 * گوشیِ عمودی لبهٔ بالایش پیدا می‌شود و صحنه شبیهِ یک تختهٔ شناور می‌شود.
 * ۵٫۶ همان است به‌اضافهٔ جا برای تکانِ دوربین.
 */
export const WALL_HEIGHT = 5.6;
/** ضخامتِ واقعی. دیوارِ بی‌ضخامت از زاویهٔ دوربین لبه‌اش لو می‌رود. */
export const WALL_THICKNESS = 0.3;

/**
 * ارتفاعِ رویهٔ طاقچه.
 *
 * ⚠️ این عدد از قدِ شخصیت مشتق می‌شود و تصادفی نیست: کفِ کتاب باید *کمی
 * بالاتر از فرقِ سرِ* او باشد (۱٫۵۵). اگر پایین‌تر بود، «کتاب از بالا روی
 * سرش می‌افتد» بی‌معنا می‌شد و ضربه شبیهِ هل‌دادن در می‌آمد.
 */
export const SHELF_Y = CHARACTER_HEIGHT + 0.07;
export const SHELF_THICKNESS = 0.085;
export const SHELF_DEPTH = 0.44;
/** کتاب وسطِ عمقِ طاقچه می‌ایستد، نه لبِ آن. */
export const BOOK_Z = WALL_Z + SHELF_DEPTH / 2;

/* ── لنگرها ────────────────────────────────────────────────────────────────

   ⚠️ چرا شخصیت به خودِ کتاب نمی‌رود.

   موقعیتِ کتاب روی طاقچه و در ارتفاعِ ۱٫۶۲ است. «رفتن به آنجا» یعنی رفتن به
   داخلِ دیوار. چیزی که لازم است یک *لنگرِ رسیدن* روی کف است: زیرِ همان
   کتاب، ولی به‌اندازهٔ کافی جلوتر که

     ۱. کتاب هنگامِ پرتاب‌شدن جا داشته باشد،
     ۲. دوربین هم کتاب و هم شخصیت را با هم ببیند و روی هم نیفتند،
     ۳. شخصیت هنگامِ زمین‌خوردن (۶۰ سانت به جلو) به پایهٔ طاقچه نخورد.

   هر سه شرط با ۱٫۳ متر برآورده می‌شود. */
export const ARRIVAL_Z = 1.3;
/** جایی که شخصیت بینِ دورها می‌ایستد — وسط و عقب‌تر، در فضای باز. */
export const HOME_Z = 2.9;
export const HOME_X = 0;

/* ── چیدمانِ کتاب‌ها ───────────────────────────────────────────────────── */

export interface BookSlot {
  index: number;
  /** مرکزِ کتاب روی طاقچه. */
  position: readonly [number, number, number];
  /** جایی که شخصیت برای این کتاب می‌ایستد — روی کف. */
  arrival: readonly [number, number, number];
  /** ناحیهٔ لمس: کمی بزرگ‌تر از خودِ کتاب. */
  hitSize: readonly [number, number, number];
  /** لنگرِ برچسبِ HTML — بالای کتاب. */
  label: readonly [number, number, number];
}

/**
 * فاصلهٔ مرکزِ دو کتاب، بر حسبِ اینکه چند کتاب و چقدر پهنا داریم.
 *
 * ⚠️ چرا تابع و نه ثابت: روی گوشیِ باریک، پنج کتاب با فاصلهٔ دسکتاپ از دو
 * طرفِ کادر بیرون می‌زدند. ولی کوچک‌کردنِ فاصله تا بی‌نهایت هم جواب نیست —
 * زیرِ یک حدی کتاب‌ها به هم می‌چسبند و ناحیه‌های لمس روی هم می‌افتند. پس
 * فاصله بینِ یک کف و یک سقف بسته می‌شود و اگر باز هم جا نشد، *مقیاسِ صحنه*
 * است که عوض می‌شود (نگاه کنید به `frameFor`).
 */
const MIN_SPACING = BOOK_WIDTH + 0.2;
const MAX_SPACING = 0.98;

export function bookSpacing(count: number, visibleWidth: number): number {
  if (count <= 1) return MAX_SPACING;
  // ۸۴٪ از پهنای دیدنی، تا کتابِ کناری به لبهٔ کادر نچسبد.
  const fit = (visibleWidth * 0.84) / (count - 1);
  return Math.min(MAX_SPACING, Math.max(MIN_SPACING, fit));
}

/**
 * جایگاهِ همهٔ کتاب‌ها — تنها منبعِ حقیقت برای رندر *و* حرکت *و* برچسب.
 *
 * چون `arrival` از همین‌جا و از روی همان x می‌آید، عوض‌کردنِ تعداد یا فاصله
 * هیچ‌وقت نمی‌تواند مقصدِ حرکت را از کتاب جدا کند — چیزی که با مختصاتِ دستی
 * دیر یا زود پیش می‌آمد.
 */
export function bookSlots(count: number, spacing: number): BookSlot[] {
  const mid = (count - 1) / 2;
  return Array.from({ length: count }, (_, index) => {
    const x = (index - mid) * spacing;
    return {
      index,
      position: [x, SHELF_Y, BOOK_Z] as const,
      arrival: [x, 0, ARRIVAL_Z] as const,
      /* ناحیهٔ لمس عمداً از کتاب بزرگ‌تر است: عطفِ کتاب فقط ۹ سانت پهناست و
         روی گوشی زدن روی آن تقریباً غیرممکن می‌شد. ارتفاع هم تا زیرِ طاقچه
         کشیده شده تا زدن روی «جای کتاب» هم بگیرد.
         پهنا هرگز از `spacing` بیشتر نمی‌شود تا دو ناحیه روی هم نیفتند. */
      hitSize: [Math.min(spacing * 0.92, BOOK_WIDTH * 2.1), BOOK_HEIGHT * 1.35, Math.max(BOOK_DEPTH * 3.5, 0.3)] as const,
      label: [x, SHELF_Y + BOOK_HEIGHT + 0.14, BOOK_Z] as const,
    };
  });
}

