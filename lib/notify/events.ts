/**
 * کلیدِ تنظیماتی که شناسهٔ قالبِ این رویداد در آن است.
 *
 * ⚠️ تابع است و نه یک جدولِ دستی: اگر روزی رویدادی اضافه شود و کسی یادش
 * برود کلیدش را هم بنویسد، آن رویداد بی‌صدا «قالب ندارد» می‌شد.
 */
export function smsTemplateSettingKey(event: NotifyEvent): `sms.template_${NotifyEvent}` {
  return `sms.template_${event}`;
}

/** دلیلِ نرفتنِ یک پیام — ماشین‌خوان، تا در گزارش قابلِ گروه‌بندی باشد. */
export type NotifySkipReason =
  /** کاربر این کانال را در تنظیماتِ حسابش خاموش کرده. */
  | "opted_out"
  /** شماره/ایمیلِ **تأییدشده**ای وجود ندارد. */
  | "no_contact"
  /** شناسهٔ قالبِ این رویداد در تنظیمات ثبت نشده. */
  | "no_template"
  /** کلِ اطلاع‌رسانی از تنظیمات خاموش است. */
  | "disabled"
  /** همین پیام قبلاً برای همین کاربر رفته. */
  | "duplicate";
