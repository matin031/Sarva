-- =============================================================================
-- سروا — رصدپذیری: وصل کردن لاگ‌ها به هم با «شناسهٔ درخواست»
-- =============================================================================
-- تا امروز سه جای جدا وجود داشت و هیچ‌کدام به هم وصل نبودند:
--
--   • لاگ کانتینر (stdout)      → «چه اتفاقی افتاد»
--   • app_error_log             → «چه خطایی رخ داد»
--   • admin_audit_log           → «چه کسی چه کرد»
--
-- وقتی کاربری می‌گفت «دیروز موقع ثبت‌نام خطا گرفتم»، راهی نبود که ردیفِ
-- app_error_log را به خطوطِ همان درخواست در لاگ کانتینر وصل کرد. حالا هر
-- درخواست یک uuid دارد که proxy.ts می‌سازد و در هدر x-request-id هم به
-- مرورگر برمی‌گردد — پس همان یک عدد، هر سه جا را به هم می‌دوزد.
--
-- هیچ ستون یا ردیفی حذف نمی‌شود. همهٔ ستون‌های تازه nullable اند (یا
-- default دارند)، پس ردیف‌های قدیمی دست‌نخورده و معتبر می‌مانند.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- لاگ فعالیت مدیران
-- ---------------------------------------------------------------------------
-- فقط شناسهٔ درخواست. بقیهٔ این جدول همان است که بود و نباید عوض شود.
alter table admin_audit_log
  add column if not exists request_id text;

-- «این کار مدیر، در همان درخواستی که خطا داد انجام شد؟»
create index if not exists admin_audit_request_idx
  on admin_audit_log (request_id)
  where request_id is not null;

-- ---------------------------------------------------------------------------
-- لاگ خطا
-- ---------------------------------------------------------------------------
alter table app_error_log
  -- نامِ کلاسِ خطا: TypeError، AuthError، DatabaseError… . جدا از پیام نگه
  -- داشته می‌شود چون در گروه‌بندی و در ساختِ اثرانگشت نقش دارد.
  add column if not exists error_name text,

  -- کدِ ماشینیِ خطا وقتی وجود دارد: `23505` پستگرس، `ECONNREFUSED` شبکه.
  -- برای کسی که با پیام فارسی/انگلیسیِ خطا آشنا نیست، همین کد سریع‌ترین راه
  -- جست‌وجوی علت است.
  add column if not exists error_code text,

  -- digest ای که Next روی خطاهای رندرِ سمت سرور می‌گذارد. تنها چیزی است که
  -- کاربر در مرورگر می‌بیند؛ با آن می‌شود از شکایتِ کاربر به ردیفِ اینجا رسید.
  add column if not exists digest text,

  -- کدام محیط و کدام نسخه. بدون این‌ها، بعد از یک deploy معلوم نیست خطا
  -- مالِ نسخهٔ تازه است یا از قبل بوده.
  add column if not exists environment text,
  add column if not exists release text,

  -- اولین و آخرین درخواستی که این خطا در آن دیده شد. «اولین» برای ریشه‌یابی
  -- و «آخرین» برای اینکه ببینید همین حالا هم دارد رخ می‌دهد.
  add column if not exists first_request_id text,
  add column if not exists last_request_id text,

  -- زمینهٔ ساختاریافته: مسیر، متد، وضعیت، نوع route و… .
  -- ⚠️ هرگز بدنهٔ درخواست، کوکی، توکن یا پارامتر SQL. lib/observability/redact.ts
  -- مقادیر را قبل از رسیدن به اینجا بازگشتی پاک می‌کند.
  add column if not exists metadata jsonb not null default '{}'::jsonb;

-- «آن خطایی که کاربر شناسه‌اش را داد کدام ردیف است؟»
create index if not exists app_error_last_request_idx
  on app_error_log (last_request_id)
  where last_request_id is not null;

-- فیلترِ «فقط خطاهای همین نسخه» در پنل.
create index if not exists app_error_release_idx
  on app_error_log (release, last_seen_at desc)
  where release is not null;

