"use client";

import { KIMIA_CONFIG } from "@/lib/kimia/config";

/**
 * لایهٔ جریان — جایی که مایعِ بیرونِ شیشه کشیده می‌شود.
 *
 * ═══════════════════════════════════════════════════════════════════════
 * ⚠️ چرا `position: fixed` و مختصاتِ viewport
 * ═══════════════════════════════════════════════════════════════════════
 * جریان از لبهٔ یک شیشه شروع می‌شود و به سطحِ مایعِ داخلِ باکسِ بیت
 * می‌رسد — دو عنصر که در دو جای متفاوتِ سند نشسته‌اند. اگر این لایه در
 * جریانِ عادیِ صفحه بود، باید مختصات را بینِ سه دستگاه ترجمه می‌کردیم و
 * هر اسکرول یکی از آن‌ها را کهنه می‌کرد.
 *
 * با یک لایهٔ ثابت، «دستگاهِ مختصات» همان چیزی است که
 * `getBoundingClientRect` می‌دهد و بس. اسکرولِ وسطِ انیمیشن هم فقط یک
 * تفاضلِ `scrollY` است که خطِ زمانی هر فریم اعمال می‌کند — بدونِ یک بار
 * خواندنِ layout.
 *
 * ⚠️ و هیچ‌وقت لمس را نمی‌گیرد (`pointer-events: none`) و در درختِ
 * دسترسی‌پذیری نیست: یک تصویرِ محض است.
 *
 * ⚠️ این کامپوننت هیچ handleی بیرون نمی‌دهد: خطِ زمانی گره‌هایش را از
 * DOM پیدا می‌کند (`lib/kimia/scene.ts`) تا مسئلهٔ دوبار سوار شدنِ
 * کامپوننت در حالتِ توسعه اصلاً پیش نیاید.
 *
 * ── چرا گره‌ها از پیش ساخته می‌شوند ─────────────────────────────────────
 * ⚠️ قطره‌ها در هر فریم ساخته و حذف نمی‌شوند. یک استخرِ ثابت به اندازهٔ
 * سقفِ قطره‌ها یک بار ساخته می‌شود و خطِ زمانی فقط `transform` و
 * `opacity`شان را عوض می‌کند. ساختنِ گره در هر فریم یعنی GC وسطِ
 * انیمیشن، و GC وسطِ انیمیشن یعنی همان پرشی که این بازطراحی برای
 * نداشتنش نوشته شده.
 */

export default function PourOverlay() {
  const max = KIMIA_CONFIG.motion.fluid.maxDroplets;
  const slots = Array.from({ length: max }, (_, i) => i);

  return (
    <svg className="km-pour-layer" aria-hidden focusable="false">
      <path className="km-pour-stream" style={{ opacity: 0 }} />
      <ellipse className="km-pour-ripple" style={{ opacity: 0 }} />
      {slots.map((i) => (
        <circle key={i} className="km-pour-drop" style={{ opacity: 0 }} />
      ))}
    </svg>
  );
}
