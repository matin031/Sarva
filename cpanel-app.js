/**
 * فایل شروعِ برنامه روی هاست اشتراکی cPanel.
 *
 * =============================================================================
 * این فایل کجا می‌نشیند و چرا وجود دارد
 * =============================================================================
 *
 * در «Setup Node.js App» در cPanel، فیلدِ «Application startup file» را روی
 * همین فایل تنظیم می‌کنید (نامش بعد از آماده‌سازی `app.js` می‌شود).
 *
 * cPanel برنامه را با Phusion Passenger اجرا می‌کند و نه با `npm start`.
 * Passenger فایل شروع را require می‌کند و متد `listen` را خودش می‌قاپد، پس
 * شمارهٔ پورت اهمیتی ندارد.
 *
 * می‌شد مستقیم `server.js` (خروجی standalone خودِ Next) را به cPanel داد.
 * این فایل سه کارِ کوچک ولی لازم را قبلش انجام می‌دهد:
 *
 *   ۱) `.env` را می‌خواند. سرورِ standalone این کار را نمی‌کند — آن قابلیتِ
 *      `next start` است. بدون این، باید همهٔ متغیرها را در رابط cPanel
 *      یکی‌یکی وارد کنید، و آن رابط با نویسه‌های ویژه (مثل @ و = در
 *      گذرواژه) رفتار قابلِ اتکایی ندارد. یک فایل متنی در File Manager
 *      هم ساده‌تر است و هم قابلِ بازبینی.
 *
 *   ۲) مسیر فایل‌های آپلودی را جایی *بیرون* از پوشهٔ برنامه می‌گذارد.
 *      ⚠️ اگر این کار نشود، `uploads/` کنارِ کدِ برنامه می‌نشیند و اولین
 *      باری که نسخهٔ تازه را آپلود کنید، همهٔ صوت‌های آپلودشدهٔ پنل پاک
 *      می‌شوند — بی‌آنکه هشداری بگیرید.
 *
 *   ۳) اگر تنظیمی جا افتاده باشد، یک پیام فارسیِ روشن می‌دهد. بدون این،
 *      Passenger فقط یک صفحهٔ «We're sorry…» نشان می‌دهد و علتِ واقعی در
 *      لاگی می‌ماند که پیدا کردنش کار هرکسی نیست.
 *
 * =============================================================================
 * ⚠️ این فایل هیچ چیزی از رفتار سایت را عوض نمی‌کند
 * =============================================================================
 *
 * فقط محیط را آماده می‌کند و بعد همان `server.js` را صدا می‌زند.
 */

"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = __dirname;

// ---------------------------------------------------------------------------
// ۱) خواندن .env
// ---------------------------------------------------------------------------

/**
 * یک خوانندهٔ کوچکِ .env — عمداً بدون کتابخانه.
 *
 * افزودن dotenv یعنی یک وابستگی بیشتر که باید روی هاست نصب شود، برای کاری
 * که سی خط است.
 *
 * ⚠️ نکتهٔ ظریف: مقدارها **بازگشایی نمی‌شوند**. یعنی اگر بنویسید
 * `PASS="a\nb"`، همان بک‌اسلش و n در مقدار می‌ماند. این عمدی است: گذرواژهٔ
 * دیتابیس می‌تواند هر نویسه‌ای داشته باشد و «هوشمند» بودن اینجا فقط راه‌های
 * تازه برای خراب شدنِ بی‌صدا باز می‌کند. فقط گیومهٔ *دورِ* مقدار برداشته
 * می‌شود، که خودش هم فقط برای وقتی است که مقدار با فاصله شروع یا تمام شود.
 */
function loadEnvFile(file) {
  let text;
  try {
    text = fs.readFileSync(file, "utf8");
  } catch {
    return 0; // فایل نیست؛ اشکالی ندارد.
  }

  let count = 0;
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;

    const eq = line.indexOf("=");
    if (eq <= 0) continue;

    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"') && value.length > 1) ||
      (value.startsWith("'") && value.endsWith("'") && value.length > 1)
    ) {
      value = value.slice(1, -1);
    }

    // ⚠️ متغیرهایی که cPanel خودش تنظیم کرده بازنویسی نمی‌شوند. اگر کسی
    // مقداری را در رابط cPanel گذاشته، آن باید برنده باشد — وگرنه عوض
    // کردنش در رابط هیچ اثری نمی‌کند و ساعت‌ها وقت می‌گیرد تا بفهمید چرا.
    if (process.env[key] === undefined) {
      process.env[key] = value;
      count += 1;
    }
  }
  return count;
}

const envCount = loadEnvFile(path.join(ROOT, ".env"));

// ---------------------------------------------------------------------------
// ۲) مسیر پایدارِ فایل‌های آپلودی
// ---------------------------------------------------------------------------

if (!process.env.UPLOADS_DIR) {
  // یک پله بالاتر از پوشهٔ برنامه. اگر برنامه در /home/user/sarva باشد،
  // آپلودها در /home/user/sarva-uploads می‌نشینند و با جایگزین کردنِ
  // پوشهٔ برنامه از بین نمی‌روند.
  process.env.UPLOADS_DIR = path.join(path.dirname(ROOT), path.basename(ROOT) + "-uploads");
}
try {
  fs.mkdirSync(process.env.UPLOADS_DIR, { recursive: true });
} catch (err) {
  console.error(`[سروا] پوشهٔ آپلود ساخته نشد: ${process.env.UPLOADS_DIR}\n${err.message}`);
}

// ---------------------------------------------------------------------------
// ۳) بررسی تنظیماتِ لازم، پیش از بالا آمدن
// ---------------------------------------------------------------------------

const REQUIRED = [
  ["DATABASE_URL", "آدرس اتصال به دیتابیس MySQL"],
  ["AUTH_JWT_SECRET", "کلید امضای ورود کاربران"],
  ["OTP_PEPPER", "کلید کدهای یک‌بارمصرف ایمیل"],
];

const missing = REQUIRED.filter(([name]) => !process.env[name]);

if (missing.length > 0) {
  const lines = [
    "",
    "  ┌──────────────────────────────────────────────────────────┐",
    "  │  سروا بالا نیامد: تنظیمات کامل نیست                       │",
    "  └──────────────────────────────────────────────────────────┘",
    "",
    `  ${missing.length} مقدار تنظیم نشده است:`,
    "",
    ...missing.map(([name, why]) => `      ${name}  —  ${why}`),
    "",
    "  این‌ها را یا در فایل .env کنارِ همین برنامه بگذارید، یا در",
    "  بخش Environment variables در «Setup Node.js App» در cPanel.",
    "",
    `  مسیر فایل .env:  ${path.join(ROOT, ".env")}`,
    "  نمونهٔ کامل با توضیح فارسی: فایل .env.example",
    "",
  ];
  console.error(lines.join("\n"));

  // ⚠️ خروج با کد ناصفر و نه ادامه دادن.
  //
  // اگر بگذاریم بالا بیاید، سایت باز می‌شود ولی هر صفحه‌ای که به دیتابیس
  // نیاز دارد خطای ۵۰۰ می‌دهد — و پیدا کردنِ علت از روی آن خطاها بسیار
  // سخت‌تر از یک برنامهٔ بالا نیامده با پیامِ روشن است.
  process.exit(1);
}

// ---------------------------------------------------------------------------
// و حالا خودِ برنامه
// ---------------------------------------------------------------------------

console.log(
  `[سروا] شروع | Node ${process.version} | ` +
    `${envCount} مقدار از .env خوانده شد | آپلودها: ${process.env.UPLOADS_DIR}`,
);

require("./server.js");
