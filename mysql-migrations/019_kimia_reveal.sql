-- =============================================================================
-- ۰۱۹ — «پاسخ را ببین»: سه تلاش برای هر بیت، و پایانی که همیشه آموزنده است
-- =============================================================================
--
-- ── مسئله ──────────────────────────────────────────────────────────────────
--
-- تا امروز یک دورِ «کیمیای وزن» فقط یک راهِ پایان داشت: پاسخِ درست. بازیکنی
-- که گیر می‌کرد، یا تا ابد تلاش می‌کرد یا بیت را رها می‌کرد و می‌رفت — و در
-- هر دو حالت **هیچ‌وقت پاسخِ درست را نمی‌دید**. یعنی سخت‌ترین بیت‌ها، همان‌ها
-- که بیشترین چیز را برای یاد دادن داشتند، تنها بیت‌هایی بودند که چیزی یاد
-- نمی‌دادند.
--
-- حالا هر بیت سه تلاش دارد و در سه حالت پاسخ نشان داده می‌شود: درست ساختی،
-- تلاش‌ها تمام شد، یا خودت خواستی ببینی.
--
-- ── چرا `status` دست نمی‌خورد ──────────────────────────────────────────────
--
-- ⚠️ وسوسه این بود که `status` یک مقدارِ سومِ `'revealed'` بگیرد. نشد، و
-- دلیلش دو CHECK ای است که مهاجرت ۰۱۸ عمداً گذاشته:
--
--     kimia_rounds_completed_matches     (status='completed') = (completed_at IS NOT NULL)
--     kimia_rounds_completed_is_correct  (status='completed') = (last_correct = 1)
--
-- آن دو قید معنای روشنی دارند و درست‌اند: «بسته شد» یعنی «درست جواب داد».
-- دورِ reveal شده درست جواب نداده، پس نه `completed` است و نه باید وانمود
-- کند هست. بازنویسیِ آن CHECKها یعنی `DROP CONSTRAINT` روی جدولی که داده
-- دارد، و یعنی این فایل دیگر «فقط افزودنی» نیست.
--
-- پس دورِ reveal شده `status = 'active'` می‌ماند و فقط `revealed_at` پر
-- می‌شود. «دورِ بسته» از این به بعد یعنی:
--
--     status = 'completed'  OR  revealed_at IS NOT NULL
--
-- و این تعریف در `lib/kimia/round-state.ts` به‌شکلِ `isRoundClosed` زندگی
-- می‌کند تا در هیچ کوئری‌ای دوباره نوشته نشود.
--
-- ⚠️ بهایش را صادقانه می‌نویسم: ایندکسِ `kimia_rounds_open_idx` که برای
-- «این کاربر چند دورِ باز دارد» ساخته شده بود، از این به بعد دورهای
-- reveal شده را هم «باز» می‌شمارد. هیچ کوئریِ امروزِ پروژه از آن ایندکس
-- استفاده نمی‌کند، و روزی که پاکسازیِ دورهای رهاشده نوشته شود باید
-- `revealed_at IS NULL` را هم شرط کند.
--
-- ── چرا سقفِ تلاش CHECK نمی‌شود ────────────────────────────────────────────
--
-- ⚠️ `CHECK (attempts_count <= 3)` وسوسه‌انگیز است و اشتباه. «سه تلاش» یک
-- قاعدهٔ *محصولی* است و نه یک خاصیتِ داده؛ روزی که چهار شود، این قید همهٔ
-- ردیف‌های تاریخی را که با قاعدهٔ امروز نوشته شده‌اند گروگان می‌گیرد و یک
-- مهاجرتِ دیگر لازم می‌شود که چیزی جز عوض کردنِ یک عدد نمی‌کند.
--
-- سقف جایی اعمال می‌شود که تصمیم گرفته می‌شود: داخلِ همان تراکنشِ قفل‌شدهٔ
-- `recordAttempt`، و یک بارِ دیگر در شرطِ `WHERE` خودِ `UPDATE`. همان الگوی
-- دو لایه‌ای که ۰۱۸ برای `attempts_count = 0` دارد.
--
-- ── چرا هیچ ستونِ امتیازی اضافه نمی‌شود ────────────────────────────────────
--
-- ⚠️ «تلاشِ دوم نصفِ امتیاز» یک نگاشتِ جذاب است و اینجا جایش نیست. سنجهٔ
-- کارنامهٔ این بازی از روزِ اول یک بولین بوده — `first_correct` — و هر سه
-- مصرف‌کننده‌اش (`getWeightAnalysis`، پنلِ دبیر، روندِ هفتگی) همان را
-- می‌خوانند. اضافه کردنِ یک عددِ دوم یعنی دو تعریف از «موفقیت» که روزی از
-- هم دور می‌شوند. «چند بار طول کشید» را `attempts_count` از قبل می‌گوید.
--
-- ── backfill لازم نیست ─────────────────────────────────────────────────────
--
-- هر دو ستون `NULL`پذیرند و `NULL` دقیقاً یعنی «این دور reveal نشده» — که
-- دربارهٔ همهٔ ردیف‌های موجود راست است. هیچ ردیفی نباید لمس شود.


-- ── چرا سه دستور و نه یکی ──────────────────────────────────────────────────
--
-- ⚠️ MySQL اجازه می‌دهد افزودنِ ستون و قید در یک `ALTER` بیایند، ولی این
-- فایل روی هاست و با دست اجرا می‌شود. اگر همه در یک دستور باشند و یکی از
-- قیدها رد شود، پیام خطا نمی‌گوید کدام — و چون DDL در MySQL برنمی‌گردد،
-- نیمهٔ اجراشده می‌ماند و باید دستی جمع شود. سه دستور یعنی سه پیام خطای
-- روشن و سه نقطهٔ توقفِ معلوم.


-- ۱) دو ستون. هر دو NULL‌پذیر، پس هیچ ردیفی لمس نمی‌شود و backfill لازم نیست.
ALTER TABLE `kimia_rounds`
  ADD COLUMN `revealed_at` DATETIME(6) NULL AFTER `completed_at`,
  ADD COLUMN `reveal_reason` VARCHAR(16)
    CHARACTER SET ascii COLLATE ascii_general_ci NULL AFTER `revealed_at`;


-- ۲) قیدها.
--
-- زمان و علت با هم می‌آیند یا هیچ‌کدام — همان الگوی
-- `kimia_rounds_first_attempt_matches` در ۰۱۸.
ALTER TABLE `kimia_rounds`
  ADD CONSTRAINT `kimia_rounds_reveal_matches`
    CHECK ((`revealed_at` IS NULL) = (`reveal_reason` IS NULL));

ALTER TABLE `kimia_rounds`
  ADD CONSTRAINT `kimia_rounds_reveal_reason_check`
    CHECK (`reveal_reason` IS NULL OR `reveal_reason` IN ('exhausted', 'user'));

-- ⚠️ پاسخ بدونِ تلاش باز نمی‌شود. `POST /reveal` این را برای کاربرِ
-- واردشده شرط می‌کند (۴۰۹ با `no-attempt-yet`)، و این قید همان قاعده را
-- در لایه‌ای می‌گذارد که هیچ کدی نمی‌تواند دورش بزند: یک دورِ دست‌نخورده
-- که «پاسخش دیده شده» یک شاهدِ بی‌معناست.
ALTER TABLE `kimia_rounds`
  ADD CONSTRAINT `kimia_rounds_reveal_needs_attempt`
    CHECK (`revealed_at` IS NULL OR `attempts_count` > 0);


-- ۳) ایندکس — روی *علت* و نه روی زمان.
--
-- سؤالی که این ستون‌ها ساخته شده‌اند تا جواب بدهند «کِی باز شد» نیست؛
-- «کدام وزن‌ها بازیکن را به بن‌بست می‌رسانند» است — یعنی گروه‌بندی روی
-- علت، محدود به یک کاربر. `answered_at` هم در کلید هست تا همان کوئری
-- بتواند بازهٔ زمانی بگیرد بدونِ برگشت به جدول.
CREATE INDEX `kimia_rounds_reveal_idx`
  ON `kimia_rounds` (`user_id`, `reveal_reason`, `answered_at`);
