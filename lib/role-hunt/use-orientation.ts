"use client";

import { useSyncExternalStore } from "react";

/**
 * «این دستگاه گوشی است؟ و اگر هست، عمودی گرفته شده؟»
 *
 * =============================================================================
 * ⚠️ چرا «شکار نقش‌ها» روی گوشیِ عمودی بازی نمی‌شود
 * =============================================================================
 *
 * چیدمانِ این بازی یک قیدِ هندسی دارد که با هیچ ترفندِ CSS ای حل نمی‌شود:
 * مصراع باید *وسطِ* مدار بنشیند، و مدار باید دورش جا داشته باشد. روی گوشیِ
 * عمودی عرضِ مفید حدودِ ۳۵۸ پیکسل است:
 *
 *     تابلویی که یک مصراعِ ۵۰ نویسه‌ای را خوانا نگه دارد  ≥ ۱۶۰px
 *     ستارهٔ یک واژهٔ بلند                                  ≈ ۸۵px
 *     پس حلقه‌ای که تابلو را در بر بگیرد                     ≥ ۱۵۰px شعاع
 *     ولی نصفِ عرضِ موجود                                    ≈ ۱۳۵px
 *
 * یعنی یا ستاره می‌رود روی متن، یا متن آن‌قدر کوچک می‌شود که خوانده نشود.
 *
 * نسخهٔ قبلی راهِ سومی رفت: روی گوشی تابلو را از مدار جدا کرد و گذاشت
 * بالایش. جا می‌شد، ولی دیگر «شکار نقش‌ها» نبود — یک فهرستِ واژه بود زیرِ
 * یک مصراع. حالا به‌جای شکستنِ چیدمان، از کاربر می‌خواهیم گوشی را بچرخاند.
 *
 * =============================================================================
 * ⚠️ چرا `screen.orientation.lock()` استفاده نمی‌شود
 * =============================================================================
 *
 * چون روی iOS Safari اصلاً وجود ندارد و روی اندروید هم فقط در حالتِ
 * تمام‌صفحه کار می‌کند. رفتارِ اصلی نباید به چیزی تکیه کند که روی نصفِ
 * دستگاه‌ها بی‌صداست؛ پس تشخیص کاملاً با `matchMedia` است — که همه‌جا هست.
 *
 * =============================================================================
 * ⚠️ «گوشی» با عرضِ خام تشخیص داده نمی‌شود
 * =============================================================================
 *
 * یک پنجرهٔ باریکِ مرورگر روی لپ‌تاپ هم عرضِ کم دارد، و نشان دادنِ «گوشی را
 * بچرخان» به کسی که ماوس دستش است، یک بن‌بست است — او نمی‌تواند بچرخاند.
 *
 * پس شرط ترکیبی است: عرضِ کم **و** اشاره‌گرِ درشت (`pointer: coarse`، یعنی
 * انگشت و نه ماوس). تبلت هم بیرون می‌ماند: ۳۴rem برابرِ ۵۴۴ پیکسل است و
 * باریک‌ترین تبلتِ رایج ۶۰۰ پیکسل عرض دارد، در حالی که پهن‌ترین گوشیِ رایج
 * (iPhone Pro Max) ۴۳۰ است.
 */

/** گوشیِ عمودی — تنها حالتی که بازی در آن قفل می‌شود. */
const PORTRAIT_PHONE =
  "(orientation: portrait) and (max-width: 34rem) and (pointer: coarse)";

/**
 * گوشی، در هر جهتی.
 *
 * ⚠️ در حالتِ افقی عرض بزرگ می‌شود (۸۴۴ پیکسل روی آیفون)، پس اینجا
 * *ارتفاع* سنجیده می‌شود و نه عرض. تبلتِ افقی ۷۶۸ پیکسل ارتفاع دارد و
 * بیرون می‌ماند؛ گوشیِ افقی حدودِ ۳۹۰.
 */
const PHONE_ANY =
  "(pointer: coarse) and ((max-width: 34rem) or (max-height: 34rem))";

export type RoleHuntOrientation = {
  /** دستگاه گوشی‌مانند است (صفحهٔ کوچک + اشاره‌گرِ درشت). */
  phone: boolean;
  /** گوشی است و عمودی گرفته شده — بازی باید قفل شود. */
  blocked: boolean;
};

/* ⚠️ یک store مشترک و نه یک شنونده به‌ازای هر کامپوننت.
   همان الگوی `lib/perf/use-perf.ts`: `useSyncExternalStore` مقدار را در
   *همان رندرِ اول* درست می‌دهد، در حالی که `useState` + `useEffect` یک
   فریم با مقدارِ غلط رندر می‌کرد — یعنی بازی یک لحظه زیرِ پوششِ «گوشی را
   بچرخان» ظاهر می‌شد و بعد می‌رفت. */
function subscribe(onChange: () => void): () => void {
  const a = window.matchMedia(PORTRAIT_PHONE);
  const b = window.matchMedia(PHONE_ANY);
  a.addEventListener("change", onChange);
  b.addEventListener("change", onChange);
  return () => {
    a.removeEventListener("change", onChange);
    b.removeEventListener("change", onChange);
  };
}

/* ⚠️ شیءِ نتیجه باید cache شود.
   `getSnapshot` بین دو رندرِ بی‌تغییر باید *همان* مرجع را بدهد، وگرنه React
   هر بار تغییر می‌بیند و بی‌نهایت رندر می‌کند. پس فقط وقتی شیءِ تازه ساخته
   می‌شود که یکی از دو مقدار واقعاً عوض شده باشد. */
let cached: RoleHuntOrientation = { phone: false, blocked: false };

function snapshot(): RoleHuntOrientation {
  const phone = window.matchMedia(PHONE_ANY).matches;
  const blocked = window.matchMedia(PORTRAIT_PHONE).matches;
  if (cached.phone !== phone || cached.blocked !== blocked) {
    cached = { phone, blocked };
  }
  return cached;
}

/** روی سرور نه صفحه‌ای هست و نه اشاره‌گری؛ «گوشی نیست» تنها فرضِ امن است.
 *  اگر اینجا چیزِ دیگری می‌گفتیم، HTMLِ سرور با اولین رندرِ مرورگر نمی‌خواند. */
const SERVER: RoleHuntOrientation = { phone: false, blocked: false };

function serverSnapshot(): RoleHuntOrientation {
  return SERVER;
}

export function useRoleHuntOrientation(): RoleHuntOrientation {
  return useSyncExternalStore(subscribe, snapshot, serverSnapshot);
}
