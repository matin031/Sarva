/**
 * قاعده‌های عضویت در کلاس — منطقِ خالص، بدونِ دیتابیس.
 *
 * ⚠️ چرا فایلِ جدا و نه داخلِ `lib/teacher/classes.ts`:
 *
 * همان الگوی `doc-paths.ts` و `analytics-rules.ts`. آن ماژول
 * `"server-only"` است و هیچ تستی نمی‌تواند واردش کند.
 *
 * ⚠️⚠️ ولی دلیلِ مهم‌ترِ این جدایی چیزِ دیگری است: این قاعده در **دو جا**
 * اجرا می‌شود — یک بار در پیش‌نمایش («می‌توانی عضو شوی؟») و یک بار در خودِ
 * عضویت. اگر دو پیاده‌سازیِ جدا داشتند، روزی از هم جدا می‌افتادند و نتیجه‌اش
 * بدترین شکلِ ممکن بود: دکمه‌ای که می‌گوید «تأیید و عضویت» و بعد خطا
 * می‌دهد، یا بدتر، پیش‌نمایشی که «نمی‌شود» می‌گوید ولی mutation می‌پذیرد.
 *
 * یک تابع، دو فراخوان.
 */

/**
 * وضعیتِ یک ردیفِ `class_members`.
 *
 * ⚠️ باید مو‌به‌مو با `class_members_status_check` در مهاجرت ۰۱۴ یکی باشد.
 *
 *   active  — عضوِ فعال.
 *   removed — **خودش** رفته. با کدِ معتبر برمی‌گردد.
 *   blocked — **دبیر** بیرونش گذاشته. تا وقتی دبیر اجازه ندهد برنمی‌گردد.
 *
 * تفاوتِ دو تای آخر کلِ دلیلِ وجودِ مهاجرت ۰۱۴ است: پیش از آن هر دو
 * `removed` بودند و اخراج‌شده با همان کد بلافاصله برمی‌گشت.
 */
export const MEMBERSHIP_STATUSES = ["active", "removed", "blocked"] as const;

export type MembershipStatus = (typeof MEMBERSHIP_STATUSES)[number];

/**
 * پیامِ «کد پیدا نشد».
 *
 * ⚠️ یک ثابت، چون باید در همهٔ مسیرها **دقیقاً یکی** باشد: کدِ ناموجود،
 * کدِ بدشکل، و کدِ کلاسی که حذف شده. اگر پیام‌ها فرق داشتند، کسی که کد
 * حدس می‌زند از روی تفاوتشان می‌فهمید کدام الگوها واقعی‌اند.
 */
export const NO_SUCH_CODE = "کدی با این مشخصات پیدا نشد.";

export type JoinGateInput = {
  /** کلاس بایگانی نشده؟ */
  isActive: boolean;
  /** دبیر عضوگیری را باز گذاشته؟ */
  joinEnabled: boolean;
  /** خودِ دبیرِ همین کلاس است؟ */
  isOwnClass: boolean;
  /** ردیفِ عضویتِ موجود، یا `null`. */
  membership: MembershipStatus | null;
};

export type JoinGate =
  | { ok: true; alreadyActive: boolean }
  | { ok: false; error: string };

/**
 * «آیا این نفر همین حالا می‌تواند عضوِ این کلاس شود؟»
 *
 * ترتیبِ بررسی‌ها عمدی است و از خصوصی‌ترین به عمومی‌ترین می‌رود:
 *
 *   ۱) **بلاک** اول از همه. دانش‌آموزی که دبیر بیرونش گذاشته نباید از
 *      «کلاس بایگانی شده» یا «عضوگیری بسته است» سر دربیاورد — این‌ها
 *      حالتِ کلاس‌اند و ربطی به او ندارند، و گفتنشان یعنی او فکر کند
 *      مشکل موقتی است و فردا دوباره امتحان کند.
 *   ۲) از قبل عضوِ فعال → موفقیتِ بی‌اثر و نه خطا.
 *   ۳) بعد وضعیتِ خودِ کلاس.
 *
 * ⚠️ «از قبل عضوی» یک **موفقیت** است. دانش‌آموزی که کد را دو بار وارد
 * کرده، نتیجه‌اش همان است که می‌خواست؛ خطا دادن فقط او را نگران می‌کند که
 * کاری اشتباه کرده.
 */
export function joinGate(input: JoinGateInput): JoinGate {
  if (input.membership === "blocked") {
    return {
      ok: false,
      /* ⚠️ لحن. «اخراج شده‌ای» یک جملهٔ تحقیرآمیز است که یک نوجوان روی
         صفحه می‌خواند. این جمله همان واقعیت را می‌گوید و راهِ ادامه را هم
         نشان می‌دهد. */
      error: "عضویت شما در این کلاس پایان یافته است. برای بازگشت با دبیرتان هماهنگ کنید.",
    };
  }

  if (input.membership === "active") {
    return { ok: true, alreadyActive: true };
  }

  if (input.isOwnClass) {
    /* دبیر نمی‌تواند عضوِ کلاسِ خودش شود: بعدش در فهرستِ اعضا ظاهر می‌شود و
       «عملکردِ دانش‌آموزان» کارنامهٔ خودِ دبیر را هم نشان می‌دهد. */
    return { ok: false, error: "این کلاسِ خودتان است." };
  }

  if (!input.isActive) {
    return { ok: false, error: "این کلاس بایگانی شده است." };
  }

  if (!input.joinEnabled) {
    /* ⚠️ این پیام عمداً با «کد پیدا نشد» فرق دارد: کسی که کدِ درست دارد
       باید بداند مشکل از او نیست. کسی که کد حدس می‌زند هم از این چیزی
       نمی‌فهمد جز اینکه یک کلاسِ واقعی هست — و آن را از خودِ پیش‌نمایش هم
       می‌فهمید. */
    return { ok: false, error: "دبیر این کلاس فعلاً عضو تازه نمی‌پذیرد." };
  }

  return { ok: true, alreadyActive: false };
}

/**
 * وضعیتی که پس از خروج باید نوشته شود.
 *
 * ⚠️ کلِ تفاوتِ «خودش رفت» و «بیرونش کردند» در همین یک خط است، و جدا
 * نگه داشتنش یعنی هیچ‌وقت جایی تصادفاً برعکس نوشته نشود.
 */
export function exitStatus(by: "student" | "teacher"): MembershipStatus {
  return by === "teacher" ? "blocked" : "removed";
}
