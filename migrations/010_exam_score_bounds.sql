-- =============================================================================
-- ۰۰۵ — مرزهای نمره در کارنامهٔ آزمون
-- =============================================================================
--
-- تا امروز `submitExamAttempt` نمره را از `questionResults`ی که کلاینت
-- می‌فرستاد جمع می‌زد. یعنی هر دانش‌آموزی می‌توانست همان Server Action را
-- دستی صدا بزند و کارنامه‌ای با نمرهٔ دلخواه بسازد. آن حفره در
-- `app/exam/[examKey]/actions.ts` بسته شد: نمره حالا روی سرور و از روی برگهٔ
-- واقعی دوباره حساب می‌شود.
--
-- این migration لایهٔ دوم است. اگر روزی مسیر دیگری برای نوشتن در این جدول باز
-- شد — یک اسکریپت، یک اکشن تازه، یا اشتباهی در همان تابع — دیتابیس خودش جلوی
-- ردیفِ بی‌معنی را می‌گیرد:
--
--   • نمرهٔ منفی معنا ندارد.
--   • برگه‌ای با سقفِ صفر یعنی هیچ سؤالی شمرده نشده؛ چنین کارنامه‌ای نباید ثبت شود.
--   • نمره نمی‌تواند از سقفِ همان برگه بیشتر باشد.
--
-- ⚠️ اگر ردیف‌های قدیمی‌ای وجود دارند که این شرط‌ها را نقض می‌کنند (مثلاً از
--    همان دورهٔ آسیب‌پذیر)، `add constraint` شکست می‌خورد. عمداً `not valid`
--    نگذاشته‌ام: بهتر است migration سر و صدا کند تا کسی آن ردیف‌ها را ببیند و
--    تصمیم بگیرد، نه اینکه بی‌صدا از کنارشان رد شود.
--    برای دیدنشان پیش از اجرا:
--      select id, user_id, total_score, max_score from exam_attempts
--       where total_score < 0 or max_score <= 0 or total_score > max_score;

alter table exam_attempts
  add constraint exam_attempts_total_score_nonneg check (total_score >= 0),
  add constraint exam_attempts_max_score_positive check (max_score > 0),
  add constraint exam_attempts_score_within_max check (total_score <= max_score);
